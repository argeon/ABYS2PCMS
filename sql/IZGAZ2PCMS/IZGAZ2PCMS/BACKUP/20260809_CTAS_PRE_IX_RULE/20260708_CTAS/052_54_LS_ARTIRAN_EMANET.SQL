-- oracleCTAS3007 / 54 — LS_ARTIRAN (arttiran tahakkuk) + LS_EMANET (ACCRUE=14)
-- Onkosul: O11 LS_INVOICE; emanet icin SMS.CS_ACCOUNT
-- Dogal ID; MAP/SRC_KEY yok

WHENEVER SQLERROR EXIT FAILURE
SET SERVEROUTPUT ON SIZE UNLIMITED

ALTER SESSION ENABLE PARALLEL DML;
ALTER SESSION ENABLE PARALLEL QUERY;
ALTER SESSION FORCE PARALLEL QUERY PARALLEL 56;
ALTER SESSION FORCE PARALLEL DML PARALLEL 56;

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE MIGRATION.LS_AGREEMENT_AUTO_PAYMENT_LOG PURGE';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE MIGRATION.LS_AGREEMENT_AUTO_PAYMENT_LOG
NOLOGGING
PARALLEL 56
AS
SELECT
    a.ID                                                    AS ID,
    a.ID                                                    AS ABYS_ID,
    a.AGREEMENT_ID                                          AS AGREEMENT_ID,
    a.BANK_ID                                               AS BANK_ID,
    a.INSTRUCTION_DATE                                      AS INSTRUCTION_DATE,
    a.CANCEL_DATE                                           AS CANCEL_DATE,
    a.DESCRIPTION                                           AS DESCRIPTION,
    a.CREATED_USER_ID                                       AS CREATED_USER_ID,
    CAST(a.CREATED_TIMESTAMP AS TIMESTAMP)                  AS CREATED_TIMESTAMP,
    a.UPDATED_USER_ID                                       AS UPDATED_USER_ID,
    CAST(a.UPDATED_TIMESTAMP AS TIMESTAMP)                  AS UPDATED_TIMESTAMP,
    a.VERSION                                               AS VERSION,
    a.CANCEL_USER_ID                                        AS CANCEL_USER_ID
FROM SMS.CS_AGREEMENT_AUTO_PAYMENT_LOG a
;

ALTER TABLE MIGRATION.LS_AGREEMENT_AUTO_PAYMENT_LOG NOPARALLEL LOGGING;

CREATE UNIQUE INDEX MIGRATION.UX_LS_AAPL_ID
    ON MIGRATION.LS_AGREEMENT_AUTO_PAYMENT_LOG (ID) NOLOGGING PARALLEL 4;

CREATE UNIQUE INDEX MIGRATION.UX_LS_AAPL_ABYS_ID
    ON MIGRATION.LS_AGREEMENT_AUTO_PAYMENT_LOG (ABYS_ID) NOLOGGING PARALLEL 4;

CREATE INDEX MIGRATION.IDX_LS_AAPL_AGR
    ON MIGRATION.LS_AGREEMENT_AUTO_PAYMENT_LOG (AGREEMENT_ID) NOLOGGING PARALLEL 4;

CREATE INDEX MIGRATION.IDX_LS_AAPL_BANK
    ON MIGRATION.LS_AGREEMENT_AUTO_PAYMENT_LOG (BANK_ID) NOLOGGING PARALLEL 4;

CREATE INDEX MIGRATION.IDX_LS_AAPL_CANCEL_USER
    ON MIGRATION.LS_AGREEMENT_AUTO_PAYMENT_LOG (CANCEL_USER_ID) NOLOGGING PARALLEL 4;

CREATE INDEX MIGRATION.IDX_LS_AAPL_INSTR
    ON MIGRATION.LS_AGREEMENT_AUTO_PAYMENT_LOG (INSTRUCTION_DATE) NOLOGGING PARALLEL 4;

CREATE INDEX MIGRATION.IDX_LS_AAPL_CANCEL
    ON MIGRATION.LS_AGREEMENT_AUTO_PAYMENT_LOG (CANCEL_DATE) NOLOGGING PARALLEL 4;

ALTER INDEX MIGRATION.UX_LS_AAPL_ID          NOPARALLEL;
ALTER INDEX MIGRATION.UX_LS_AAPL_ABYS_ID     NOPARALLEL;
ALTER INDEX MIGRATION.IDX_LS_AAPL_AGR         NOPARALLEL;
ALTER INDEX MIGRATION.IDX_LS_AAPL_BANK        NOPARALLEL;
ALTER INDEX MIGRATION.IDX_LS_AAPL_CANCEL_USER NOPARALLEL;
ALTER INDEX MIGRATION.IDX_LS_AAPL_INSTR       NOPARALLEL;
ALTER INDEX MIGRATION.IDX_LS_AAPL_CANCEL      NOPARALLEL;

BEGIN
  DBMS_STATS.GATHER_TABLE_STATS(
    'MIGRATION', 'LS_AGREEMENT_AUTO_PAYMENT_LOG', cascade => TRUE, degree => 56);
END;

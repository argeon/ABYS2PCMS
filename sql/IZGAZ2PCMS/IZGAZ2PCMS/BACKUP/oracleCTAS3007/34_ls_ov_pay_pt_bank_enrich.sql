-- PAID + banka/makbuz/tarih/kanal — PDML 56
ALTER TABLE MIGRATION.LS_OV_PAY_PT PARALLEL 56;
MERGE /*+ ENABLE_PARALLEL_DML PARALLEL(p 56) PARALLEL(s 56) */
 INTO MIGRATION.LS_OV_PAY_PT p
USING (
  SELECT /*+ PARALLEL(56) */
      pt.ROWID AS RID,
      act.BANK_ID AS BANKREF,
      CAST(SUBSTR(NVL(act.BANK_RECEIPT_NUMBER, TO_CHAR(act.RECEIPT_NUMBER)), 1, 50)
           AS VARCHAR2(50)) AS BANK_RECORD_REF
  FROM MIGRATION.LS_OV_PAY_PT pt
  LEFT JOIN SMS.CS_ACCOUNT_ACTION act ON act.ID = pt.ABYS_ID
) s
ON (p.ROWID = s.RID)
WHEN MATCHED THEN UPDATE SET
  p.PAID = CASE WHEN NVL(p.CANCELED, 0) = 0 THEN p.PAYABLETOTAL ELSE 0 END,
  p.BANKREF = COALESCE(s.BANKREF, p.BANKREF),
  p.BANK_RECORD_REF = COALESCE(s.BANK_RECORD_REF, p.BANK_RECORD_REF),
  p.LASTPAIDDATE = CASE WHEN NVL(p.CANCELED, 0) = 0 THEN p.DATE_ ELSE p.LASTPAIDDATE END,
  /* O30 XTYPE = PayType kanali; yoksa 1 */
  p.XTYPE = NVL(p.XTYPE, 1);

COMMIT;
ALTER TABLE MIGRATION.LS_OV_PAY_PT NOPARALLEL;


ALTER TABLE MIGRATION.LS_OV_DEBT_PAID_UPD PARALLEL 56;
MERGE /*+ ENABLE_PARALLEL_DML PARALLEL(d 56) PARALLEL(lp 56) */
 INTO MIGRATION.LS_OV_DEBT_PAID_UPD d
USING (
  SELECT /*+ PARALLEL(56) */ CROSSREF_MAIN_LREF AS MAIN_LREF,
         BANKREF, BANK_RECORD_REF,
         ROW_NUMBER() OVER (
           PARTITION BY CROSSREF_MAIN_LREF
           ORDER BY DATE_ DESC NULLS LAST, ABYS_ID DESC
         ) RN
    FROM MIGRATION.LS_OV_PAY_PT
   WHERE NVL(CANCELED,0)=0 AND OV_KIND='PAY' AND CROSSREF_MAIN_LREF IS NOT NULL
) lp
ON (d.MAIN_LREF = lp.MAIN_LREF AND lp.RN = 1)
WHEN MATCHED THEN UPDATE SET
  d.BANKREF = COALESCE(lp.BANKREF, d.BANKREF),
  d.BANK_RECORD_REF = COALESCE(lp.BANK_RECORD_REF, d.BANK_RECORD_REF),
  d.XTYPE = NVL(d.XTYPE, 1);

COMMIT;
ALTER TABLE MIGRATION.LS_OV_DEBT_PAID_UPD NOPARALLEL;


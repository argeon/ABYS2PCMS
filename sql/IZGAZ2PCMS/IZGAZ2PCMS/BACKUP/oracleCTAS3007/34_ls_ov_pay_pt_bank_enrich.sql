ALTER TABLE MIGRATION.LS_OV_TAH_INVOICE PARALLEL 56;
MERGE /*+ ENABLE_PARALLEL_DML PARALLEL(t 56) PARALLEL(s 56) */
 INTO MIGRATION.LS_OV_TAH_INVOICE t
USING (
  SELECT /*+ PARALLEL(56) */
      tah.ROWID AS RID,
      pt.BANKREF,
      pt.BANK_RECORD_REF,
      CASE WHEN NVL(pt.CANCELED, 0) = 0 THEN pt.DATE_ ELSE CAST(NULL AS DATE) END AS LASTPAIDDATE
  FROM MIGRATION.LS_OV_TAH_INVOICE tah
  INNER JOIN MIGRATION.LS_OV_PAY_PT pt
    ON pt.INVOICEREF = tah.LREF
   AND pt.ALLOC_RN = 1
) s
ON (t.ROWID = s.RID)
WHEN MATCHED THEN UPDATE SET
  t.BANKREF = COALESCE(s.BANKREF, t.BANKREF),
  t.BANK_RECORD_REF = COALESCE(s.BANK_RECORD_REF, t.BANK_RECORD_REF),
  t.LASTPAIDDATE = COALESCE(s.LASTPAIDDATE, t.LASTPAIDDATE);

COMMIT;
ALTER TABLE MIGRATION.LS_OV_TAH_INVOICE NOPARALLEL;

DECLARE
  n NUMBER; n_paid NUMBER; n_bank NUMBER; n_tah_bank NUMBER;
BEGIN
  SELECT COUNT(*),
         COUNT(CASE WHEN NVL(PAID,0) > 0.01 THEN 1 END),
         COUNT(CASE WHEN BANKREF IS NOT NULL THEN 1 END)
    INTO n, n_paid, n_bank
    FROM MIGRATION.LS_OV_PAY_PT
   WHERE NVL(CANCELED,0)=0 AND OV_KIND='PAY';
  SELECT COUNT(CASE WHEN BANKREF IS NOT NULL THEN 1 END)
    INTO n_tah_bank
    FROM MIGRATION.LS_OV_TAH_INVOICE
   WHERE NVL(CANCELED,0)=0;
  MIGRATION.P_MIG_CTAS_LOG('O34', 'pay_pt_bank_paid', 'OK', n,
    'pay=' || n || ' paid_gt0=' || n_paid || ' bank=' || n_bank
    || ' tah_bank=' || n_tah_bank);
  DBMS_OUTPUT.PUT_LINE('========== O34 PAY_PT+TAH ENRICH OK | n=' || n
    || ' paid=' || n_paid || ' bank=' || n_bank
    || ' tah_bank=' || n_tah_bank || ' ==========');
END;

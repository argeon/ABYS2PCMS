    ON MIGRATION.LS_INSTALLMENT (REGISTER_ID) NOLOGGING PARALLEL 4;

CREATE INDEX MIGRATION.IDX_LS_INST_INS
    ON MIGRATION.LS_INSTALLMENT (INSTALLATION_ID) NOLOGGING PARALLEL 4;

CREATE INDEX MIGRATION.IDX_LS_INST_TYPE
    ON MIGRATION.LS_INSTALLMENT (INSTALLMENT_TYPE_ID) NOLOGGING PARALLEL 4;

CREATE INDEX MIGRATION.IDX_LS_INST_CANCEL
    ON MIGRATION.LS_INSTALLMENT (CANCELLATION_DATE, LEGAL_PROCEEDING_ID) NOLOGGING PARALLEL 4;

ALTER INDEX MIGRATION.UX_LS_INST_ID      NOPARALLEL;

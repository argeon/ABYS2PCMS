SELECT 'CS_INSTALLMENT' KAYNAK, COUNT(*) CNT FROM SMS.CS_INSTALLMENT
UNION ALL
SELECT 'LS_INSTALLMENT', COUNT(*) FROM MIGRATION.LS_INSTALLMENT
UNION ALL
SELECT 'LS_INSTALLMENT_ACTIVE', COUNT(*) FROM MIGRATION.LS_INSTALLMENT WHERE CANCELLATION_DATE IS NULL
UNION ALL
SELECT 'LS_INSTALLMENT_CANCELLED', COUNT(*) FROM MIGRATION.LS_INSTALLMENT WHERE CANCELLATION_DATE IS NOT NULL;

CREATE TABLE MIGRATION.LS_OV_GUVENCE_IADE_INVLINES NOLOGGING PARALLEL 56 AS
SELECT /*+ PARALLEL(56) */ * FROM (
  SELECT
      CAST('GUV_IADE_IL|' || TO_CHAR(inv.ABYS_ACCOUNT_ID) || '|' || TO_CHAR(ln.INCOME_ID)
           AS VARCHAR2(80))                                      AS SRC_KEY,
      CAST(NULL AS NUMBER(12))                                   AS LREF_HINT,
      inv.SRC_KEY                                                AS INVOICE_SRC_KEY,
      inv.CLIENTREF,
      inv.DATE_,
      CAST(110 AS NUMBER(3))                                     AS TYPE,
      CAST(ROW_NUMBER() OVER (PARTITION BY inv.ABYS_ACCOUNT_ID
                              ORDER BY ln.INCOME_ID) AS NUMBER(5)) AS LINENR,
      CAST(ln.INCOME_ID AS NUMBER(10))                           AS TRANSTYPE,
      CAST(ABS(ln.NET) AS NUMBER(18,3))                          AS AMOUNT,
      CAST(ABS(ln.NET) AS NUMBER(18,3))                          AS TLTOTAL,
      CAST(0 AS NUMBER(18,3))                                    AS TAX,
      CAST(ABS(ln.NET) AS NUMBER(18,3))                          AS GRANDTOTAL,
      CAST(CASE ln.INCOME_ID
             WHEN 162  THEN 'GÜVENCE BEDELİ'
             WHEN 1936 THEN 'GÜVENCE FARK BEDELİ'
             ELSE 'Guvence Bedeli İade'
           END AS VARCHAR2(100))                                 AS LINEEXP,
      CAST(ln.INCOME_ID AS NUMBER(10))                           AS ABYS_INCOME_ID,
      CAST(823 AS NUMBER(10))                                    AS PCMS_INCOME_CODE, -- 823 Guvence Bedeli İade
      CAST(NULL AS NUMBER(12))                                   AS ABYS_ID,
      inv.ABYS_TEDIYE_ACTION_ID                                  AS ABYS_TEDIYE_ACTION_ID,
      inv.ABYS_AGREEMENT_ID,
      inv.ABYS_ACCOUNT_ID,
      CAST('GUV_IADE' AS VARCHAR2(10))                           AS OV_KIND
  FROM MIGRATION.LS_OV_GUVENCE_IADE_INVOICE inv
  JOIN (
    SELECT aa.ACCOUNT_ID,
           ai.INCOME_ID,
           ROUND(SUM(ai.AMOUNT * ai.STATUS), 2) AS NET
      FROM SMS.CS_ACCOUNT_ACTION aa
      JOIN SMS.CS_ACCOUNT_INCOME ai ON ai.ACCOUNT_ACTION_ID = aa.ID
      JOIN MIGRATION.STG_GUV_IADE_PIVOT p ON p.ACCOUNT_ID = aa.ACCOUNT_ID
     WHERE aa.ACTION_TYPE_ID IN (40, 11, 29)
       AND ai.INCOME_ID IN (
             162, 163, 164, 165, 1936, 3198, 3199,
             7649, 7650, 7651, 7652, 12531, 23032
           )
     GROUP BY aa.ACCOUNT_ID, ai.INCOME_ID
    HAVING ABS(SUM(ai.AMOUNT * ai.STATUS)) > 0.02
  ) ln ON ln.ACCOUNT_ID = inv.ABYS_ACCOUNT_ID
  UNION ALL
  /* tip40 gelir satiri yoksa tek 823 satiri */
  SELECT
      CAST('GUV_IADE_IL|' || TO_CHAR(inv.ABYS_ACCOUNT_ID) || '|823' AS VARCHAR2(80)),
      CAST(NULL AS NUMBER(12)),
      inv.SRC_KEY,
      inv.CLIENTREF,
      inv.DATE_,
      CAST(110 AS NUMBER(3)),
      CAST(1 AS NUMBER(5)),
      CAST(823 AS NUMBER(10)),
      inv.TLTOTAL,
      inv.TLTOTAL,
      CAST(0 AS NUMBER(18,3)),
      inv.TLTOTAL,
      CAST('Guvence Bedeli İade' AS VARCHAR2(100)),
      CAST(823 AS NUMBER(10)),
      CAST(823 AS NUMBER(10)),
      CAST(NULL AS NUMBER(12)),
      inv.ABYS_TEDIYE_ACTION_ID,
      inv.ABYS_AGREEMENT_ID,
      inv.ABYS_ACCOUNT_ID,
      CAST('GUV_IADE' AS VARCHAR2(10))
  FROM MIGRATION.LS_OV_GUVENCE_IADE_INVOICE inv
  WHERE NOT EXISTS (
    SELECT 1
      FROM SMS.CS_ACCOUNT_ACTION aa
      JOIN SMS.CS_ACCOUNT_INCOME ai ON ai.ACCOUNT_ACTION_ID = aa.ID
     WHERE aa.ACCOUNT_ID = inv.ABYS_ACCOUNT_ID
       AND aa.ACTION_TYPE_ID IN (40, 11, 29)
       AND ai.INCOME_ID IN (
             162, 163, 164, 165, 1936, 3198, 3199,
             7649, 7650, 7651, 7652, 12531, 23032
           )
       AND ABS(ai.AMOUNT * ai.STATUS) > 0.02
  )
);


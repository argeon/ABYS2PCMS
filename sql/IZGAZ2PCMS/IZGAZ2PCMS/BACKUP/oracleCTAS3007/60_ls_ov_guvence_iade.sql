    CASE
      WHEN p.IADE_DATE IS NULL THEN CAST(NULL AS DATE)
      WHEN p.IADE_DATE < DATE '1900-01-01' THEN DATE '1900-01-01'
      WHEN p.IADE_DATE > DATE '2079-06-06' THEN DATE '2079-06-06'
      ELSE p.IADE_DATE
    END                                                          AS DATE_,
    CASE
      WHEN p.IADE_DATE IS NULL THEN CAST(NULL AS DATE)
      WHEN p.IADE_DATE < DATE '1900-01-01' THEN DATE '1900-01-01'
      WHEN p.IADE_DATE > DATE '2079-06-06' THEN DATE '2079-06-06'
      ELSE p.IADE_DATE
    END                                                          AS DUEDATE,
    CAST(110 AS NUMBER(3))                                       AS TYPE,            -- GÜVENCE BEDELİ İADE
    CAST(NVL(p.REGISTER_ID, 0) AS NUMBER(12))                    AS CLIENTREF,
    CAST(p.TLTOTAL_110 AS NUMBER(18,3))                          AS TLTOTAL,
    CAST(160 AS NUMBER(5))                                       AS CURID,
    CAST(p.TLTOTAL_110 AS NUMBER(18,3))                          AS CURTOTAL,
    CAST(UPPER(TO_CHAR(NVL(p.FITNO, 0)) || ' Mahsuplaşma sonrası kalan bedel')
         AS VARCHAR2(250))                                       AS EXPLAIN,
    CAST(0 AS NUMBER(1))                                         AS CANCELED,
    CAST(p.AGREEMENT_ID AS NUMBER(12))                           AS OWNERREF,
    CAST(91 AS NUMBER(3))                                        AS OWNERTYPE,       -- AGR
    CAST(0 AS NUMBER(18,3))                                      AS TAX,
    CAST(0 AS NUMBER(18,3))                                      AS DV,
    CAST(p.TLTOTAL_110 AS NUMBER(18,3))                          AS GRANDTOTAL,
    CAST(0 AS NUMBER(10))                                        AS PRINTCOUNT,
    CAST(p.TLTOTAL_110 AS NUMBER(18,3))                          AS PAYABLETOTAL,
    CAST(1 AS NUMBER(1))                                         AS CLOSED,
    CAST(NULL AS NUMBER(12))                                     AS RETURN_SOURCE_INVREF,
    CAST(NULL AS NUMBER(12))                                     AS RETURN_TARGET_INVREF,
    CAST(p.FITNO AS NUMBER(19))                                  AS FITNO,
    CAST(p.BN_TYPE AS NUMBER(10))                                AS BN_TYPE,
    CAST(p.TLTOTAL_110 AS NUMBER(18,3))                          AS AMOUNT,
    CAST(CASE WHEN p.IADE_DATE IS NULL THEN NULL
              ELSE TO_NUMBER(TO_CHAR(p.IADE_DATE, 'YYYYMM')) END AS NUMBER(10)) AS PERIOD,
    CAST(0 AS NUMBER(1))                                         AS HAS_DISCOUNT,
    CAST(0 AS NUMBER(18,3))                                      AS DISCOUNT_AMOUNT,
    CASE
      WHEN p.IADE_DATE IS NULL THEN CAST(NULL AS DATE)
      WHEN p.IADE_DATE < DATE '1900-01-01' THEN DATE '1900-01-01'
      WHEN p.IADE_DATE > DATE '2079-06-06' THEN DATE '2079-06-06'
      ELSE p.IADE_DATE
    END                                                          AS ADDDATE,
    CAST(NULL AS NUMBER(10))                                     AS ADDUSER,
    CAST(NVL(p.TEDIYE_ACTION_ID, p.ACCOUNT_ID) AS NUMBER(12))    AS ABYS_ID,
    CAST(p.ACCOUNT_ID AS NUMBER(12))                             AS ABYS_ACCOUNT_ID,
    CAST(NVL(p.TEDIYE_ACTION_TYPE_ID, 40) AS NUMBER(10))         AS ABYS_ACTION_TYPE_ID,
    CAST(p.AGREEMENT_ID AS NUMBER(12))                           AS ABYS_AGREEMENT_ID,
    CAST(p.ACCOUNT_ID AS NUMBER(12))                             AS ABYS_MAIN_LREF,   -- emanet hesabi
    CAST(p.TEDIYE_ACTION_ID AS NUMBER(12))                       AS ABYS_TEDIYE_ACTION_ID,
    CAST(p.TIP20_ACTION_ID AS NUMBER(12))                        AS ABYS_TIP20_ACTION_ID,
    CAST(p.TIP20 AS NUMBER(18,3))                                AS TIP20_NET,
    CAST(p.TIP12 AS NUMBER(18,3))                                AS TIP12_NET,
    CAST(p.TEDIYE AS NUMBER(18,3))                               AS TEDIYE_NET,
    CAST('GUV_IADE' AS VARCHAR2(10))                             AS OV_KIND
FROM MIGRATION.STG_GUV_IADE_PIVOT p;


CREATE TABLE MIGRATION.STG_GUV_IADE_PIVOT NOLOGGING PARALLEL 56 AS
SELECT /*+ PARALLEL(56) */
    CAST(p.ACCOUNT_ID AS NUMBER(12))                             AS ACCOUNT_ID,
    CAST(p.AGREEMENT_ID AS NUMBER(12))                           AS AGREEMENT_ID,
    CAST(p.REGISTER_ID AS NUMBER(12))                            AS REGISTER_ID,
    CAST(p.FITNO AS NUMBER(19))                                  AS FITNO,
    CAST(p.BN_TYPE AS NUMBER(10))                                AS BN_TYPE,
    CAST(ROUND(p.TIP20, 2) AS NUMBER(18,3))                      AS TIP20,
    CAST(ROUND(p.TIP12, 2) AS NUMBER(18,3))                      AS TIP12,
    CAST(ROUND(p.TEDIYE, 2) AS NUMBER(18,3))                     AS TEDIYE,
    CAST(ROUND(p.G162, 2) AS NUMBER(18,3))                       AS G162,
    CAST(ROUND(p.G1936, 2) AS NUMBER(18,3))                      AS G1936,
    CAST(ROUND(ABS(p.TEDIYE), 2) AS NUMBER(18,3))                AS TLTOTAL_110,
    p.IADE_DATE,
    CAST(p.TEDIYE_ACTION_ID AS NUMBER(12))                       AS TEDIYE_ACTION_ID,
    CAST(p.TEDIYE_ACTION_TYPE_ID AS NUMBER(10))                  AS TEDIYE_ACTION_TYPE_ID,
    CAST(p.TIP20_ACTION_ID AS NUMBER(12))                        AS TIP20_ACTION_ID
FROM (
  SELECT
      a.ID                                                       AS ACCOUNT_ID,
      a.AGREEMENT_ID,
      a.REGISTER_ID,
      i.INSTALLATION_NUMBER                                      AS FITNO,
      CAST(NULL AS NUMBER(10))                                   AS BN_TYPE,
      SUM(CASE WHEN aa.ACTION_TYPE_ID = 20
               THEN ai.AMOUNT * ai.STATUS ELSE 0 END)            AS TIP20,
      SUM(CASE WHEN aa.ACTION_TYPE_ID = 12
               THEN ai.AMOUNT * ai.STATUS ELSE 0 END)            AS TIP12,
      SUM(CASE WHEN aa.ACTION_TYPE_ID IN (40, 11, 29)
               THEN ai.AMOUNT * ai.STATUS ELSE 0 END)            AS TEDIYE,
      SUM(CASE WHEN aa.ACTION_TYPE_ID = 20 AND ai.INCOME_ID = 162
               THEN ai.AMOUNT * ai.STATUS ELSE 0 END)            AS G162,
      SUM(CASE WHEN aa.ACTION_TYPE_ID = 20 AND ai.INCOME_ID = 1936
               THEN ai.AMOUNT * ai.STATUS ELSE 0 END)            AS G1936,
      MAX(CASE WHEN aa.ACTION_TYPE_ID IN (40, 11, 29)
               THEN aa.ACTION_DATE END)                          AS IADE_DATE,
      MAX(CASE WHEN aa.ACTION_TYPE_ID IN (40, 11, 29)
               THEN aa.ID END)                                   AS TEDIYE_ACTION_ID,
      MAX(CASE WHEN aa.ACTION_TYPE_ID IN (40, 11, 29)
               THEN aa.ACTION_TYPE_ID END)                       AS TEDIYE_ACTION_TYPE_ID,
      MAX(CASE WHEN aa.ACTION_TYPE_ID = 20 THEN aa.ID END)       AS TIP20_ACTION_ID
  FROM SMS.CS_ACCOUNT a
  JOIN SMS.CS_ACCOUNT_ACTION aa ON aa.ACCOUNT_ID = a.ID
  JOIN SMS.CS_ACCOUNT_INCOME ai ON ai.ACCOUNT_ACTION_ID = aa.ID
  JOIN SMS.CS_AGREEMENT ag ON ag.ID = a.AGREEMENT_ID
  LEFT JOIN SMS.CS_INSTALLATION i ON i.ID = ag.INSTALLATION_ID
  WHERE a.ACCRUE_TYPE_ID = 14
    AND ai.INCOME_ID IN (
          162, 163, 164, 165, 1936, 3198, 3199,
          7649, 7650, 7651, 7652, 12531, 23032
        )
    AND aa.ACTION_TYPE_ID IN (20, 12, 40, 11, 29)
    AND (
          NOT EXISTS (SELECT 1 FROM MIGRATION.MIG_PARAM p WHERE p.AGR_ID IS NOT NULL)
       OR a.AGREEMENT_ID IN (SELECT p.AGR_ID FROM MIGRATION.MIG_PARAM p WHERE p.AGR_ID IS NOT NULL)
        )
  GROUP BY a.ID, a.AGREEMENT_ID, a.REGISTER_ID, i.INSTALLATION_NUMBER
) p
WHERE ABS(NVL(p.TEDIYE, 0)) > 0.02;


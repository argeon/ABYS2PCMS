WHERE ABYS_ID IS NOT NULL
UNION ALL
SELECT
    'POST_BANKREF_NULL',
    COUNT(*)
FROM dbo.LS_BANK_ACC
WHERE ABYS_ID IS NOT NULL
  AND BANKREF IS NULL
UNION ALL
SELECT
    'POST_BANKREF_ORPHAN',
    COUNT(*)
FROM dbo.LS_BANK_ACC t
WHERE t.ABYS_ID IS NOT NULL
  AND t.BANKREF IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM dbo.LS_BANK b WHERE b.LREF = t.BANKREF);

SELECT TOP (20)
    t.LREF, t.ACCNO, t.IBAN, t.DEFN, t.BANKREF, t.LOGOCODE, t.ENT_ID,
    t.IS_INTERGRATION_BANK, t.ISACTIVE, t.VALOR,
    t.ABYS_ID, t.ABYS_BANK_ID, b.DEFN AS BANK_DEFN, b.ABYS_ID AS BANK_ABYS_ID
FROM dbo.LS_BANK_ACC t
LEFT JOIN dbo.LS_BANK b ON b.LREF = t.BANKREF
WHERE t.ABYS_ID IS NOT NULL
ORDER BY t.ABYS_ID;


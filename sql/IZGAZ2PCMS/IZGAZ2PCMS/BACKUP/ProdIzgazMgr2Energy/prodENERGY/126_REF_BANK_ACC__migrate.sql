--   ACCNO                 = COALESCE(BANK_ACCOUNT_NUMBER, CODE)
--   IBAN                  = BANK_ACCOUNT_NUMBER
--   BANKREF               = LS_BANK.LREF WHERE ABYS_ID = BANK_ID
--   LOGOCODE              = ACCOUNT_CODE
--   ENT_ID                = 4102
--   IS_INTERGRATION_BANK  = BANK_INTEGRATION_CODE IS NOT NULL
--   ISACTIVE              = IS_ACTIVE
--   VALOR                 = PAYMENT_RETURN_DAY
--   NR                    = 0
--   ABYS_*                = kaynak kolonlar
--
-- Idempotent: NOT EXISTS (ABYS_ID)
-- Önkoşul: 121_REF_BANK + 125_REF_BANK_ACC__setup
-- ============================================================

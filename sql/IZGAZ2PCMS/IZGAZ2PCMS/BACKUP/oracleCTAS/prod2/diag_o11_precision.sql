PROMPT ========== READING_ID NUMBER(12) ==========
SELECT
  SUM(CASE WHEN r.READING_ID IS NOT NULL AND ABS(r.READING_ID) >= 1E12 THEN 1 ELSE 0 END) AS BAD_READ,
  MAX(r.READING_ID) AS MAX_READ
FROM SMS.CS_ACCOUNT_ACTION aa
JOIN SMS.CS_ACCOUNT acc ON acc.ID = aa.ACCOUNT_ID
LEFT JOIN (
  SELECT ACCOUNT_ID, MAX(ID) AS READING_ID
  FROM SMS.CS_READING
  GROUP BY ACCOUNT_ID
) r ON r.ACCOUNT_ID = acc.ID
WHERE aa.ACTION_TYPE_ID IN (1, 3, 10, 41)
  AND NVL(acc.ACCRUE_TYPE_ID, -1) <> 14
  AND aa.ID BETWEEN 1 AND 2147483647;


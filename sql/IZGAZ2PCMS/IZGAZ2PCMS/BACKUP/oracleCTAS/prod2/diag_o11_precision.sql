PROMPT ========== NUMBER(1) flag adaylari (ABS>9 veya >1 digit) ==========
SELECT
  SUM(CASE WHEN acc.IS_E_BILL IS NOT NULL AND ABS(acc.IS_E_BILL) > 9 THEN 1 ELSE 0 END) AS BAD_IS_E_BILL,
  SUM(CASE WHEN acc.IS_FPS IS NOT NULL AND ABS(acc.IS_FPS) > 9 THEN 1 ELSE 0 END) AS BAD_IS_FPS,
  SUM(CASE WHEN acc.DO_DISCHARGE IS NOT NULL AND ABS(acc.DO_DISCHARGE) > 9 THEN 1 ELSE 0 END) AS BAD_DO_DISCHARGE,
  MAX(acc.IS_E_BILL) AS MAX_IS_E_BILL,
  MAX(acc.IS_FPS) AS MAX_IS_FPS,
  MAX(acc.DO_DISCHARGE) AS MAX_DO_DISCHARGE
FROM SMS.CS_ACCOUNT_ACTION aa
JOIN SMS.CS_ACCOUNT acc ON acc.ID = aa.ACCOUNT_ID
WHERE aa.ACTION_TYPE_ID IN (1, 3, 10, 41)
  AND NVL(acc.ACCRUE_TYPE_ID, -1) <> 14
  AND aa.ID BETWEEN 1 AND 2147483647;


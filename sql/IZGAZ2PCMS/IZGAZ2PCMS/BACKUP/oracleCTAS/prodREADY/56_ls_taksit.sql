CREATE TABLE MIGRATION.LS_TAKSIT NOLOGGING PARALLEL 56 AS
SELECT /*+ PARALLEL(56) */
    CAST(A.FATURAID AS NUMBER(12))                               AS FATURAID,
    CAST(A.SOZLESME_HESABI AS NUMBER(12))                        AS SOZLESME,
    CAST(A.BALANCE AS NUMBER(15,3))                              AS BALANCE,
    CAST(A.TAKSIT_DURUMU AS VARCHAR2(1))                         AS TAKSIT_DURUMU,
    CAST(A.INSTALLMENT_ID AS NUMBER(12))                         AS INSTALLMENT_ID,
    CAST(INV.LREF AS NUMBER(12))                                 AS MAIN_LREF,
    A.SNAPSHOT_DATE                                              AS SNAPSHOT_DATE
FROM MIGRATION.LS_AFL_OPEN_DEBT A
LEFT JOIN MIGRATION.LS_INVOICE INV
  ON INV.ABYS_ACCOUNT_ID = A.FATURAID
 AND INV.ABYS_ACTION_TYPE_ID = 1
 AND NVL(INV.CANCELED, 0) = 0
WHERE A.TAKSIT_DURUMU = 'T';

CREATE INDEX MIGRATION.IX_LS_TAKSIT_INST ON MIGRATION.LS_TAKSIT (INSTALLMENT_ID) PARALLEL 56 NOLOGGING;
CREATE INDEX MIGRATION.IX_LS_TAKSIT_AGR ON MIGRATION.LS_TAKSIT (SOZLESME) PARALLEL 56 NOLOGGING;
CREATE INDEX MIGRATION.IX_LS_TAKSIT_FAT ON MIGRATION.LS_TAKSIT (FATURAID) PARALLEL 56 NOLOGGING;

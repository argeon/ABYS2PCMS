CREATE TABLE MIGRATION.LS_STG_INV_PAY_CLOSE
NOLOGGING
PARALLEL 56
AS
SELECT /*+ PARALLEL(56) */
    CAST(inv.LREF AS NUMBER(12))                                 AS MAIN_LREF,
    CAST(NVL(pay.FATURAID, inv.ABYS_ACCOUNT_ID) AS NUMBER(12))   AS FATURAID,
    CAST(NVL(pay.SOZLESME, inv.ABYS_AGREEMENT_ID) AS NUMBER(12)) AS SOZLESME,
    CAST(ROUND(NVL(inv.PAYABLETOTAL, 0), 2) AS NUMBER(15,3))     AS PAYABLE_AMT,
    CAST(NVL(pay.OV_PAID_AMT, 0) AS NUMBER(15,3))                AS OV_PAID_AMT,
    CAST(NVL(pay.OV_PAY_CNT, 0) AS NUMBER(10))                   AS OV_PAY_CNT,
    pay.OV_LAST_PAY_DATE                                         AS OV_LAST_PAY_DATE,
    CAST(NVL(pay.OV_PAY_FULL_SUM, 0) AS NUMBER(15,3))            AS OV_PAY_FULL_SUM,
    CAST(debt.CLOSED AS NUMBER(1))                               AS OV_CLOSED,
    debt.LASTPAIDDATE                                            AS OV_LASTPAIDDATE,
    lp.LAST_PAYTYPE                                              AS LAST_PAYTYPE,
    lp.LAST_OV_KIND                                              AS LAST_OV_KIND,
    lp.LAST_PAY_LREF                                             AS LAST_PAY_LREF,
    lp.LAST_BANK_PAY_DATE                                        AS LAST_BANK_PAY_DATE,
    /* banka / vezne = kanal; USERID = islemi yapan kisi (ayri) */
    lp.BANKA_ID                                                  AS BANKA_ID,
    lp.BANKA_CODE                                                AS BANKA_CODE,
    lp.BANKA                                                     AS BANKA,
    lp.VEZNE_ID                                                  AS VEZNE_ID,
    lp.VEZNE_CODE                                                AS VEZNE_CODE,
    lp.VEZNE                                                     AS VEZNE,
    lp.USERID                                                    AS USERID,
    lp.UPDATED_USER_ID                                           AS UPDATED_USER_ID,
    lp.TAH_MAKBUZ_SERIAL                                         AS TAH_MAKBUZ_SERIAL,
    lp.TAH_MAKBUZ_NO                                             AS TAH_MAKBUZ_NO,
    lp.BANK_RECORD_REF                                           AS BANK_RECORD_REF,
    CAST(CASE WHEN afl.FATURAID IS NOT NULL THEN 1 ELSE 0 END
         AS NUMBER(1))                                           AS AFL_OPEN,
    CAST(afl.BALANCE AS NUMBER(15,3))                            AS AFL_BAL,
    CAST(0.50 AS NUMBER(15,3))                                   AS EPS_AMT,
    /* WANT_CLOSED: AFL acik → 0; aksi halde PAID≈PAYABLE (EPS) veya PAYABLE=0 */
    CAST(
      CASE
        WHEN afl.FATURAID IS NOT NULL THEN 0
        WHEN ABS(NVL(inv.PAYABLETOTAL, 0)) <= 0.01 THEN 1
        WHEN NVL(pay.OV_PAID_AMT, 0)
             >= ROUND(NVL(inv.PAYABLETOTAL, 0), 2) - 0.50
         AND ROUND(NVL(inv.PAYABLETOTAL, 0), 2) > 0.01
        THEN 1
        ELSE 0
      END AS NUMBER(1)
    )                                                            AS WANT_CLOSED,
    CASE
      WHEN afl.FATURAID IS NOT NULL THEN CAST(NULL AS DATE)
      WHEN debt.LASTPAIDDATE IS NOT NULL THEN debt.LASTPAIDDATE
      WHEN pay.OV_LAST_PAY_DATE IS NOT NULL THEN pay.OV_LAST_PAY_DATE
      WHEN lp.LAST_BANK_PAY_DATE IS NOT NULL THEN lp.LAST_BANK_PAY_DATE
      ELSE CAST(NULL AS DATE)
    END                                                          AS WANT_LPD,
    CAST(
      CASE
        WHEN afl.FATURAID IS NOT NULL THEN 'AFL_OPEN'
        WHEN NVL(pay.OV_PAY_CNT, 0) = 0
         AND ABS(NVL(inv.PAYABLETOTAL, 0)) <= 0.01
          THEN 'CLOSE_FULL'
        WHEN NVL(pay.OV_PAY_CNT, 0) = 0 THEN 'NO_PAY'
        WHEN NVL(pay.OV_PAID_AMT, 0)
             >= ROUND(NVL(inv.PAYABLETOTAL, 0), 2) - 0.01
          THEN 'CLOSE_FULL'
        WHEN NVL(pay.OV_PAID_AMT, 0)
             >= ROUND(NVL(inv.PAYABLETOTAL, 0), 2) - 0.50
          THEN 'CLOSE_EPS'
        ELSE 'KEEP_OPEN'
      END AS VARCHAR2(16)
    )                                                            AS FIX_KIND,
    CAST(
      ROUND(
        NVL(pay.OV_PAID_AMT, 0) - ROUND(NVL(inv.PAYABLETOTAL, 0), 2)
      , 2) AS NUMBER(15,3)
    )                                                            AS PAID_MINUS_PAYABLE,
    CAST(SYSDATE AS DATE)                                        AS SNAPSHOT_DATE
FROM MIGRATION.LS_INVOICE inv
LEFT JOIN MIGRATION.TMP_STG_PAY_AGG pay
  ON pay.MAIN_LREF = inv.LREF
LEFT JOIN MIGRATION.TMP_STG_PAY_LAST lp
  ON lp.MAIN_LREF = inv.LREF
LEFT JOIN MIGRATION.TMP_STG_DEBT debt
  ON debt.MAIN_LREF = inv.LREF
LEFT JOIN MIGRATION.LS_AFL_OPEN_DEBT afl
  ON afl.FATURAID = inv.ABYS_ACCOUNT_ID
 AND NVL(afl.MIG_IN_SCOPE, 1) = 1
WHERE NVL(inv.IOCODE, 0) = 0
  AND inv.ABYS_ACCOUNT_ID IS NOT NULL;

CREATE UNIQUE INDEX MIGRATION.IX_STG_IPC_MAIN
  ON MIGRATION.LS_STG_INV_PAY_CLOSE (MAIN_LREF) PARALLEL 56 NOLOGGING;
CREATE INDEX MIGRATION.IX_STG_IPC_FATURA

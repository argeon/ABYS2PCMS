    COUNT(*) AS STG_CNT,
    COUNT(CASE WHEN AFL_OPEN = 1 THEN 1 END) AS AFL_OPEN_CNT,
    COUNT(CASE WHEN WANT_CLOSED = 1 THEN 1 END) AS WANT_CLOSED_CNT,
    COUNT(CASE WHEN FIX_KIND = 'CLOSE_EPS' THEN 1 END) AS CLOSE_EPS_CNT,
    COUNT(CASE WHEN WANT_LPD IS NOT NULL THEN 1 END) AS WANT_LPD_CNT,
    COUNT(CASE WHEN LAST_BANK_PAY_DATE IS NOT NULL THEN 1 END) AS BANK_DATE_CNT,
    COUNT(CASE WHEN BANKA_ID IS NOT NULL THEN 1 END) AS BANKA_CNT,
    COUNT(CASE WHEN VEZNE_ID IS NOT NULL THEN 1 END) AS VEZNE_CNT,
    COUNT(CASE WHEN USERID IS NOT NULL THEN 1 END) AS USERID_CNT,
    COUNT(CASE WHEN UPDATED_USER_ID IS NOT NULL THEN 1 END) AS UPD_USER_CNT,
    COUNT(CASE WHEN USERID IS NOT NULL AND UPDATED_USER_ID IS NOT NULL
                AND USERID <> UPDATED_USER_ID THEN 1 END) AS USER_DIFF_CNT,
    COUNT(CASE WHEN TAH_MAKBUZ_NO IS NOT NULL THEN 1 END) AS MAKBUZ_CNT,
    COUNT(CASE WHEN BANK_RECORD_REF IS NOT NULL THEN 1 END) AS BANK_REF_CNT
FROM MIGRATION.LS_STG_INV_PAY_CLOSE;

DECLARE
  n_stg NUMBER; n_want NUMBER; n_eps NUMBER;
BEGIN
  SELECT COUNT(*),
         COUNT(CASE WHEN WANT_CLOSED = 1 THEN 1 END),
         COUNT(CASE WHEN FIX_KIND = 'CLOSE_EPS' THEN 1 END)
    INTO n_stg, n_want, n_eps
    FROM MIGRATION.LS_STG_INV_PAY_CLOSE;
  BEGIN
    MIGRATION.P_MIG_CTAS_LOG('O51', 'stg_inv_pay_close', 'OK', n_stg,
      'want_closed=' || n_want || ' close_eps=' || n_eps || ' dump→izgazMGR');
  EXCEPTION WHEN OTHERS THEN NULL;
  END;
  DBMS_OUTPUT.PUT_LINE('========== O51 OK | stg=' || n_stg
    || ' want_closed=' || n_want || ' close_eps=' || n_eps
    || ' | CTAS BITTI → dump LS_STG_INV_PAY_CLOSE ==========');
END;

CREATE TABLE MIGRATION.TMP_STG_PAY_AGG NOLOGGING PARALLEL 56 AS
SELECT /*+ PARALLEL(56) */
    p.CROSSREF_MAIN_LREF                                         AS MAIN_LREF,
    MAX(p.ABYS_ACCOUNT_ID)                                       AS FATURAID,
    MAX(p.ABYS_AGREEMENT_ID)                                     AS SOZLESME,
    CAST(ROUND(SUM(CASE WHEN NVL(p.CANCELED, 0) = 0
                        THEN p.PAYABLETOTAL ELSE 0 END), 2)
         AS NUMBER(15,3))                                        AS OV_PAID_AMT,
    CAST(SUM(CASE WHEN NVL(p.CANCELED, 0) = 0 THEN 1 ELSE 0 END)
         AS NUMBER(10))                                          AS OV_PAY_CNT,
    MAX(CASE WHEN NVL(p.CANCELED, 0) = 0 THEN p.DATE_ END)       AS OV_LAST_PAY_DATE,
    CAST(ROUND(SUM(CASE WHEN NVL(p.CANCELED, 0) = 0
                        THEN NVL(p.PAY_FULL_AMT, 0) ELSE 0 END), 2)
         AS NUMBER(15,3))                                        AS OV_PAY_FULL_SUM
FROM MIGRATION.LS_OV_PAY_PT p
WHERE p.CROSSREF_MAIN_LREF IS NOT NULL
GROUP BY p.CROSSREF_MAIN_LREF;


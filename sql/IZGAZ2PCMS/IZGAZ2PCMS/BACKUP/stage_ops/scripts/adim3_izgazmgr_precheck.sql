DECLARE @AGR_ID BIGINT = 197168;

PRINT '=== 0) TABLO VAR MI ===';
SELECT
    OBJECT_ID('dbo.LS_INVOICE', 'U')  AS LS_INVOICE_OBJ,
    OBJECT_ID('dbo.LS_INVLINES', 'U') AS LS_INVLINES_OBJ;

IF OBJECT_ID('dbo.LS_INVOICE', 'U') IS NULL
BEGIN
    RAISERROR('izgazMGR.dbo.LS_INVOICE yok. Oracle → izgazMGR dump yapin.', 16, 1);
    RETURN;
END
GO

DECLARE @AGR_ID BIGINT = 197168;

PRINT '=== 1) INVOICE — kapsam / sayim ===';
SELECT
    @AGR_ID AS AGR_ID,
    COUNT_BIG(*) AS INV_CNT,
    COUNT_BIG(DISTINCT ABYS_ACTION_ID) AS DISTINCT_ACTION,
    COUNT_BIG(DISTINCT ABYS_ACCOUNT_ID) AS DISTINCT_ACCOUNT,
    SUM(CASE WHEN ISNULL(IOCODE, 0) = 0 THEN 1 ELSE 0 END) AS INV_IOCODE0,
    SUM(CAST(PAYABLETOTAL AS FLOAT)) AS INV_SUM,
    SUM(CAST(TLTOTAL AS FLOAT)) AS INV_TL,
    SUM(CAST(TAX AS FLOAT)) AS INV_TAX,
    SUM(CAST(GRANDTOTAL AS FLOAT)) AS INV_GRAND
FROM dbo.LS_INVOICE WITH (NOLOCK)
WHERE ABYS_AGREEMENT_ID = @AGR_ID;

PRINT '=== 2) INVOICE — anahtar sagligi (571) ===';
-- LREF dump'ta ABYS_ACTION_ID olmali; 571 LREF=ABYS_ACTION_ID kullanir
SELECT
    SUM(CASE WHEN ABYS_ACTION_ID IS NULL THEN 1 ELSE 0 END) AS NULL_ACTION,
    SUM(CASE WHEN ABYS_AGREEMENT_ID IS NULL THEN 1 ELSE 0 END) AS NULL_AGR,
    SUM(CASE WHEN ABYS_ACCOUNT_ID IS NULL THEN 1 ELSE 0 END) AS NULL_ACCOUNT,
    SUM(CASE WHEN LREF IS NOT NULL AND ABYS_ACTION_ID IS NOT NULL
                  AND CAST(LREF AS BIGINT) <> CAST(ABYS_ACTION_ID AS BIGINT)
             THEN 1 ELSE 0 END) AS BAD_LREF_VS_ACTION,
    SUM(CASE WHEN ABYS_ACTION_ID < 1 OR ABYS_ACTION_ID > 2147483647 THEN 1 ELSE 0 END) AS ACTION_OUT_OF_INT,
    SUM(CASE WHEN ISNULL(IOCODE, 0) <> 0 THEN 1 ELSE 0 END) AS NONZERO_IOCODE
FROM dbo.LS_INVOICE WITH (NOLOCK)
WHERE ABYS_AGREEMENT_ID = @AGR_ID;

PRINT '=== 3) INVOICE — TYPE / ACTION_TYPE ===';
SELECT
    [TYPE],
    ABYS_ACTION_TYPE_ID,
    COUNT_BIG(*) AS ADET,
    SUM(CAST(PAYABLETOTAL AS FLOAT)) AS TOPLAM
FROM dbo.LS_INVOICE WITH (NOLOCK)
WHERE ABYS_AGREEMENT_ID = @AGR_ID
GROUP BY [TYPE], ABYS_ACTION_TYPE_ID
ORDER BY ABYS_ACTION_TYPE_ID, [TYPE];

PRINT '=== 4) INVOICE — sifir tutar / income yok aday ===';
SELECT COUNT_BIG(*) AS INV_ZERO_AMT
FROM dbo.LS_INVOICE WITH (NOLOCK)
WHERE ABYS_AGREEMENT_ID = @AGR_ID
  AND ISNULL(CAST(PAYABLETOTAL AS FLOAT), 0) = 0
  AND ISNULL(CAST(TLTOTAL AS FLOAT), 0) = 0
  AND ISNULL(CAST(TAX AS FLOAT), 0) = 0;
GO

DECLARE @AGR_ID BIGINT = 197168;

PRINT '=== 5) INVLINES (varsa) ===';
IF OBJECT_ID('dbo.LS_INVLINES', 'U') IS NULL
BEGIN
    SELECT 'LS_INVLINES yok — 581 atlanabilir; 575 icin zorunlu degil' AS UYARI;
END
ELSE
BEGIN
    SELECT
        COUNT_BIG(*) AS LINE_CNT,
        COUNT_BIG(DISTINCT INVOICEREF) AS INV_WITH_LINES,
        SUM(CAST(GRANDTOTAL AS FLOAT)) AS LINE_SUM,
        SUM(CAST(TLTOTAL AS FLOAT)) AS LINE_TL,
        SUM(CAST(TAX AS FLOAT)) AS LINE_TAX
    FROM dbo.LS_INVLINES WITH (NOLOCK)
    WHERE ABYS_AGREEMENT_ID = @AGR_ID
       OR INVOICEREF IN (
            SELECT CAST(ABYS_ACTION_ID AS INT)
            FROM dbo.LS_INVOICE WITH (NOLOCK)
            WHERE ABYS_AGREEMENT_ID = @AGR_ID
          );

    -- orphan satir (fatura yok)
    SELECT COUNT_BIG(*) AS ORPHAN_LINES
    FROM dbo.LS_INVLINES l WITH (NOLOCK)
    WHERE (
            l.ABYS_AGREEMENT_ID = @AGR_ID
         OR l.INVOICEREF IN (
                SELECT CAST(ABYS_ACTION_ID AS INT)
                FROM dbo.LS_INVOICE WITH (NOLOCK)
                WHERE ABYS_AGREEMENT_ID = @AGR_ID
            )
          )
      AND NOT EXISTS (
            SELECT 1
            FROM dbo.LS_INVOICE i WITH (NOLOCK)
            WHERE CAST(i.ABYS_ACTION_ID AS INT) = l.INVOICEREF
               OR CAST(i.LREF AS INT) = l.INVOICEREF
          );

    -- fatura ↔ satir tutar farki
    SELECT COUNT_BIG(*) AS INV_TUTAR_FARK
    FROM dbo.LS_INVOICE i WITH (NOLOCK)
    LEFT JOIN (
        SELECT INVOICEREF, SUM(CAST(GRANDTOTAL AS FLOAT)) AS SUM_G
        FROM dbo.LS_INVLINES WITH (NOLOCK)
        GROUP BY INVOICEREF
    ) l ON l.INVOICEREF = CAST(i.ABYS_ACTION_ID AS INT)
    WHERE i.ABYS_AGREEMENT_ID = @AGR_ID
      AND ABS(ISNULL(CAST(i.PAYABLETOTAL AS FLOAT), 0) - ISNULL(l.SUM_G, 0)) > 0.01;

    -- satir anahtar
    SELECT
        SUM(CASE WHEN LREF IS NULL THEN 1 ELSE 0 END) AS NULL_LREF,
        SUM(CASE WHEN INVOICEREF IS NULL THEN 1 ELSE 0 END) AS NULL_INVREF,
        SUM(CASE WHEN ABYS_INCOME_ROW_ID IS NOT NULL
                      AND CAST(LREF AS BIGINT) <> CAST(ABYS_INCOME_ROW_ID AS BIGINT)
                 THEN 1 ELSE 0 END) AS BAD_LREF_VS_INCOME_ROW,
        SUM(CASE WHEN LREF < 1 OR LREF > 2147483647 THEN 1 ELSE 0 END) AS LREF_OUT_OF_INT
    FROM dbo.LS_INVLINES WITH (NOLOCK)
    WHERE ABYS_AGREEMENT_ID = @AGR_ID
       OR INVOICEREF IN (
            SELECT CAST(ABYS_ACTION_ID AS INT)
            FROM dbo.LS_INVOICE WITH (NOLOCK)
            WHERE ABYS_AGREEMENT_ID = @AGR_ID
          );
END
GO


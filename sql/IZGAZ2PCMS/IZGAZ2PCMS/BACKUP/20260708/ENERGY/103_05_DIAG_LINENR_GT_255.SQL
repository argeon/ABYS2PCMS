/* ============================================================
   FILE : prodEnergy/hotfix/05_diag_linenr_gt_255.sql
   Amac : INVLINES gelir adedi (MAX LINENR / satir sayisi) > 255
          → 581 TINYINT overflow adaylari
   Kaynak: izgazMGR.dbo.LS_INVLINES (dump sonrasi)
   Salt okuma
   ============================================================ */
USE izgazMGR;
GO

SET NOCOUNT ON;

DECLARE @Lim INT = 255;

PRINT CONVERT(VARCHAR(30), SYSDATETIME(), 121) + ' | LINENR/gelir adedi > ' + CAST(@Lim AS VARCHAR(10));

IF OBJECT_ID('dbo.LS_INVLINES', 'U') IS NULL
BEGIN
    RAISERROR('izgazMGR.dbo.LS_INVLINES yok. Once CTAS dump.', 16, 1);
    RETURN;
END

/* Ozet */
SELECT
    COUNT_BIG(*) AS FATURA_ADET,
    MAX(cnt) AS MAX_GELIR_ADET,
    SUM(cnt) AS TOPLAM_SATIR_BU_FATURALARDA
FROM (
    SELECT
        INVOICEREF,
        COUNT_BIG(*) AS cnt,
        MAX(TRY_CONVERT(INT, LINENR)) AS max_linenr
    FROM dbo.LS_INVLINES WITH (NOLOCK)
    WHERE INVOICEREF IS NOT NULL
    GROUP BY INVOICEREF
    HAVING COUNT_BIG(*) > @Lim
        OR MAX(TRY_CONVERT(INT, LINENR)) > @Lim
) x;

/* Detay — en yogun faturalar */
SELECT TOP (200)
    CAST(INVOICEREF AS BIGINT) AS INVOICEREF,
    COUNT_BIG(*) AS GELIR_ADET,
    MAX(TRY_CONVERT(INT, LINENR)) AS MAX_LINENR,
    MAX(TRY_CONVERT(BIGINT, ABYS_AGREEMENT_ID)) AS ABYS_AGREEMENT_ID,
    MIN(TRY_CONVERT(BIGINT, LREF)) AS MIN_LREF,
    MAX(TRY_CONVERT(BIGINT, LREF)) AS MAX_LREF
FROM dbo.LS_INVLINES WITH (NOLOCK)
WHERE INVOICEREF IS NOT NULL
GROUP BY INVOICEREF
HAVING COUNT_BIG(*) > @Lim
    OR MAX(TRY_CONVERT(INT, LINENR)) > @Lim
ORDER BY GELIR_ADET DESC;

/* Ornek: bilinen LREF 546501435 hangi faturada */
IF EXISTS (
    SELECT 1 FROM dbo.LS_INVLINES WITH (NOLOCK)
    WHERE TRY_CONVERT(BIGINT, LREF) = 546501435
)
SELECT
    CAST(LREF AS BIGINT) AS LREF,
    CAST(INVOICEREF AS BIGINT) AS INVOICEREF,
    TRY_CONVERT(INT, LINENR) AS LINENR,
    TRY_CONVERT(BIGINT, ABYS_AGREEMENT_ID) AS ABYS_AGREEMENT_ID
FROM dbo.LS_INVLINES WITH (NOLOCK)
WHERE TRY_CONVERT(BIGINT, LREF) = 546501435;

PRINT CONVERT(VARCHAR(30), SYSDATETIME(), 121) + ' | diag bitti';
GO

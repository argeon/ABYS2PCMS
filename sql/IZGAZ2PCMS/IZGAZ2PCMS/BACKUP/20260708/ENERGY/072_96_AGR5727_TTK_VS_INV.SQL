/* ---------- Energy: IADE / IPTAL (account grain) ---------- */
CREATE TABLE #IADE96 (
    ACCOUNT_ID        BIGINT NOT NULL,
    IADE_CNT          INT NOT NULL,
    IADE_AMT          DECIMAL(18,2) NOT NULL,
    IADE_LREF         BIGINT NULL,
    IADE_TYPE         INT NULL,
    INV_CANCELED_CNT  INT NOT NULL,
    INV_CANCELED_AMT  DECIMAL(18,2) NOT NULL,
    PT_CP_CNT         INT NOT NULL,
    PT_CP_AMT         DECIMAL(18,2) NOT NULL
);

;WITH iade_inv AS (
    SELECT
        inv.ABYS_ACCOUNT_ID AS ACCOUNT_ID,
        inv.LREF,
        inv.TYPE,
        CONVERT(DECIMAL(18,2), ISNULL(inv.PAYABLETOTAL, 0)) AS PAY,
        CASE
            WHEN inv.TYPE = 92 THEN 1
            WHEN inv.ABYS_ACTION_TYPE_ID = 2 THEN 1
            WHEN ISNULL(inv.IOCODE, 0) = 1
             AND ISNULL(inv.TYPE, 0) <> 101
             AND (
                    UPPER(ISNULL(inv.EXPLAIN, '')) LIKE N'%IADE%'
                 OR UPPER(ISNULL(inv.EXPLAIN, '')) LIKE N'%EKSILTEN%'
             ) THEN 1
            ELSE 0
        END AS IS_IADE,
        CASE WHEN ISNULL(inv.CANCELED, 0) = 1 AND ISNULL(inv.IOCODE, 0) = 0 THEN 1 ELSE 0 END AS IS_INV_CANCEL,
        CASE WHEN ISNULL(inv.CANCELED, 0) = 1 AND ISNULL(inv.IOCODE, 0) = 0
             THEN CONVERT(DECIMAL(18,2), ISNULL(inv.PAYABLETOTAL, 0)) ELSE 0 END AS CANCEL_PAY
    FROM dbo.LS_005_01_INVOICE inv WITH (NOLOCK)
    WHERE inv.ABYS_AGREEMENT_ID = @Agr
      AND inv.ABYS_ACCOUNT_ID IS NOT NULL
),
pt_cp AS (
    SELECT
        inv.ABYS_ACCOUNT_ID AS ACCOUNT_ID,
        COUNT(*) AS PT_CP_CNT,
        CONVERT(DECIMAL(18,2), SUM(CONVERT(DECIMAL(18,2), ISNULL(pt.PAYABLETOTAL, 0)))) AS PT_CP_AMT
    FROM dbo.LS_005_01_INVOICE inv WITH (NOLOCK)
    INNER JOIN dbo.LS_005_01_PAYTRANS pt WITH (NOLOCK)
        ON pt.INVOICEREF = inv.LREF
    WHERE inv.ABYS_AGREEMENT_ID = @Agr
      AND inv.ABYS_ACCOUNT_ID IS NOT NULL
      AND ISNULL(pt.CANCELLATIONPAYMENT, 0) = 1
      AND ISNULL(pt.CANCELED, 0) = 0
    GROUP BY inv.ABYS_ACCOUNT_ID
)
INSERT INTO #IADE96 (
    ACCOUNT_ID, IADE_CNT, IADE_AMT, IADE_LREF, IADE_TYPE,
    INV_CANCELED_CNT, INV_CANCELED_AMT, PT_CP_CNT, PT_CP_AMT
)
SELECT
    a.ACCOUNT_ID,
    SUM(a.IS_IADE),
    CONVERT(DECIMAL(18,2), SUM(CASE WHEN a.IS_IADE = 1 THEN a.PAY ELSE 0 END)),
    MAX(CASE WHEN a.IS_IADE = 1 THEN a.LREF END),
    MAX(CASE WHEN a.IS_IADE = 1 THEN a.TYPE END),
    SUM(a.IS_INV_CANCEL),
    CONVERT(DECIMAL(18,2), SUM(a.CANCEL_PAY)),
    ISNULL(MAX(p.PT_CP_CNT), 0),
    CONVERT(DECIMAL(18,2), ISNULL(MAX(p.PT_CP_AMT), 0))
FROM iade_inv a
LEFT JOIN pt_cp p ON p.ACCOUNT_ID = a.ACCOUNT_ID
GROUP BY a.ACCOUNT_ID
HAVING SUM(a.IS_IADE) > 0
    OR SUM(a.IS_INV_CANCEL) > 0
    OR ISNULL(MAX(p.PT_CP_CNT), 0) > 0;

CREATE CLUSTERED INDEX CX_IADE96 ON #IADE96 (ACCOUNT_ID);

/* ---------- Overlay KIND (TAM/KISMI) — birincil kaynak ---------- */
CREATE TABLE #EKS96 (
    ACCOUNT_ID   BIGINT NOT NULL,
    EKS_KIND     VARCHAR(10) NULL,
    EKS_AMT      DECIMAL(18,2) NULL,
    TAH_AMT      DECIMAL(18,2) NULL,
    KALAN_AMT    DECIMAL(18,2) NULL,
    MAIN_LREF    BIGINT NULL
);

IF OBJECT_ID('izgazMGR.dbo.LS_OV_EKS_CLASS', 'U') IS NOT NULL
BEGIN
    INSERT INTO #EKS96 (ACCOUNT_ID, EKS_KIND, EKS_AMT, TAH_AMT, KALAN_AMT, MAIN_LREF)
    SELECT
        CAST(c.ACCOUNT_ID AS BIGINT),
        /* KISMI once — ayni hesapta birden fazla satir olursa */
        CASE
            WHEN SUM(CASE WHEN c.KIND = 'KISMI' THEN 1 ELSE 0 END) > 0 THEN 'KISMI'
            WHEN SUM(CASE WHEN c.KIND = 'TAM'   THEN 1 ELSE 0 END) > 0 THEN 'TAM'
            ELSE MAX(LEFT(CAST(c.KIND AS VARCHAR(10)), 10))
        END,
        CONVERT(DECIMAL(18,2), SUM(ISNULL(c.EKS_AMT, 0))),
        CONVERT(DECIMAL(18,2), MAX(ISNULL(c.TAH_AMT, 0))),
        CONVERT(DECIMAL(18,2),
            MAX(ISNULL(c.TAH_AMT, 0)) - SUM(ISNULL(c.EKS_AMT, 0))),
        MAX(CAST(c.MAIN_LREF AS BIGINT))
    FROM izgazMGR.dbo.LS_OV_EKS_CLASS c WITH (NOLOCK)
    WHERE c.AGREEMENT_ID = @Agr
      AND ISNULL(c.KIND, '') IN ('TAM', 'KISMI')
    GROUP BY CAST(c.ACCOUNT_ID AS BIGINT);
END

CREATE CLUSTERED INDEX CX_EKS96 ON #EKS96 (ACCOUNT_ID);

/* ---------- Energy: borc INV (IOCODE=0, CANCELED=0) ---------- */
CREATE TABLE #EN96 (
    ACCOUNT_ID       BIGINT NOT NULL,
    ACCRUE_TYPE_ID   INT NULL,
    ACTION_TYPE_ID   INT NULL,
    INV_CNT          INT NOT NULL,
    TAHAKKUK_TARIHI  DATE NULL,
    ALL_CLOSED       TINYINT NOT NULL,
    INV_SUM          DECIMAL(18,2) NOT NULL,
    PT_P             DECIMAL(18,2) NOT NULL,
    PT_PAID          DECIMAL(18,2) NOT NULL,
    PT_KALAN         DECIMAL(18,2) NOT NULL,
    LINE_SUM         DECIMAL(18,2) NOT NULL
);

INSERT INTO #EN96 (
    ACCOUNT_ID, ACCRUE_TYPE_ID, ACTION_TYPE_ID, INV_CNT,
    TAHAKKUK_TARIHI, ALL_CLOSED, INV_SUM,
    PT_P, PT_PAID, PT_KALAN, LINE_SUM
)
SELECT
    inv.ABYS_ACCOUNT_ID,
    MAX(CAST(inv.ABYS_ACCRUE_TYPE_ID AS INT)),
    MAX(CAST(inv.ABYS_ACTION_TYPE_ID AS INT)),
    COUNT(*),
    MIN(CAST(inv.DATE_ AS DATE)),
    CAST(MIN(CASE WHEN ISNULL(inv.CLOSED,0) = 0 THEN 0 ELSE 1 END) AS TINYINT),
    CONVERT(DECIMAL(18,2), SUM(CONVERT(DECIMAL(18,2), ISNULL(inv.PAYABLETOTAL,0)))),
    CONVERT(DECIMAL(18,2), SUM(ISNULL(pt.PT_PAYABLE,0))),
    CONVERT(DECIMAL(18,2), SUM(ISNULL(pt.PT_PAID,0))),
    CONVERT(DECIMAL(18,2), SUM(ISNULL(pt.PT_KALAN,0))),
    CONVERT(DECIMAL(18,2), SUM(ISNULL(ln.LINE_SUM,0)))
FROM dbo.LS_005_01_INVOICE inv WITH (NOLOCK)
LEFT JOIN (
    SELECT
        INVOICEREF,
        SUM(CONVERT(DECIMAL(18,2), ISNULL(PAYABLETOTAL,0))) AS PT_PAYABLE,
        SUM(CONVERT(DECIMAL(18,2), ISNULL(PAID,0))) AS PT_PAID,
        SUM(CONVERT(DECIMAL(18,2), ISNULL(PAYABLETOTAL,0)))
      - SUM(CONVERT(DECIMAL(18,2), ISNULL(PAID,0))) AS PT_KALAN
    FROM dbo.LS_005_01_PAYTRANS WITH (NOLOCK)
    WHERE ISNULL(IOCODE,0) = 0
      AND ISNULL(CANCELED,0) = 0
      AND ISNULL(CANCELLATIONPAYMENT,0) = 0
    GROUP BY INVOICEREF
) pt ON pt.INVOICEREF = inv.LREF
LEFT JOIN (
    SELECT
        il.INVOICEREF,
        SUM(CONVERT(DECIMAL(18,2),
            ISNULL(il.ABYS_AMOUNT_RAW, il.GRANDTOTAL) * ISNULL(il.ABYS_STATUS, 1)
        )) AS LINE_SUM
    FROM dbo.LS_005_01_INVLINES il WITH (NOLOCK)
    WHERE ISNULL(il.CANCELED, 0) = 0
    GROUP BY il.INVOICEREF
) ln ON ln.INVOICEREF = inv.LREF
WHERE inv.ABYS_AGREEMENT_ID = @Agr
  AND ISNULL(inv.IOCODE, 0) = 0
  AND ISNULL(inv.CANCELED, 0) = 0
  AND inv.ABYS_ACCOUNT_ID IS NOT NULL
GROUP BY inv.ABYS_ACCOUNT_ID;

CREATE CLUSTERED INDEX CX_EN96 ON #EN96 (ACCOUNT_ID);


/* ============================================================
   SSMS — AGR: ABYS (O59 TTK) vs INV vs AFL + Energy IADE/IPTAL
   Grain: ACCOUNT_ID (1 satir = 1 hesap)

   INV  = SUM(borc) IOCODE=0 AND CANCELED=0
   ABYS = izgazMGR.TUKETIM_TUTAR_KONTROL (O59) / yoksa energy 93
   AFL  = LS_AFL_OPEN_DEBT.BALANCE

   IPTAL_KIND (TAM/KISMI) — birincil: LS_OV_EKS_CLASS.KIND
     TAM   : EKS_AMT ≈ TAH_AMT  | Energy'de TYPE=92 IADE (tam)
     KISMI : EKS_AMT < TAH_AMT  | Energy MAIN PAYABLE = kalan
             (TYPE=92 genelde YOK — 590 KISMI_HDR dusumu)
   !!! IADE_AMT < SUM(INV) ile KISMI UYDURMA (cok borc INV → sahte KISMI)

   Energy (#IADE96):
     IADE  : TYPE=92 | ACT=2 | EXPLAIN IADE
     IPTAL : INV.CANCELED=1 | PT.CANCELLATIONPAYMENT=1
   ============================================================
   KIND_ABYS:
     EKSILTEN (overlay/IADE) | IPTAL | MATCH | ONLY_INV | INV_GT_* | ABYS_GT_*

   Result set:
     1) ACCOUNT detay
     2) ONLY_ABYS
     3) Sozlesme ozeti (ABYS / Energy / AFL — tahakkuk + eksilten adet/tutar)
     4) FRK sayaclari (MATCH/DIFF/TAM/KISMI)
   ============================================================ */
USE energy;

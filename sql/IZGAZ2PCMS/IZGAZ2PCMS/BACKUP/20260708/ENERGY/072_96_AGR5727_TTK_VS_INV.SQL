IF OBJECT_ID('tempdb..#IADE96') IS NOT NULL DROP TABLE #IADE96;
IF OBJECT_ID('tempdb..#EKS96') IS NOT NULL DROP TABLE #EKS96;
IF OBJECT_ID('tempdb..#ABYS96') IS NOT NULL DROP TABLE #ABYS96;
GO


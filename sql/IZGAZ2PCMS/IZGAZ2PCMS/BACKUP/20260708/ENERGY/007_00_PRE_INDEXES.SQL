/* --- OV helper: AGR + LREF (tablo varsa) --- */
DECLARE @sql NVARCHAR(MAX);
DECLARE @t SYSNAME;
DECLARE c CURSOR LOCAL FAST_FORWARD FOR
SELECT v.t
FROM (VALUES
    (N'LS_OV_IADE_INVOICE'),
    (N'LS_OV_IADE_INVLINES'),
    (N'LS_OV_IADE_PAYTRANS'),
    (N'LS_OV_MAIN_UPD'),
    (N'LS_OV_KISMI_INVLINES'),
    (N'LS_OV_KISMI_HDR'),
    (N'LS_OV_KISMI_PAYTRANS'),
    (N'LS_OV_PAY_PT'),
    (N'LS_OV_TAH_INVOICE'),
    (N'LS_OV_DEBT_PAID_UPD'),
    (N'LS_OV_CANCEL_PAY'),
    (N'LS_OV_PAY_ALLOC'),
    (N'LS_OV_GUVENCE_IADE_INVOICE'),
    (N'LS_OV_GUVENCE_IADE_INVLINES'),
    (N'LS_OV_GUVENCE_IADE_PAYTRANS')
) v(t);

OPEN c;
FETCH NEXT FROM c INTO @t;
WHILE @@FETCH_STATUS = 0
BEGIN
    IF OBJECT_ID(N'dbo.' + @t, 'U') IS NOT NULL
    BEGIN
        IF COL_LENGTH(N'dbo.' + @t, 'ABYS_AGREEMENT_ID') IS NOT NULL
           AND NOT EXISTS (
                SELECT 1 FROM sys.indexes
                WHERE object_id = OBJECT_ID(N'dbo.' + @t)
                  AND name = N'IX_MIG_' + @t + N'_AGR'
              )
        BEGIN
            SET @sql = N'CREATE NONCLUSTERED INDEX [IX_MIG_' + @t + N'_AGR]
                ON dbo.[' + @t + N'] (ABYS_AGREEMENT_ID)
                WITH (MAXDOP = 48, ONLINE = ON, SORT_IN_TEMPDB = ON);';
            EXEC sp_executesql @sql;
            PRINT 'IX_MIG_' + @t + '_AGR OK';
        END

        IF COL_LENGTH(N'dbo.' + @t, 'LREF') IS NOT NULL
           AND NOT EXISTS (
                SELECT 1 FROM sys.indexes
                WHERE object_id = OBJECT_ID(N'dbo.' + @t)
                  AND name = N'IX_MIG_' + @t + N'_LREF'
              )
        BEGIN
            SET @sql = N'CREATE NONCLUSTERED INDEX [IX_MIG_' + @t + N'_LREF]
                ON dbo.[' + @t + N'] (LREF)
                WITH (MAXDOP = 48, ONLINE = ON, SORT_IN_TEMPDB = ON);';
            EXEC sp_executesql @sql;
            PRINT 'IX_MIG_' + @t + '_LREF OK';
        END
    END
    FETCH NEXT FROM c INTO @t;
END
CLOSE c; DEALLOCATE c;
GO


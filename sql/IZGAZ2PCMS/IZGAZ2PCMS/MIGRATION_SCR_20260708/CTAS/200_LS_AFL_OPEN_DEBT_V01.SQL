BEGIN EXECUTE IMMEDIATE 'DROP TABLE MIGRATION.LS_AFL_OPEN_DEBT PURGE';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;

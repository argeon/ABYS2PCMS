ALTER SESSION FORCE PARALLEL DML PARALLEL 56;

DECLARE
  n NUMBER;
BEGIN
  BEGIN
    MIGRATION.P_MIG_CTAS_LOG('O50', 'afl_open_debt', 'START', NULL, 'FRK master BALANCE>0 + GECIKME');
  EXCEPTION WHEN OTHERS THEN NULL;
  END;
END;

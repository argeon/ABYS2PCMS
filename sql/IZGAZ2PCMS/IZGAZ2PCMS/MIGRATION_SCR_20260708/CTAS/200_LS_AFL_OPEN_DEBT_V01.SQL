-- RECON
SELECT
    COUNT(*) AS AFL_CNT,
    COUNT(CASE WHEN MIG_IN_SCOPE = 1 THEN 1 END) AS MIG_SCOPE_CNT,
    COUNT(CASE WHEN TAKSIT_DURUMU = 'T' THEN 1 END) AS TAKSIT_CNT,
    ROUND(SUM(BALANCE), 2) AS AFL_BAL_SUM,
    ROUND(SUM(CASE WHEN MIG_IN_SCOPE = 1 THEN BALANCE ELSE 0 END), 2) AS MIG_BAL_SUM,
    ROUND(SUM(GECIKME_BEDELI), 2) AS AFL_GECIKME_SUM,
    COUNT(CASE WHEN GECIKME_BEDELI IS NOT NULL AND GECIKME_BEDELI <> 0 THEN 1 END) AS GECIKME_NZ_CNT
FROM MIGRATION.LS_AFL_OPEN_DEBT;

DECLARE
  n_afl NUMBER; n_mig NUMBER;
BEGIN
  SELECT COUNT(*), COUNT(CASE WHEN MIG_IN_SCOPE = 1 THEN 1 END)
    INTO n_afl, n_mig FROM MIGRATION.LS_AFL_OPEN_DEBT;
  MIGRATION.P_MIG_CTAS_LOG('O50', 'afl_open_debt', 'OK', n_afl,
    'afl=' || n_afl || ' mig_scope=' || n_mig || ' dump→izgazMGR');
  DBMS_OUTPUT.PUT_LINE('========== O50 AFL OK | afl=' || n_afl
    || ' mig_scope=' || n_mig || ' | CTAS BITTI → dump ==========');
END;

CREATE TABLE MIGRATION.LS_AFL_OPEN_DEBT
NOLOGGING
PARALLEL 56
AS
SELECT /*+ PARALLEL(56) */
    CAST(a.ID AS NUMBER(12))                                     AS FATURAID,
    CAST(a.AGREEMENT_ID AS NUMBER(12))                           AS SOZLESME_HESABI,
    a.EXPIRY_DATE                                                AS EXPIRY_DATE,
    CAST(ROUND(SUM(ai.STATUS * ai.AMOUNT), 2) AS NUMBER(18,2))   AS BALANCE,
    CAST(ROUND(
      CASE
        WHEN MAX(a.LEGAL_PROCEEDING_ID) IS NOT NULL THEN
          SMS.F_GET_COMMISSION_CALC(
            NVL(MAX(la.COMMISSION_DELAY_TYPE_ID), 2),
            SUM(CASE
                  WHEN NVL(ip.IS_LEGAL_EXPENSE, 0) = 0
                   AND NVL(ip.IS_OVERDUE_INCOME, 0) = 0
                   AND a.ACCRUE_TYPE_ID <> 8
                  THEN ai.STATUS * ai.AMOUNT
                  ELSE 0
                END),
            NVL(MAX(lp.LAST_PAYMENT_DATE), NVL(MAX(lp.LAW_DOC_DATE), SYSDATE)),
            SYSDATE
          )
        ELSE
          SMS.F_GET_COMMISSION_CALC(
            MAX(ip.COMMISSION_DELAY_TYP_ID),
            SUM(ai.STATUS * ai.AMOUNT),
            a.EXPIRY_DATE,
            SYSDATE,
            MAX(ip.ID)
          )
      END
    , 2) AS NUMBER(18,2))                                        AS GECIKME_BEDELI,
    CAST(stpl.VALUE AS VARCHAR2(200))                            AS SUBSCRIBER_TYPE,
    CAST(ttpl.VALUE AS VARCHAR2(200))                            AS TARIFF_TYPE,
    CAST(ttpl2.VALUE AS VARCHAR2(200))                           AS SKB_TARIFF_TYPE,
    CASE WHEN a.INSTALLMENT_ID IS NOT NULL THEN 'T' ELSE 'N' END AS TAKSIT_DURUMU,
    CASE WHEN a.LEGAL_PROCEEDING_ID IS NOT NULL THEN 'VAR' ELSE 'YOK' END AS YT_DURUMU,
    CAST(a.INSTALLMENT_ID AS NUMBER(12))                         AS INSTALLMENT_ID,
    CAST(a.LEGAL_PROCEEDING_ID AS NUMBER(12))                    AS LEGAL_PROCEEDING_ID,
    CAST(a.ACCRUE_TYPE_ID AS NUMBER(10))                         AS ACCRUE_TYPE_ID,
    CAST(CASE WHEN NVL(a.ACCRUE_TYPE_ID, -1) <> 14 THEN 1 ELSE 0 END AS NUMBER(1)) AS MIG_IN_SCOPE,
    CAST(TRUNC(SYSDATE) AS DATE)                                 AS AS_OF_DATE,
    CAST(SYSDATE AS DATE)                                        AS SNAPSHOT_DATE
FROM SMS.CS_ACCOUNT a
JOIN SMS.CS_ACCOUNT_ACTION aa
  ON aa.ACCOUNT_ID = a.ID
JOIN SMS.CS_ACCOUNT_INCOME ai
  ON ai.ACCOUNT_ACTION_ID = aa.ID
JOIN SMS.CS_INCOME_PRM ip
  ON ip.ID = ai.INCOME_ID
LEFT JOIN (
  SELECT LEGAL_PROCEEDING_ID,
         ACCOUNT_ID,
         MAX(COMMISSION_DELAY_TYPE_ID) AS COMMISSION_DELAY_TYPE_ID
    FROM SMS.LP_ACCOUNT
   GROUP BY LEGAL_PROCEEDING_ID, ACCOUNT_ID
) la
  ON la.ACCOUNT_ID = a.ID
 AND la.LEGAL_PROCEEDING_ID = a.LEGAL_PROCEEDING_ID
LEFT JOIN SMS.LP_LEGAL_PROCEEDING lp
  ON lp.ID = a.LEGAL_PROCEEDING_ID
LEFT JOIN SMS.CS_SUBSCRIBER_TYPE_PRM_LNG stpl
  ON stpl.PRM_ID = a.SUBSCRIBER_TYPE_ID AND stpl.LANG_ID = 1
LEFT JOIN SMS.CS_TARIFF_TYPE_PRM_LNG ttpl
  ON ttpl.PRM_ID = a.TARIFF_TYPE_ID AND ttpl.LANG_ID = 1
LEFT JOIN SMS.CS_TARIFF_TYPE_PRM_LNG ttpl2
  ON ttpl2.PRM_ID = a.SKB_TARIFF_TYPE_ID AND ttpl2.LANG_ID = 1
GROUP BY
    a.ID, a.AGREEMENT_ID, a.EXPIRY_DATE,
    stpl.VALUE, ttpl.VALUE, ttpl2.VALUE,
    a.LEGAL_PROCEEDING_ID, a.INSTALLMENT_ID, a.ACCRUE_TYPE_ID
HAVING SUM(ai.STATUS * ai.AMOUNT) > 0;

CREATE UNIQUE INDEX MIGRATION.IX_AFL_FATURA ON MIGRATION.LS_AFL_OPEN_DEBT (FATURAID) PARALLEL 56 NOLOGGING;
CREATE INDEX MIGRATION.IX_AFL_AGR ON MIGRATION.LS_AFL_OPEN_DEBT (SOZLESME_HESABI) PARALLEL 56 NOLOGGING;
CREATE INDEX MIGRATION.IX_AFL_MIG ON MIGRATION.LS_AFL_OPEN_DEBT (MIG_IN_SCOPE) PARALLEL 56 NOLOGGING;
ALTER INDEX MIGRATION.IX_AFL_FATURA NOPARALLEL;
ALTER INDEX MIGRATION.IX_AFL_AGR NOPARALLEL;
ALTER INDEX MIGRATION.IX_AFL_MIG NOPARALLEL;
ALTER TABLE MIGRATION.LS_AFL_OPEN_DEBT NOPARALLEL LOGGING;

BEGIN DBMS_STATS.GATHER_TABLE_STATS('MIGRATION','LS_AFL_OPEN_DEBT', degree => 40); END;

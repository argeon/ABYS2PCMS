CREATE TABLE MIGRATION.TUKETIM_TUTAR_KONTROL
NOLOGGING
PARALLEL 56
AS
SELECT /*+ PARALLEL(56) */
    CAST(A.ID AS NUMBER(12))                                      AS ACCOUNT_ID,
    CAST(A.AGREEMENT_ID AS NUMBER(12))                            AS AGREEMENT_ID,
    CAST(MAX(ACP.VALUE) AS VARCHAR2(200))                         AS ACCRUE_TYPE_NAME,
    CAST(A.ACCRUE_TYPE_ID AS NUMBER(10))                          AS ACCRUE_TYPE_ID,
    A.EXPIRY_DATE                                                 AS SON_ODEME_TARIHI,
    CAST(TRUNC(A.CREATED_TIMESTAMP) AS DATE)                      AS TAHAKKUK_TARIHI,
    CAST(SUBSTR(MAX(AA.BILL_SERIAL || TO_CHAR(AA.BILL_ORDER_NUMBER)), 1, 45)
         AS VARCHAR2(45))                                         AS FATURA_SERI_SIRA,
    CAST(MAX(AIX.FIRST_INDEX) AS NUMBER(18,6))                    AS FIRST_INDEX,
    CAST(MAX(AIX.LAST_INDEX) AS NUMBER(18,6))                     AS LAST_INDEX,
    CAST(ROUND(SUM(X.M3), 6) AS NUMBER(18,6))                     AS M3,
    CAST(ROUND(SUM(X.CORRECTED_M3), 6) AS NUMBER(18,6))           AS CORRECTED_M3,
    CAST(ROUND(SUM(X.KWH), 6) AS NUMBER(18,6))                    AS KWH,
    CAST(ROUND(SUM(X.CONSUMPTION), 6) AS NUMBER(18,6))            AS CONSUMPTION,
    CAST(ROUND(SUM(X.CONSUMPTION_1), 6) AS NUMBER(18,6))          AS CONSUMPTION_1,
    CAST(ROUND(SUM(X.CONSUMPTION_2), 6) AS NUMBER(18,6))          AS CONSUMPTION_2,
    CAST(ROUND(SUM(X.CONSUMPTION_3), 6) AS NUMBER(18,6))          AS CONSUMPTION_3,
    CAST(ROUND(SUM(X.GAZ_TUTARI), 2) AS NUMBER(18,2))             AS GAZ_TUTARI,
    CAST(ROUND(SUM(X.SKB_TUTARI), 2) AS NUMBER(18,2))             AS SKB_TUTARI,
    CAST(ROUND(SUM(X.KDV_TUTARI), 2) AS NUMBER(18,2))             AS KDV_TUTARI,
    CAST(ROUND(MAX(X.GAZ_M3_BIRIM_FIYAT), 6) AS NUMBER(18,6))     AS GAZ_M3_BIRIM_FIYAT,
    CAST(ROUND(SUM(X.TOPLAM_TAHAKKUK), 2) AS NUMBER(18,2))        AS TOPLAM_TAHAKKUK,
    CAST(ROUND(SUM(X.ODENEN_TUTAR), 2) AS NUMBER(18,2))           AS ODENEN_TUTAR,
    CAST(ROUND(SUM(X.TOPLAM_TAHAKKUK) + SUM(X.ODENEN_TUTAR), 2)
         AS NUMBER(18,2))                                         AS KALAN_TUTAR,
    CAST(TRUNC(SYSDATE) AS DATE)                                  AS AS_OF_DATE,
    CAST(SYSDATE AS DATE)                                         AS SNAPSHOT_DATE
FROM (
    SELECT
        AA.ACCOUNT_ID,
        AA.ID                                                       AS ACTION_ID,
        MAX(CASE WHEN ATP.TYPE IN (1, 5) THEN AA.M3 END)            AS M3,
        MAX(CASE WHEN ATP.TYPE IN (1, 5) THEN AA.CORRECTED_M3 END)  AS CORRECTED_M3,
        MAX(CASE WHEN ATP.TYPE IN (1, 5) THEN AA.KWH END)           AS KWH,
        MAX(CASE WHEN ATP.TYPE IN (1, 5) THEN AA.CONSUMPTION END)   AS CONSUMPTION,
        MAX(CASE WHEN ATP.TYPE IN (1, 5) THEN AA.CONSUMPTION_1 END) AS CONSUMPTION_1,
        MAX(CASE WHEN ATP.TYPE IN (1, 5) THEN AA.CONSUMPTION_2 END) AS CONSUMPTION_2,
        MAX(CASE WHEN ATP.TYPE IN (1, 5) THEN AA.CONSUMPTION_3 END) AS CONSUMPTION_3,
        SUM(CASE WHEN ATP.TYPE IN (1, 5) AND AI.INCOME_ID = 939
                 THEN AI.AMOUNT * AI.STATUS END)                    AS GAZ_TUTARI,
        SUM(CASE WHEN ATP.TYPE IN (1, 5) AND AI.INCOME_ID = 7658
                 THEN AI.AMOUNT * AI.STATUS END)                    AS SKB_TUTARI,
        SUM(CASE WHEN ATP.TYPE IN (1, 5) AND AI.INCOME_ID = 169
                 THEN AI.AMOUNT * AI.STATUS END)                    AS KDV_TUTARI,
        MAX(CASE WHEN ATP.TYPE IN (1, 5) AND AI.INCOME_ID = 939
                 THEN AI.UNIT_PRICE END)                            AS GAZ_M3_BIRIM_FIYAT,
        SUM(CASE WHEN ATP.TYPE IN (1, 5)
                 THEN AI.AMOUNT * AI.STATUS END)                    AS TOPLAM_TAHAKKUK,
        SUM(CASE WHEN ATP.TYPE IN (2, 3, 4, 7)
                 THEN AI.AMOUNT * AI.STATUS END)                    AS ODENEN_TUTAR
    FROM SMS.CS_ACCOUNT_ACTION AA
    JOIN SMS.CS_ACCOUNT_INCOME AI
      ON AI.ACCOUNT_ACTION_ID = AA.ID
    LEFT JOIN SMS.CS_ACTION_TYPE_PRM ATP
      ON ATP.ID = AA.ACTION_TYPE_ID
     AND ATP.TYPE IN (1, 2, 3, 4, 5, 7)
    GROUP BY AA.ACCOUNT_ID, AA.ID
) X
JOIN SMS.CS_ACCOUNT A
  ON A.ID = X.ACCOUNT_ID
LEFT JOIN SMS.CS_ACCRUE_TYPE_PRM_LNG ACP
  ON ACP.PRM_ID = A.ACCRUE_TYPE_ID
 AND ACP.LANG_ID = 1
LEFT JOIN SMS.CS_ACCOUNT_ACTION AA
  ON AA.ID = X.ACTION_ID
LEFT JOIN SMS.CS_ACCOUNT_ACTION_INDEX AIX
  ON AIX.ACCOUNT_ACTION_ID = X.ACTION_ID
 AND AIX.INDEX_TYPE_ID = 1
GROUP BY
    A.ID,
    A.AGREEMENT_ID,
    A.ACCRUE_TYPE_ID,
    A.EXPIRY_DATE,
    TRUNC(A.CREATED_TIMESTAMP);

ALTER TABLE MIGRATION.TUKETIM_TUTAR_KONTROL NOPARALLEL LOGGING;



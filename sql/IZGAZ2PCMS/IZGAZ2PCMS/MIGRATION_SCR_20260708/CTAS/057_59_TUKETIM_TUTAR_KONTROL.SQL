    ROUND(SUM(ODENEN_TUTAR), 2) AS ODE_SUM,
    ROUND(SUM(KALAN_TUTAR), 2) AS KALAN_SUM
FROM MIGRATION.TUKETIM_TUTAR_KONTROL;


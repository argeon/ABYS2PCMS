CREATE TABLE MIGRATION.TMP_O33_OPEN_ACC NOLOGGING PARALLEL 56 AS
SELECT /*+ PARALLEL(56) */ DISTINCT ABYS_ACCOUNT_ID AS ACCOUNT_ID
FROM MIGRATION.LS_INVOICE
WHERE NVL(IOCODE, 0) = 0
  AND NVL(CANCELED, 0) = 0
  AND NVL(CLOSED, 0) = 0
  AND ABYS_ACCOUNT_ID IS NOT NULL;

CREATE UNIQUE INDEX MIGRATION.IX_TMP_O33_OA ON MIGRATION.TMP_O33_OPEN_ACC (ACCOUNT_ID) PARALLEL 56 NOLOGGING;
BEGIN EXECUTE IMMEDIATE 'ALTER INDEX MIGRATION.IX_TMP_O33_OA NOPARALLEL'; END;
/

BEGIN EXECUTE IMMEDIATE 'DROP TABLE MIGRATION.TMP_O33_BAL PURGE';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
CREATE TABLE MIGRATION.TMP_O33_BAL NOLOGGING PARALLEL 56 AS
SELECT /*+ PARALLEL(56) LEADING(oa aa ai) USE_HASH(aa ai) */
    oa.ACCOUNT_ID,
    CAST(ROUND(SUM(ai.STATUS * ai.AMOUNT), 2) AS NUMBER(15,3)) AS BALANCE
FROM MIGRATION.TMP_O33_OPEN_ACC oa
JOIN SMS.CS_ACCOUNT_ACTION aa ON aa.ACCOUNT_ID = oa.ACCOUNT_ID
JOIN SMS.CS_ACCOUNT_INCOME ai ON ai.ACCOUNT_ACTION_ID = aa.ID
GROUP BY oa.ACCOUNT_ID
HAVING ABS(ROUND(SUM(ai.STATUS * ai.AMOUNT), 2)) <= 0.01;

CREATE UNIQUE INDEX MIGRATION.IX_TMP_O33_BAL ON MIGRATION.TMP_O33_BAL (ACCOUNT_ID) PARALLEL 56 NOLOGGING;
BEGIN EXECUTE IMMEDIATE 'ALTER INDEX MIGRATION.IX_TMP_O33_BAL NOPARALLEL'; END;
/

-- Sadece zero-balance hesaplar; CASE..END yok (SQL Developer ORA-00911)
UPDATE /*+ ENABLE_PARALLEL_DML PARALLEL(inv 56) */
       MIGRATION.LS_INVOICE inv
   SET inv.CLOSED = 1
 WHERE NVL(inv.IOCODE, 0) = 0
   AND NVL(inv.CANCELED, 0) = 0
   AND NVL(inv.CLOSED, 0) = 0
   AND EXISTS (
         SELECT /*+ HASH_SJ */ 1
           FROM MIGRATION.TMP_O33_BAL b
          WHERE b.ACCOUNT_ID = inv.ABYS_ACCOUNT_ID
       );

COMMIT;
ALTER TABLE MIGRATION.LS_INVOICE NOPARALLEL;

-- LS_DEBT_PAYTRANS varsa banka/LPD hizala (O14 erken calistiysa)
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TABLES
   WHERE OWNER = 'MIGRATION' AND TABLE_NAME = 'LS_DEBT_PAYTRANS';
  IF n > 0 THEN
    EXECUTE IMMEDIATE q'[
      ALTER TABLE MIGRATION.LS_DEBT_PAYTRANS PARALLEL 56
    ]';
    EXECUTE IMMEDIATE q'[
      MERGE /*+ ENABLE_PARALLEL_DML PARALLEL(pt 56) PARALLEL(s 56) */
       INTO MIGRATION.LS_DEBT_PAYTRANS pt
      USING (
        SELECT /*+ PARALLEL(56) */ inv.LREF, inv.BANKREF, inv.BANK_RECORD_REF, inv.LASTPAIDDATE, inv.XTYPE,
               d.PAID_AMT, d.CLOSED
          FROM MIGRATION.LS_INVOICE inv
          LEFT JOIN MIGRATION.LS_OV_DEBT_PAID_UPD d ON d.MAIN_LREF = inv.LREF
         WHERE NVL(inv.IOCODE,0)=0
      ) s
      ON (pt.INVOICEREF = s.LREF)
      WHEN MATCHED THEN UPDATE SET
        pt.BANKREF = COALESCE(s.BANKREF, pt.BANKREF),
        pt.BANK_RECORD_REF = COALESCE(s.BANK_RECORD_REF, pt.BANK_RECORD_REF),
        pt.LASTPAIDDATE = COALESCE(s.LASTPAIDDATE, pt.LASTPAIDDATE),
        pt.XTYPE = NVL(COALESCE(pt.XTYPE, s.XTYPE), 1),
        pt.PAID = DECODE(NVL(s.CLOSED,0), 1, pt.PAYABLETOTAL, pt.PAID)
    ]';
    COMMIT;
    EXECUTE IMMEDIATE q'[ALTER TABLE MIGRATION.LS_DEBT_PAYTRANS NOPARALLEL]';
  END IF;
END;

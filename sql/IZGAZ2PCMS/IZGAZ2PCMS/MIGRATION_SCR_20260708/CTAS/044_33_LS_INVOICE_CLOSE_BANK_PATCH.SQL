DECLARE
  n_closed NUMBER; n_lpd NUMBER; n_bank NUMBER;
BEGIN
  SELECT
    COUNT(CASE WHEN NVL(CLOSED,0)=1 THEN 1 END),
    COUNT(CASE WHEN LASTPAIDDATE IS NOT NULL THEN 1 END),
    COUNT(CASE WHEN BANKREF IS NOT NULL THEN 1 END)
  INTO n_closed, n_lpd, n_bank
  FROM MIGRATION.LS_INVOICE
  WHERE NVL(IOCODE,0)=0 AND NVL(CANCELED,0)=0;

  MIGRATION.P_MIG_CTAS_LOG('O33', 'invoice_close_bank', 'OK', n_closed,
    'closed=' || n_closed || ' lpd=' || n_lpd || ' bank=' || n_bank);
  DBMS_OUTPUT.PUT_LINE('========== O33 INVOICE CLOSE/BANK OK | closed='
    || n_closed || ' lpd=' || n_lpd || ' bank=' || n_bank || ' ==========');
END;

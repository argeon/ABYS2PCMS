-- Son gecerli odeme (tip2 veya ACTION_TYPE=3) - MAIN grain
BEGIN EXECUTE IMMEDIATE 'DROP TABLE MIGRATION.TMP_O33_LAST_PAY PURGE';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
CREATE TABLE MIGRATION.TMP_O33_LAST_PAY NOLOGGING PARALLEL 56 AS
SELECT /*+ PARALLEL(56) */ *
FROM (
  SELECT
      p.CROSSREF_MAIN_LREF                                       AS MAIN_LREF,
      p.DATE_                                                    AS PAY_DATE,
      act.BANK_ID                                                AS BANKREF,
      CAST(SUBSTR(NVL(act.BANK_RECEIPT_NUMBER, TO_CHAR(act.RECEIPT_NUMBER)), 1, 50)
           AS VARCHAR2(50))                                      AS BANK_RECORD_REF,
      NVL(act.CASH_ID, 0)                                        AS CASH_ID,
      ROW_NUMBER() OVER (
        PARTITION BY p.CROSSREF_MAIN_LREF
        ORDER BY p.DATE_ DESC NULLS LAST, p.ABYS_ID DESC
      )                                                          AS RN
  FROM MIGRATION.LS_OV_PAY_PT p
  JOIN SMS.CS_ACCOUNT_ACTION act ON act.ID = p.ABYS_ID
  WHERE NVL(p.CANCELED, 0) = 0
    AND p.OV_KIND = 'PAY'
    AND p.CROSSREF_MAIN_LREF IS NOT NULL
)
WHERE RN = 1;

CREATE UNIQUE INDEX MIGRATION.IX_TMP_O33_LP ON MIGRATION.TMP_O33_LAST_PAY (MAIN_LREF) PARALLEL 56 NOLOGGING;
BEGIN EXECUTE IMMEDIATE 'ALTER INDEX MIGRATION.IX_TMP_O33_LP NOPARALLEL'; END;
/

-- CLOSED / LPD / BANK / XTYPE patch (DEBT_PAID) — PDML 56
ALTER TABLE MIGRATION.LS_INVOICE PARALLEL 56;
MERGE /*+ ENABLE_PARALLEL_DML PARALLEL(inv 56) PARALLEL(s 56) */
 INTO MIGRATION.LS_INVOICE inv
USING (
  SELECT /*+ PARALLEL(56) */
      d.MAIN_LREF,
      d.CLOSED,
      d.LASTPAIDDATE,
      lp.BANKREF,
      lp.BANK_RECORD_REF
  FROM MIGRATION.LS_OV_DEBT_PAID_UPD d
  LEFT JOIN MIGRATION.TMP_O33_LAST_PAY lp ON lp.MAIN_LREF = d.MAIN_LREF
) s
ON (inv.LREF = s.MAIN_LREF AND NVL(inv.IOCODE, 0) = 0)
WHEN MATCHED THEN UPDATE SET
  inv.CLOSED = DECODE(NVL(s.CLOSED, 0), 1, 1, inv.CLOSED),
  inv.LASTPAIDDATE = COALESCE(s.LASTPAIDDATE, inv.LASTPAIDDATE),
  inv.BANKREF = COALESCE(s.BANKREF, inv.BANKREF),
  inv.BANK_RECORD_REF = COALESCE(s.BANK_RECORD_REF, inv.BANK_RECORD_REF),
  inv.XTYPE = NVL(inv.XTYPE, 1);

COMMIT;

-- CLOSED_CALC: sadece HALA ACIK fatura hesaplari (tum SMS ledger degil)
-- Bakiye ~0 olanlari kapat (pilot SyncClosedFromMgr)
BEGIN EXECUTE IMMEDIATE 'DROP TABLE MIGRATION.TMP_O33_OPEN_ACC PURGE';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;

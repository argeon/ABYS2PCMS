CREATE TABLE MIGRATION.TMP_HHD_TRAN_KEY NOLOGGING PARALLEL 56 AS
SELECT /*+ FULL(r) PARALLEL(r 56) */
    r.LREF,
    CAST(r.LOC_REGION AS NUMBER(10))                 AS LOC_REGION,
    r.READ_DATE                                      AS READ_DATE,
    TRUNC(r.READ_DATE)                               AS READ_DATE_DAY,
    r.READER_PRSNL                                   AS READER_PRSNL,
    CAST(r.READER_PRSNL_ID AS NUMBER(10))            AS READER_PRSNL_ID,
    CAST(r.ABYS_READING_END_OF_DAY_ID AS NUMBER(18)) AS ENDOFDAY_ID,
    CASE WHEN e.ID IS NOT NULL THEN 1 ELSE 0 END     AS EOD_OK,
    CASE WHEN NVL(r.ABYS_NOTE, 'x') LIKE 'MIG_SYNTH%' THEN 1 ELSE 0 END AS IS_SYNTH,
    CAST(r.ABYS_ACCRUE_TYPE_ID AS NUMBER(10))        AS ABYS_ACCRUE_TYPE_ID,
    CAST(SUBSTR(
           CASE
             WHEN NVL(r.ABYS_NOTE, 'x') LIKE 'MIG_SYNTH%'
               THEN NVL(
                      (SELECT m.EXPLAIN_PREFIX
                         FROM MIGRATION.MIG_ACCRUE_TYPE_MAP m
                        WHERE m.ABYS_ACCRUE_TYPE_ID = r.ABYS_ACCRUE_TYPE_ID),
                      'ACCRUE=' || TO_CHAR(r.ABYS_ACCRUE_TYPE_ID))
             ELSE NULL
           END, 1, 50) AS VARCHAR2(50))              AS ROUTE_GRP
FROM MIGRATION.LS_READING r
LEFT JOIN SMS.CS_READING_END_OF_DAY e
  ON e.ID = r.ABYS_READING_END_OF_DAY_ID;

CREATE INDEX MIGRATION.IX_TMP_HHD_TRAN_LREF ON MIGRATION.TMP_HHD_TRAN_KEY (LREF) PARALLEL 56 NOLOGGING;
CREATE INDEX MIGRATION.IX_TMP_HHD_TRAN_EOD  ON MIGRATION.TMP_HHD_TRAN_KEY (ENDOFDAY_ID) PARALLEL 56 NOLOGGING;
CREATE INDEX MIGRATION.IX_TMP_HHD_TRAN_KEY  ON MIGRATION.TMP_HHD_TRAN_KEY (LOC_REGION, READ_DATE_DAY, READER_PRSNL_ID, EOD_OK) PARALLEL 56 NOLOGGING;
ALTER INDEX MIGRATION.IX_TMP_HHD_TRAN_LREF NOPARALLEL;
ALTER INDEX MIGRATION.IX_TMP_HHD_TRAN_EOD  NOPARALLEL;
ALTER INDEX MIGRATION.IX_TMP_HHD_TRAN_KEY  NOPARALLEL;

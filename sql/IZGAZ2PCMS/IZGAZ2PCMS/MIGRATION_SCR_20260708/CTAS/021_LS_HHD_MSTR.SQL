-- =============================================================================
-- 2) Birlesik mstr + READ_NO
-- =============================================================================
BEGIN EXECUTE IMMEDIATE 'DROP TABLE MIGRATION.LS_OV_HHD_MSTR PURGE';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
CREATE TABLE MIGRATION.LS_OV_HHD_MSTR NOLOGGING PARALLEL 56 AS
SELECT
    CAST(
      ROW_NUMBER() OVER (
        -- READ_NO = READ_DATE sirali (birebir energy IDENTITY_INSERT)
        ORDER BY x.READ_DATE,
                 x.HAS_EOD DESC,
                 x.ENDOFDAY_ID NULLS LAST,
                 x.READER_REGION,
                 x.READER_PRSNL_ID,
                 NVL(x.READER_PRSNL, CHR(0)),
                 NVL(x.IS_SYNTH, 0),
                 NVL(x.ABYS_ACCRUE_TYPE_ID, -1),
                 NVL(x.ROUTE_GRP, CHR(0))
      ) AS NUMBER(10)
    ) AS READ_NO,
    x.ENDOFDAY_ID,
    x.READER_REGION,
    x.READER_CMP,
    x.READ_DATE,
    x.READER_PRSNL,
    x.READER_PRSNL_ID,
    x.TOTAL_COUNT,
    x.NOTREAD_COUNT,
    x.HAS_EOD,
    x.REC_STATUS,
    x.READING_TYPE,
    x.ABYS_ACCRUE_TYPE_ID,
    x.ROUTE_GRP,
    x.IS_SYNTH,
    x.KIND AS OV_KIND
FROM (
    SELECT
        ENDOFDAY_ID, READER_REGION, READER_CMP, READ_DATE, READER_PRSNL, READER_PRSNL_ID,
        TOTAL_COUNT, NOTREAD_COUNT, HAS_EOD, REC_STATUS, READING_TYPE,
        ABYS_ACCRUE_TYPE_ID, ROUTE_GRP, IS_SYNTH,
        CAST('EOD' AS VARCHAR2(10)) AS KIND
    FROM MIGRATION.LS_OV_HHD_MSTR_EOD
    UNION ALL
    SELECT
        ENDOFDAY_ID, READER_REGION, READER_CMP, READ_DATE, READER_PRSNL, READER_PRSNL_ID,
        TOTAL_COUNT, NOTREAD_COUNT, HAS_EOD, REC_STATUS, READING_TYPE,
        ABYS_ACCRUE_TYPE_ID, ROUTE_GRP, IS_SYNTH,
        CAST('ORPHAN' AS VARCHAR2(10)) AS KIND
    FROM MIGRATION.LS_OV_HHD_MSTR_ORPHAN
) x;

CREATE UNIQUE INDEX MIGRATION.UX_OV_HHD_MSTR_RN
  ON MIGRATION.LS_OV_HHD_MSTR (READ_NO) PARALLEL 56 NOLOGGING;
CREATE INDEX MIGRATION.IX_OV_HHD_MSTR_EOD
  ON MIGRATION.LS_OV_HHD_MSTR (ENDOFDAY_ID) PARALLEL 56 NOLOGGING;
CREATE INDEX MIGRATION.IX_OV_HHD_MSTR_KEY
  ON MIGRATION.LS_OV_HHD_MSTR (READER_REGION, READ_DATE, READER_PRSNL_ID, HAS_EOD) PARALLEL 56 NOLOGGING;
ALTER INDEX MIGRATION.UX_OV_HHD_MSTR_RN NOPARALLEL;
ALTER INDEX MIGRATION.IX_OV_HHD_MSTR_EOD NOPARALLEL;
ALTER INDEX MIGRATION.IX_OV_HHD_MSTR_KEY NOPARALLEL;
BEGIN DBMS_STATS.GATHER_TABLE_STATS('MIGRATION','LS_OV_HHD_MSTR'); END;

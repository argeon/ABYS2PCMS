-- =============================================================================
-- 1A) EOD'li mstr grain  (ENDOFDAY_ID; READ_DATE = gun)
-- =============================================================================
BEGIN EXECUTE IMMEDIATE 'DROP TABLE MIGRATION.LS_OV_HHD_MSTR_EOD PURGE';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
CREATE TABLE MIGRATION.LS_OV_HHD_MSTR_EOD NOLOGGING PARALLEL 56 AS
SELECT
    CAST(trn.ENDOFDAY_ID AS NUMBER(18))           AS ENDOFDAY_ID,
    CAST(trn.LOC_REGION AS NUMBER(10))            AS READER_REGION,
    CAST(0 AS NUMBER(10))                         AS READER_CMP,
    TRUNC(MIN(trn.READ_DATE))                     AS READ_DATE,
    trn.READER_PRSNL                              AS READER_PRSNL,
    CAST(trn.READER_PRSNL_ID AS NUMBER(10))       AS READER_PRSNL_ID,
    CAST(COUNT(*) AS NUMBER(10))                  AS TOTAL_COUNT,
    CAST(0 AS NUMBER(10))                         AS NOTREAD_COUNT,
    CAST(1 AS NUMBER(1))                          AS HAS_EOD,
    CAST(3 AS NUMBER(5))                          AS REC_STATUS,
    CAST(0 AS NUMBER(10))                         AS READING_TYPE,
    CAST(NULL AS NUMBER(10))                      AS ABYS_ACCRUE_TYPE_ID,
    CAST(NULL AS VARCHAR2(50))                    AS ROUTE_GRP,
    CAST(0 AS NUMBER(1))                          AS IS_SYNTH
FROM MIGRATION.TMP_HHD_TRAN_KEY trn
WHERE trn.EOD_OK = 1
  AND trn.ENDOFDAY_ID IS NOT NULL
  AND trn.LOC_REGION IS NOT NULL
  AND trn.READ_DATE IS NOT NULL
  AND trn.READER_PRSNL_ID IS NOT NULL
GROUP BY trn.ENDOFDAY_ID, trn.LOC_REGION, trn.READER_PRSNL, trn.READER_PRSNL_ID;

BEGIN DBMS_STATS.GATHER_TABLE_STATS('MIGRATION','LS_OV_HHD_MSTR_EOD'); END;

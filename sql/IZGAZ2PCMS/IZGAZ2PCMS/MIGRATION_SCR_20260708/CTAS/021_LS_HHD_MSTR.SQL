/
CREATE TABLE MIGRATION.LS_OV_HHD_MSTR_ORPHAN NOLOGGING PARALLEL 56 AS
SELECT
    CAST(NULL AS NUMBER(18))                      AS ENDOFDAY_ID,
    CAST(trn.LOC_REGION AS NUMBER(10))            AS READER_REGION,
    CAST(0 AS NUMBER(10))                         AS READER_CMP,
    trn.READ_DATE_DAY                             AS READ_DATE,
    trn.READER_PRSNL                              AS READER_PRSNL,
    CAST(trn.READER_PRSNL_ID AS NUMBER(10))       AS READER_PRSNL_ID,
    CAST(COUNT(*) AS NUMBER(10))                  AS TOTAL_COUNT,
    CAST(0 AS NUMBER(10))                         AS NOTREAD_COUNT,
    CAST(0 AS NUMBER(1))                          AS HAS_EOD,
    CAST(3 AS NUMBER(5))                          AS REC_STATUS,
    CAST(9 AS NUMBER(10))                         AS READING_TYPE,
    CAST(NULL AS NUMBER(10))                      AS ABYS_ACCRUE_TYPE_ID,
    CAST(NULL AS VARCHAR2(50))                    AS ROUTE_GRP,
    CAST(0 AS NUMBER(1))                          AS IS_SYNTH
FROM MIGRATION.TMP_HHD_TRAN_KEY trn
WHERE trn.EOD_OK = 0
  AND NVL(trn.IS_SYNTH, 0) = 0
  AND trn.LOC_REGION IS NOT NULL
  AND trn.READ_DATE_DAY IS NOT NULL
  AND trn.READER_PRSNL_ID IS NOT NULL
GROUP BY trn.LOC_REGION, trn.READ_DATE_DAY, trn.READER_PRSNL, trn.READER_PRSNL_ID
UNION ALL
SELECT
    CAST(NULL AS NUMBER(18))                      AS ENDOFDAY_ID,
    CAST(trn.LOC_REGION AS NUMBER(10))            AS READER_REGION,
    CAST(0 AS NUMBER(10))                         AS READER_CMP,
    trn.READ_DATE_DAY                             AS READ_DATE,
    trn.READER_PRSNL                              AS READER_PRSNL,
    CAST(trn.READER_PRSNL_ID AS NUMBER(10))       AS READER_PRSNL_ID,
    CAST(COUNT(*) AS NUMBER(10))                  AS TOTAL_COUNT,
    CAST(0 AS NUMBER(10))                         AS NOTREAD_COUNT,
    CAST(0 AS NUMBER(1))                          AS HAS_EOD,
    CAST(3 AS NUMBER(5))                          AS REC_STATUS,
    CAST(9 AS NUMBER(10))                         AS READING_TYPE,
    CAST(trn.ABYS_ACCRUE_TYPE_ID AS NUMBER(10))   AS ABYS_ACCRUE_TYPE_ID,
    MAX(trn.ROUTE_GRP)                            AS ROUTE_GRP,
    CAST(1 AS NUMBER(1))                          AS IS_SYNTH

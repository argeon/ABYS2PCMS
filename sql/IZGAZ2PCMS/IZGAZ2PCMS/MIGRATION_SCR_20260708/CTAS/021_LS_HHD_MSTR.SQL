-- =============================================================================
-- 3) Detay → READ_NO map
--    EOD    : ENDOFDAY_ID + okuyucu key
--    ORPHAN : TRUNC(READ_DATE) + okuyucu key
-- =============================================================================
BEGIN EXECUTE IMMEDIATE 'DROP TABLE MIGRATION.LS_OV_HHD_TRAN_MAP PURGE';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
CREATE TABLE MIGRATION.LS_OV_HHD_TRAN_MAP NOLOGGING PARALLEL 56 AS
SELECT /*+ PARALLEL(56) */
    d.LREF AS SRC_LREF,
    m.READ_NO,
    m.OV_KIND AS MAP_KIND,
    m.ENDOFDAY_ID,
    m.HAS_EOD
FROM MIGRATION.TMP_HHD_TRAN_KEY d
JOIN MIGRATION.LS_OV_HHD_MSTR m
  ON m.READER_REGION   = d.LOC_REGION
 AND m.READER_PRSNL_ID = d.READER_PRSNL_ID
 AND NVL(m.READER_PRSNL, CHR(0)) = NVL(d.READER_PRSNL, CHR(0))
 AND (
        (d.EOD_OK = 1 AND m.HAS_EOD = 1
         AND m.ENDOFDAY_ID = d.ENDOFDAY_ID)
     OR (d.EOD_OK = 0 AND m.HAS_EOD = 0 AND NVL(d.IS_SYNTH, 0) = 0
         AND m.READ_DATE = d.READ_DATE_DAY
         AND NVL(m.IS_SYNTH, 0) = 0)
     OR (d.EOD_OK = 0 AND m.HAS_EOD = 0 AND NVL(d.IS_SYNTH, 0) = 1
         AND m.READ_DATE = d.READ_DATE_DAY
         AND NVL(m.IS_SYNTH, 0) = 1
         AND NVL(m.ABYS_ACCRUE_TYPE_ID, -1) = NVL(d.ABYS_ACCRUE_TYPE_ID, -1))
     );

CREATE INDEX MIGRATION.IX_OV_HHD_TRAN_MAP
  ON MIGRATION.LS_OV_HHD_TRAN_MAP (SRC_LREF) PARALLEL 56 NOLOGGING;
ALTER INDEX MIGRATION.IX_OV_HHD_TRAN_MAP NOPARALLEL;
BEGIN DBMS_STATS.GATHER_TABLE_STATS('MIGRATION','LS_OV_HHD_TRAN_MAP'); END;

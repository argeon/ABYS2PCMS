ALTER SESSION ENABLE PARALLEL QUERY;
ALTER SESSION FORCE PARALLEL QUERY PARALLEL 56;
ALTER SESSION FORCE PARALLEL DML PARALLEL 56;

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TABLES
   WHERE OWNER = 'MIGRATION' AND TABLE_NAME = 'LS_INVOICE';
  IF n = 0 THEN
    RAISE_APPLICATION_ERROR(-20013, 'LS_INVOICE yok. Once 11_ls_invoice.sql');
  END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE MIGRATION.LS_MIG_AGR_LIST PURGE';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF;
END;
/
CREATE TABLE MIGRATION.LS_MIG_AGR_LIST NOLOGGING PARALLEL 56 AS
SELECT /*+ PARALLEL(56) */
    CAST(ABYS_AGREEMENT_ID AS NUMBER(12)) AS AGR_ID,
    CAST(COUNT(*) AS NUMBER(12))          AS INV_CNT,
    CAST(ROUND(SUM(PAYABLETOTAL), 3) AS NUMBER(18,3)) AS INV_SUM
FROM MIGRATION.LS_INVOICE
WHERE ABYS_AGREEMENT_ID IS NOT NULL
GROUP BY ABYS_AGREEMENT_ID;

ALTER TABLE MIGRATION.LS_MIG_AGR_LIST NOPARALLEL LOGGING;


SELECT COUNT(*) AS AGR_CNT, SUM(INV_CNT) AS INV_CNT FROM MIGRATION.LS_MIG_AGR_LIST;


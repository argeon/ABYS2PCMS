SELECT STEP_ID, STATUS, ROW_CNT, SUBSTR(NOTE,1,80) NOTE,
       TO_CHAR(LOG_TS,'YYYY-MM-DD HH24:MI:SS') LOG_TS
FROM (
  SELECT STEP_ID, STATUS, ROW_CNT, NOTE, LOG_TS, LOG_ID
  FROM MIGRATION.MIG_CTAS_LOG
  ORDER BY LOG_TS DESC, LOG_ID DESC
)
WHERE ROWNUM <= 30;


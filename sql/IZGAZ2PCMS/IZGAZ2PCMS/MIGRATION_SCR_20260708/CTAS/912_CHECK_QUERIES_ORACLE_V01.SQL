PROMPT ========== 6c) DEBT_PAID CLOSED / LASTPAIDDATE (O32) ==========
DECLARE
  n_col NUMBER;
  n_gap NUMBER;
  n_paid NUMBER;
  n_closed NUMBER;
  n_lpd NUMBER;
BEGIN
  SELECT COUNT(*) INTO n_col FROM ALL_TAB_COLUMNS
   WHERE OWNER='MIGRATION' AND TABLE_NAME='LS_OV_DEBT_PAID_UPD' AND COLUMN_NAME='LASTPAIDDATE';
  IF n_col = 0 THEN
    DBMS_OUTPUT.PUT_LINE('SKIP 6c: LASTPAIDDATE yok — @32_ls_ov_debt_paid_lastpaid.sql');
    RETURN;
  END IF;
  SELECT COUNT(*) INTO n_paid FROM MIGRATION.LS_OV_DEBT_PAID_UPD;
  SELECT COUNT(*) INTO n_closed FROM MIGRATION.LS_OV_DEBT_PAID_UPD WHERE CLOSED = 1;
  EXECUTE IMMEDIATE
    'SELECT COUNT(*) FROM MIGRATION.LS_OV_DEBT_PAID_UPD WHERE LASTPAIDDATE IS NOT NULL'
    INTO n_lpd;
  SELECT COUNT(*) INTO n_gap FROM ALL_TABLES
   WHERE OWNER='MIGRATION' AND TABLE_NAME='LS_OV_INV_PAY_GAP';
  IF n_gap > 0 THEN
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM MIGRATION.LS_OV_INV_PAY_GAP' INTO n_gap;
  ELSE
    n_gap := -1;
  END IF;
  DBMS_OUTPUT.PUT_LINE('DEBT_PAID=' || n_paid || ' CLOSED=' || n_closed
    || ' LPD=' || n_lpd || ' GAP=' || CASE WHEN n_gap < 0 THEN 'N/A' ELSE TO_CHAR(n_gap) END);
END;

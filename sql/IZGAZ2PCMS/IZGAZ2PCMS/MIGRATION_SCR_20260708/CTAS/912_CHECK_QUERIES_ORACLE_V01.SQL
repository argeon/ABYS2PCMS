PROMPT ========== 6c) EARLY_PAY — CTAS sonrasi SART (ghost=0 zorunlu) ==========
PROMPT ghost>0 → O30 ACTION_DATE<=PAY filtresi geri gelmis / ALLOC kacmis — DUMP YOK
PROMPT early_ok = MAIN.ACTION_DATE > PAY.ACTION_DATE ama ALLOC yazildi (beklenen, soft)
DECLARE
  n_tmp NUMBER;
  n_ghost NUMBER := -1;
  n_ok NUMBER := -1;
BEGIN
  SELECT COUNT(*) INTO n_tmp FROM ALL_TABLES
   WHERE OWNER='MIGRATION' AND TABLE_NAME='TMP_MIG_ACC';
  IF n_tmp = 0 THEN
    DBMS_OUTPUT.PUT_LINE('6c SKIP: TMP_MIG_ACC yok (O30 ayni oturumda kosulmali)');
    RETURN;
  END IF;
  EXECUTE IMMEDIATE q'[
    SELECT COUNT(DISTINCT pay.ID)
    FROM SMS.CS_ACCOUNT_ACTION pay
    JOIN MIGRATION.TMP_MIG_ACC m ON m.ACCOUNT_ID = pay.ACCOUNT_ID
    JOIN SMS.CS_ACTION_TYPE_PRM atp ON atp.ID = pay.ACTION_TYPE_ID AND atp.TYPE = 2
    WHERE pay.ACTION_TYPE_ID NOT IN (36, 37, 39, 44, 6, 24)
      AND NOT EXISTS (SELECT 1 FROM MIGRATION.TMP_PAY_CANCEL c WHERE c.PAY_ID = pay.ID)
      AND NOT EXISTS (SELECT 1 FROM MIGRATION.LS_OV_PAY_ALLOC a WHERE a.PAY_LREF = pay.ID)
      AND EXISTS (
            SELECT 1
            FROM SMS.CS_ACCOUNT_INCOME pi
            JOIN SMS.CS_ACCOUNT_INCOME gi ON gi.INCOME_ID = pi.INCOME_ID
            JOIN SMS.CS_ACCOUNT_ACTION g
              ON g.ID = gi.ACCOUNT_ACTION_ID
             AND g.ACCOUNT_ID = pay.ACCOUNT_ID
             AND g.ACTION_TYPE_ID IN (1, 3, 10, 41)
             AND g.ACTION_DATE > pay.ACTION_DATE
            WHERE pi.ACCOUNT_ACTION_ID = pay.ID
          )
  ]' INTO n_ghost;
  EXECUTE IMMEDIATE q'[
    SELECT COUNT(DISTINCT a.PAY_LREF)
    FROM MIGRATION.LS_OV_PAY_ALLOC a
    JOIN SMS.CS_ACCOUNT_ACTION pay ON pay.ID = a.PAY_LREF
    JOIN SMS.CS_ACCOUNT_ACTION main ON main.ID = a.MAIN_LREF
    WHERE main.ACTION_DATE > pay.ACTION_DATE
  ]' INTO n_ok;
  DBMS_OUTPUT.PUT_LINE('EARLY_PAY_GHOST=' || n_ghost || ' EARLY_PAY_ALLOC_OK=' || n_ok
    || CASE WHEN n_ghost = 0 THEN ' | SART_OK' ELSE ' | SART_FAIL — dump etme' END);
END;

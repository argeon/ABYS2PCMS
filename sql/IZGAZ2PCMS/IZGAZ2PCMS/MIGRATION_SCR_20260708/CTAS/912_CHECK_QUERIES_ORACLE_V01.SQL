PROMPT ========== 6c-spot) EARLY_PAY_GHOST ornek (max 20; bos olmali) ==========
PROMPT Not: TMP_MIG_ACC yoksa ORA-942 — O30 ayni oturumda kosulmali; O41 zaten hard fail eder
SELECT * FROM (
  SELECT pay.ID PAY_LREF, pay.ACCOUNT_ID, pay.ACTION_DATE PAY_AD,
         g.ID MAIN_LREF, g.ACTION_DATE MAIN_AD, g.ACTION_TYPE_ID MAIN_TIP
  FROM SMS.CS_ACCOUNT_ACTION pay
  JOIN MIGRATION.TMP_MIG_ACC m ON m.ACCOUNT_ID = pay.ACCOUNT_ID
  JOIN SMS.CS_ACTION_TYPE_PRM atp ON atp.ID = pay.ACTION_TYPE_ID AND atp.TYPE = 2
  JOIN SMS.CS_ACCOUNT_INCOME pi ON pi.ACCOUNT_ACTION_ID = pay.ID
  JOIN SMS.CS_ACCOUNT_INCOME gi ON gi.INCOME_ID = pi.INCOME_ID
  JOIN SMS.CS_ACCOUNT_ACTION g
    ON g.ID = gi.ACCOUNT_ACTION_ID
   AND g.ACCOUNT_ID = pay.ACCOUNT_ID
   AND g.ACTION_TYPE_ID IN (1, 3, 10, 41)
   AND g.ACTION_DATE > pay.ACTION_DATE
  WHERE pay.ACTION_TYPE_ID NOT IN (36, 37, 39, 44, 6, 24)
    AND NOT EXISTS (SELECT 1 FROM MIGRATION.TMP_PAY_CANCEL c WHERE c.PAY_ID = pay.ID)
    AND NOT EXISTS (SELECT 1 FROM MIGRATION.LS_OV_PAY_ALLOC a WHERE a.PAY_LREF = pay.ID)
  ORDER BY pay.ID
) WHERE ROWNUM <= 20;


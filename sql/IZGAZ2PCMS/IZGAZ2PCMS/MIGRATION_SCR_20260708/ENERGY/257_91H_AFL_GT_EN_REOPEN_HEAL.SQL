    RETURN;
END;

IF OBJECT_ID('dbo.MIG_AFL_GT_EN_REOPEN_LOG', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.MIG_AFL_GT_EN_REOPEN_LOG (
        LOG_ID          BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        RUN_ID          BIGINT         NOT NULL,
        SNAPSHOT_TS     DATETIME2(3)   NOT NULL,
        DRY_RUN         BIT            NOT NULL,
        AGREEMENT_ID    BIGINT         NULL,
        ACCOUNT_ID      BIGINT         NULL,
        MAIN_LREF       INT            NOT NULL,
        PT_LREF         INT            NOT NULL,
        PT_PAID_OLD     DECIMAL(18,2)  NULL,
        PT_PAID_NEW     DECIMAL(18,2)  NULL,
        APPLY_AMT       DECIMAL(18,2)  NULL,
        PT_KALAN_OLD    DECIMAL(18,2)  NULL,
        PT_PAYABLE      DECIMAL(18,2)  NULL,
        AFL_BALANCE     DECIMAL(18,2)  NULL,
        ACC_EN_KALAN    DECIMAL(18,2)  NULL,
        SHORTFALL       DECIMAL(18,2)  NULL,
        AGR_DELTA_NET   DECIMAL(18,2)  NULL,
        NOTE            NVARCHAR(80)   NULL
    );
    CREATE INDEX IX_AFL_GT_EN_REOPEN_RUN
        ON dbo.MIG_AFL_GT_EN_REOPEN_LOG (RUN_ID, DRY_RUN);
END;

/* Seed: AFL > EN on NET */
IF OBJECT_ID('tempdb..#AGR') IS NOT NULL DROP TABLE #AGR;
SELECT
    f.AGREEMENT_ID,
    CONVERT(DECIMAL(18,2), ISNULL(f.DELTA_KALAN_NET, 0)) AS DELTA_KALAN_NET
INTO #AGR
FROM dbo.MIG_AGR_FRK_ALL f WITH (NOLOCK)
WHERE ISNULL(f.DELTA_KALAN_NET, 0) < -@Eps
  AND (@Agr IS NULL OR f.AGREEMENT_ID = @Agr)
OPTION (RECOMPILE, MAXDOP 8);

CREATE CLUSTERED INDEX CX_AGR ON #AGR (AGREEMENT_ID);

SET @N = (SELECT COUNT(*) FROM #AGR);
SET @Msg = N'Seed AFL_GT_EN AGR n=' + CAST(@N AS VARCHAR(20))
         + N' sum_delta_net=' + CONVERT(VARCHAR(40),
                (SELECT CONVERT(DECIMAL(18,2), ISNULL(SUM(DELTA_KALAN_NET), 0)) FROM #AGR));
RAISERROR('%s', 0, 1, @Msg) WITH NOWAIT;

IF @N = 0
BEGIN
    RAISERROR('Seed bos — cikis.', 0, 1) WITH NOWAIT;
    RETURN;
END;

/* Tum borc PT (kalan 0 dahil — PAID geri almak icin) + AFL>eps */
IF OBJECT_ID('tempdb..#PT0') IS NOT NULL DROP TABLE #PT0;
SELECT
    CAST(ISNULL(inv.ABYS_AGREEMENT_ID, inv.OWNERREF) AS BIGINT) AS AGREEMENT_ID,
    CAST(inv.ABYS_ACCOUNT_ID AS BIGINT) AS ACCOUNT_ID,
    inv.LREF AS MAIN_LREF,
    pt.LREF AS PT_LREF,
    CONVERT(DECIMAL(18,2), ISNULL(pt.PAID, 0)) AS PT_PAID_OLD,
    CONVERT(DECIMAL(18,2), ISNULL(pt.PAYABLETOTAL, 0)) AS PT_PAYABLE,
    CONVERT(DECIMAL(18,2),
        ISNULL(pt.PAYABLETOTAL, 0) - ISNULL(pt.PAID, 0)) AS PT_KALAN,
    CONVERT(DECIMAL(18,2), ISNULL(a.BALANCE, 0)) AS AFL_BALANCE,
    g.DELTA_KALAN_NET AS AGR_DELTA_NET
INTO #PT0
FROM dbo.LS_005_01_INVOICE inv WITH (NOLOCK)
INNER JOIN #AGR g
    ON g.AGREEMENT_ID = CAST(ISNULL(inv.ABYS_AGREEMENT_ID, inv.OWNERREF) AS BIGINT)
INNER JOIN dbo.LS_005_01_PAYTRANS pt WITH (NOLOCK)
    ON pt.INVOICEREF = inv.LREF
   AND ISNULL(pt.IOCODE, 0) = 0
   AND ISNULL(pt.CANCELED, 0) = 0
   AND ISNULL(pt.CANCELLATIONPAYMENT, 0) = 0
INNER JOIN dbo.LS_AFL_OPEN_DEBT a WITH (NOLOCK)
    ON CAST(a.FATURAID AS BIGINT) = CAST(inv.ABYS_ACCOUNT_ID AS BIGINT)
WHERE ISNULL(inv.IOCODE, 0) = 0
  AND ISNULL(inv.CANCELED, 0) = 0
  AND inv.ABYS_ACCOUNT_ID IS NOT NULL
  AND CONVERT(DECIMAL(18,2), ISNULL(a.BALANCE, 0)) > @Eps
  AND CONVERT(DECIMAL(18,2), ISNULL(pt.PAYABLETOTAL, 0)) > @Eps
OPTION (RECOMPILE, MAXDOP 8);

CREATE CLUSTERED INDEX CX_PT0 ON #PT0 (ACCOUNT_ID, PT_LREF);

/* Hesap shortfall */
IF OBJECT_ID('tempdb..#ACC') IS NOT NULL DROP TABLE #ACC;
SELECT
    ACCOUNT_ID,
    MAX(AFL_BALANCE) AS AFL_BALANCE,
    CONVERT(DECIMAL(18,2), SUM(PT_KALAN)) AS ACC_EN_KALAN,
    CONVERT(DECIMAL(18,2), MAX(AFL_BALANCE) - SUM(PT_KALAN)) AS SHORTFALL,
    CONVERT(DECIMAL(18,2), SUM(CASE WHEN PT_PAID_OLD > 0 THEN PT_PAID_OLD ELSE 0 END)) AS ACC_PAID_ROOM
INTO #ACC
FROM #PT0
GROUP BY ACCOUNT_ID
HAVING CONVERT(DECIMAL(18,2), MAX(AFL_BALANCE) - SUM(PT_KALAN)) > @Eps;

CREATE CLUSTERED INDEX CX_ACC ON #ACC (ACCOUNT_ID);

SET @Msg = N'ACC shortfall n=' + CAST((SELECT COUNT(*) FROM #ACC) AS VARCHAR(20))
         + N' sum_shortfall=' + CONVERT(VARCHAR(40),
                (SELECT CONVERT(DECIMAL(18,2), ISNULL(SUM(SHORTFALL), 0)) FROM #ACC))
         + N' sum_paid_room=' + CONVERT(VARCHAR(40),
                (SELECT CONVERT(DECIMAL(18,2), ISNULL(SUM(ACC_PAID_ROOM), 0)) FROM #ACC));
RAISERROR('%s', 0, 1, @Msg) WITH NOWAIT;

SELECT COUNT(*) AS ACC_ROOM_LT_SHORTFALL
FROM #ACC
WHERE ACC_PAID_ROOM + @Eps < SHORTFALL;

/* FIFO DESC: PAID odasindan shortfall dagit */
IF OBJECT_ID('tempdb..#CAND') IS NOT NULL DROP TABLE #CAND;
;WITH x AS (
    SELECT
        p.AGREEMENT_ID,
        p.ACCOUNT_ID,
        p.MAIN_LREF,
        p.PT_LREF,
        p.PT_PAID_OLD,
        p.PT_PAYABLE,
        p.PT_KALAN AS PT_KALAN_OLD,
        a.AFL_BALANCE,
        a.ACC_EN_KALAN,
        a.SHORTFALL,
        p.AGR_DELTA_NET,
        CONVERT(DECIMAL(18,2), CASE WHEN p.PT_PAID_OLD > 0 THEN p.PT_PAID_OLD ELSE 0 END) AS PAID_ROOM,
        CONVERT(DECIMAL(18,2),
            SUM(CASE WHEN p.PT_PAID_OLD > 0 THEN p.PT_PAID_OLD ELSE 0 END) OVER (
                PARTITION BY p.ACCOUNT_ID
                ORDER BY p.PT_LREF DESC
                ROWS UNBOUNDED PRECEDING
            ) - CASE WHEN p.PT_PAID_OLD > 0 THEN p.PT_PAID_OLD ELSE 0 END
        ) AS RUN_BEFORE
    FROM #PT0 p
    INNER JOIN #ACC a ON a.ACCOUNT_ID = p.ACCOUNT_ID
)
SELECT
    AGREEMENT_ID,
    ACCOUNT_ID,
    MAIN_LREF,
    PT_LREF,
    PT_PAID_OLD,
    PT_PAYABLE,
    PT_KALAN_OLD,
    AFL_BALANCE,
    ACC_EN_KALAN,
    SHORTFALL,
    AGR_DELTA_NET,
    PAID_ROOM,
    RUN_BEFORE,
    CONVERT(DECIMAL(18,2),
        CASE
            WHEN PAID_ROOM <= 0 THEN 0
            WHEN RUN_BEFORE >= SHORTFALL THEN 0
            WHEN RUN_BEFORE + PAID_ROOM <= SHORTFALL THEN PAID_ROOM
            ELSE SHORTFALL - RUN_BEFORE
        END
    ) AS APPLY_AMT
INTO #CAND
FROM x
OPTION (RECOMPILE, MAXDOP 8);

DELETE FROM #CAND WHERE APPLY_AMT <= @Eps;

CREATE CLUSTERED INDEX CX_CAND ON #CAND (PT_LREF);

IF OBJECT_ID('tempdb..#APPLY') IS NOT NULL DROP TABLE #APPLY;
SELECT
    c.*,
    CONVERT(DECIMAL(18,2), c.PT_PAID_OLD - c.APPLY_AMT) AS PT_PAID_NEW
INTO #APPLY
FROM #CAND c;

CREATE CLUSTERED INDEX CX_APPLY ON #APPLY (PT_LREF);

SET @N = (SELECT COUNT(*) FROM #APPLY);
SET @Msg = N'Aday PT reopen n=' + CAST(@N AS VARCHAR(20))
         + N' ACC=' + CAST((SELECT COUNT(DISTINCT ACCOUNT_ID) FROM #APPLY) AS VARCHAR(20))
         + N' AGR=' + CAST((SELECT COUNT(DISTINCT AGREEMENT_ID) FROM #APPLY) AS VARCHAR(20))
         + N' sum_apply=' + CONVERT(VARCHAR(40),
                (SELECT CONVERT(DECIMAL(18,2), ISNULL(SUM(APPLY_AMT), 0)) FROM #APPLY));
RAISERROR('%s', 0, 1, @Msg) WITH NOWAIT;


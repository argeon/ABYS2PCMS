SELECT TOP 30
    a.AGREEMENT_ID, a.ACCOUNT_ID, a.MAIN_LREF, a.PT_LREF,
    a.APPLY_AMT, a.AFL_BALANCE, a.SHORTFALL,
    CONVERT(DECIMAL(18,2), ISNULL(pt.PAID, 0)) AS PT_PAID_NOW,
    CONVERT(DECIMAL(18,2), ISNULL(pt.PAYABLETOTAL, 0)) AS PT_PAYABLE,
    CONVERT(DECIMAL(18,2),
        ISNULL(pt.PAYABLETOTAL, 0) - ISNULL(pt.PAID, 0)) AS PT_KALAN_NOW,
    ISNULL(inv.CLOSED, 0) AS MAIN_CLOSED_NOW
FROM #APPLY a
INNER JOIN dbo.LS_005_01_PAYTRANS pt WITH (NOLOCK) ON pt.LREF = a.PT_LREF
INNER JOIN dbo.LS_005_01_INVOICE inv WITH (NOLOCK) ON inv.LREF = a.MAIN_LREF
ORDER BY a.APPLY_AMT DESC;

SET @Msg = CONVERT(VARCHAR(30), SYSDATETIME(), 121)
         + N' | 91h DONE apply RunId=' + CONVERT(VARCHAR(30), @RunId);

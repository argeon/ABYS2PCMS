/* =============================================================================
   FILE : prodEnergy/90_afl_frk/91h_afl_gt_en_reopen_heal.sql
   PATCH (cutover EXEC zincirine KOYMA) — AFL>EN reopen (PAID geri al)

   Cutover AFL taban: hesapta AFL.BALANCE > eps iken EN_KALAN >= AFL.
   EN << AFL (over-close) → PAID azalt; INV CLOSED=0.

   Seed : MIG_AGR_FRK_ALL.DELTA_KALAN_NET < -@Eps
   Grain: ABYS_ACCOUNT_ID = FATURAID
   SHORTFALL = AFL_BALANCE - SUM(PT_KALAN)
   FIFO ters (PT.LREF DESC): PAID basindan geri al
     APPLY = min(PAID, kalan shortfall)
     PAID_NEW = PAID_OLD - APPLY
   INV: reopen sonrasi PT kalan > eps → CLOSED=0

   YAPMAZ:
     EN>AFL close → 91f / 91g
     CP=1 / CANCELED / IOCODE<>0
     PAID < 0

   Onkosul: MIG_AGR_FRK_ALL guncel + LS_AFL_OPEN_DEBT
   Default @DryRun=1 — once spot @Agr sonra SEED
   ============================================================================= */

ORDER BY APPLY_AMT DESC, AGREEMENT_ID, ACCOUNT_ID, PT_LREF;

INSERT INTO dbo.MIG_AFL_GT_EN_REOPEN_LOG (
    RUN_ID, SNAPSHOT_TS, DRY_RUN, AGREEMENT_ID, ACCOUNT_ID,
    MAIN_LREF, PT_LREF, PT_PAID_OLD, PT_PAID_NEW, APPLY_AMT,
    PT_KALAN_OLD, PT_PAYABLE, AFL_BALANCE, ACC_EN_KALAN, SHORTFALL,
    AGR_DELTA_NET, NOTE
)
SELECT
    @RunId, @t0, @DryRun, AGREEMENT_ID, ACCOUNT_ID,
    MAIN_LREF, PT_LREF, PT_PAID_OLD, PT_PAID_NEW, APPLY_AMT,
    PT_KALAN_OLD, PT_PAYABLE, AFL_BALANCE, ACC_EN_KALAN, SHORTFALL,
    AGR_DELTA_NET,
    CASE WHEN @DryRun = 1 THEN N'DRY_RUN' ELSE N'APPLY_91h' END
FROM #APPLY;

IF @N = 0
BEGIN

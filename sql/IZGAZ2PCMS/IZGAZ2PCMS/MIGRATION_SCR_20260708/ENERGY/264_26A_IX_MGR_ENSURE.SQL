   CREATE OR ALTER PROCEDURE dbo.SP_MIG_IX_MGR_ENSURE  (R22 2026-08-11)

   Kritik MGR IX yoksa CREATE (idempotent). FULL 00_pre yerine P0 gate seti.
   EXEC dbo.SP_MIG_IX_MGR_ENSURE @DEBUG=1;
   Sonra: EXEC dbo.SP_MIG_IX_PRECHECK;

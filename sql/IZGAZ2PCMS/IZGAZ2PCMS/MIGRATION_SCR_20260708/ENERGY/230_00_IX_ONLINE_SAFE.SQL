DECLARE @ord INT = 1, @max INT, @t SYSNAME, @ix SYSNAME, @ddl NVARCHAR(MAX);
SELECT @max = MAX(ORD) FROM @Jobs;

WHILE @ord <= @max
BEGIN
    SELECT @t = TNAME, @ix = IXNAME, @ddl = DDL FROM @Jobs WHERE ORD = @ord;

    IF OBJECT_ID(N'dbo.' + @t, N'U') IS NULL
        SET @msg = N'SKIP no table: ' + @t;
    ELSE IF EXISTS (SELECT 1 FROM @Loading WHERE TNAME = @t)
        SET @msg = N'SKIP loading: ' + @t + N'.' + @ix;
    ELSE IF EXISTS (
        SELECT 1 FROM sys.indexes i
        WHERE i.object_id = OBJECT_ID(N'dbo.' + @t) AND i.name = @ix
    )
        SET @msg = N'EXISTS: ' + @t + N'.' + @ix;
    ELSE IF @t = N'LS_INVOICE' AND @ix = N'IX_MIG_LSINV_ACCOUNT'
         AND COL_LENGTH(N'dbo.LS_INVOICE', N'ABYS_ACCOUNT_ID') IS NULL
        SET @msg = N'SKIP no col ACCOUNT: ' + @ix;
    ELSE IF @t = N'LS_OV_KISMI_INVLINES' AND @ix = N'IX_MIG_LS_OV_KISMI_INVLINES_INC'
         AND COL_LENGTH(N'dbo.LS_OV_KISMI_INVLINES', N'ABYS_INCOME_ID') IS NULL
        SET @msg = N'SKIP no col INC: ' + @ix;
    ELSE
    BEGIN
        SET @msg = N'CREATE: ' + @t + N'.' + @ix;
        RAISERROR(N'%s', 0, 1, @msg) WITH NOWAIT;
        BEGIN TRY
            EXEC sp_executesql @ddl;
            SET @msg = N'OK: ' + @t + N'.' + @ix;
        END TRY
        BEGIN CATCH
            SET @msg = N'FAIL: ' + @t + N'.' + @ix + N' | ' + ERROR_MESSAGE();
        END CATCH
    END

    RAISERROR(N'%s', 0, 1, @msg) WITH NOWAIT;
    SET @ord += 1;
END


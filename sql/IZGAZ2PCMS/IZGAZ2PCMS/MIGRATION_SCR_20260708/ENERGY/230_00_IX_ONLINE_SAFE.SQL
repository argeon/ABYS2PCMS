INSERT INTO @Loading (TNAME)
SELECT DISTINCT
    CASE
        WHEN qt.text LIKE N'%LS_OV_TAH_INVOICE%' THEN N'LS_OV_TAH_INVOICE'
        WHEN qt.text LIKE N'%LS_INVLINES%' THEN N'LS_INVLINES'
        WHEN qt.text LIKE N'%LS_INVOICE%' AND qt.text NOT LIKE N'%INVLINES%' THEN N'LS_INVOICE'
        WHEN qt.text LIKE N'%LS_OV_PAY_PT%' THEN N'LS_OV_PAY_PT'
        WHEN qt.text LIKE N'%LS_OV_PAY_ALLOC%' THEN N'LS_OV_PAY_ALLOC'
        WHEN qt.text LIKE N'%LS_OV_ID_MAP%' THEN N'LS_OV_ID_MAP'

-- SMS BANK_ID → energy.dbo.LS_BANK.LREF  (3007: AGR veya NO_AGR=-1)
--
-- Kaynak (oncelik):
--   PAY_PT tahsilat ← LS_PAYMENT.BANKA_ID  (SMS BANK_ID; tercih)
--                  ← LS_OV_PAY_PT.BANKREF  (fallback)
--   TAH TYPE=101  ← LS_OV_TAH_INVOICE.BANKREF
--   MAIN INV      ← LS_INVOICE.BANKREF
--   debt PT       ← LS_DEBT_PAYTRANS.BANKREF + parent INV senkron
--   IPP           ← LS_INSTALLMENT_PLAN.BANKREF
--
-- Cift resolve YASAK: ABYS_ID → LREF bir kez (21→5 FINS sonra 5→45 VAKIF olmaz).
-- HATA (eski): "BANKREF henuz LREF degil" filtresi ABYS/LREF cakismasinda yanlis banka.
--
-- Onkosul: 121 (LS_BANK.ABYS_ID), 571/597, izgazMGR erisim
-- @DRY_RUN=1 sayim; 0=APPLY
-- @AGR_ID: NULL=FULL | >0=AGR | -1=NO_AGR (NULL AGR + ACCOUNT)
-- =============================================================================

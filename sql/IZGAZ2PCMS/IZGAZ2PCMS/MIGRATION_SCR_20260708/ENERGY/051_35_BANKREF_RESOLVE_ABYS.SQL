/* ---- PT debt: MGR LS_DEBT_PAYTRANS ---- */
IF OBJECT_ID(N'izgazMGR.dbo.LS_DEBT_PAYTRANS', N'U') IS NOT NULL
BEGIN
    SET @sql = N'
UPDATE e
SET e.BANKREF = b.LREF
FROM dbo.' + QUOTENAME(@Pt) + N' e
INNER JOIN izgazMGR.dbo.LS_DEBT_PAYTRANS m ON m.ABYS_ID = e.ABYS_ID
INNER JOIN dbo.LS_BANK b ON b.ABYS_ID = m.BANKREF
'
+ CASE
    WHEN @AGR_ID IS NULL THEN N''
    ELSE N'INNER JOIN dbo.' + QUOTENAME(@Inv) + N' inv ON inv.LREF = e.INVOICEREF
'
  END +
N'WHERE m.BANKREF IS NOT NULL
  AND e.ABYS_ID IS NOT NULL
  AND (e.BANKREF IS NULL OR e.BANKREF <> b.LREF)
'
+ CASE
    WHEN @AGR_ID IS NULL THEN N''
    WHEN @AGR_ID = -1 THEN N'  AND (inv.ABYS_AGREEMENT_ID IS NULL AND inv.ABYS_ACCOUNT_ID IS NOT NULL
       OR m.ABYS_AGREEMENT_ID IS NULL)
'
    ELSE N'  AND (inv.OWNERREF = @AGR OR inv.ABYS_AGREEMENT_ID = @AGR OR m.ABYS_AGREEMENT_ID = @AGR)
'
  END + N'
OPTION (MAXDOP 8);';
    EXEC sp_executesql @sql, N'@AGR BIGINT', @AGR = @AGR_ID;
    SET @nPtMap = @nPtMap + @@ROWCOUNT;
END


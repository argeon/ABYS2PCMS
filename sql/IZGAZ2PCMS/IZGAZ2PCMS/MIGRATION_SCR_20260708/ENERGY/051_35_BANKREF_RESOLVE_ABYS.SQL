/* ---- debt PT: parent INV bankasi (MGR yoksa / bos) ---- */
SET @sql = N'
UPDATE d
SET d.BANKREF = inv.BANKREF
FROM dbo.' + QUOTENAME(@Pt) + N' d
INNER JOIN dbo.' + QUOTENAME(@Inv) + N' inv ON inv.LREF = d.INVOICEREF
WHERE inv.BANKREF IS NOT NULL
  AND (d.BANKREF IS NULL OR d.BANKREF <> inv.BANKREF)
  AND d.IOCODE = 0
  AND (
    @AGR IS NULL
    OR (@AGR = -1 AND inv.ABYS_AGREEMENT_ID IS NULL AND inv.ABYS_ACCOUNT_ID IS NOT NULL)
    OR (@AGR > 0 AND (inv.OWNERREF = @AGR OR inv.ABYS_AGREEMENT_ID = @AGR))
  )
OPTION (MAXDOP 8);';
EXEC sp_executesql @sql, N'@AGR BIGINT', @AGR = @AGR_ID;
SET @nPtMap = @nPtMap + @@ROWCOUNT;


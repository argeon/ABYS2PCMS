/* ---- TAH TYPE=101: LS_OV_TAH_INVOICE (OR join YASAK: LREF sonra ABYS) ---- */
SET @nTahMap = 0;
IF OBJECT_ID(N'izgazMGR.dbo.LS_OV_TAH_INVOICE', N'U') IS NOT NULL
BEGIN
    SET @sql = N'
UPDATE e
SET e.BANKREF = b.LREF
FROM dbo.' + QUOTENAME(@Inv) + N' e

    OR (@AGR > 0 AND (p.SOZLESME = @AGR OR e.ABYS_AGREEMENT_ID = @AGR))
  );';
    EXEC sp_executesql @sql,
        N'@AGR BIGINT, @nOk INT OUTPUT, @nBad INT OUTPUT',
        @AGR = @AGR_ID, @nOk = @nPayOk OUTPUT, @nBad = @nPayBad OUTPUT;

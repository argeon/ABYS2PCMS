INNER JOIN dbo.LS_BANK b ON b.ABYS_ID = TRY_CAST(LTRIM(RTRIM(CONVERT(NVARCHAR(20), t.BANKREF))) AS INT)
WHERE t.BANKREF IS NOT NULL
  AND ISNULL(e.TYPE, 0) = 101
  AND (e.BANKREF IS NULL OR e.BANKREF <> b.LREF)
  AND (
    @AGR IS NULL
    OR (@AGR = -1 AND e.ABYS_AGREEMENT_ID IS NULL AND e.ABYS_ACCOUNT_ID IS NOT NULL)
    OR (@AGR > 0 AND (e.OWNERREF = @AGR OR e.ABYS_AGREEMENT_ID = @AGR OR t.ABYS_AGREEMENT_ID = @AGR))
  )
OPTION (MAXDOP 8);';
    EXEC sp_executesql @sql, N'@AGR BIGINT', @AGR = @AGR_ID;
    SET @nTahMap = @@ROWCOUNT;

    SET @sql = N'
UPDATE e
SET e.BANKREF = b.LREF
FROM dbo.' + QUOTENAME(@Inv) + N' e
INNER JOIN izgazMGR.dbo.LS_OV_TAH_INVOICE t WITH (NOLOCK) ON t.ABYS_ID = e.ABYS_ID
INNER JOIN dbo.LS_BANK b ON b.ABYS_ID = TRY_CAST(LTRIM(RTRIM(CONVERT(NVARCHAR(20), t.BANKREF))) AS INT)
WHERE t.ABYS_ID IS NOT NULL
  AND t.BANKREF IS NOT NULL
  AND e.ABYS_ID IS NOT NULL
  AND ISNULL(e.TYPE, 0) = 101
  AND (e.BANKREF IS NULL OR e.BANKREF <> b.LREF)
  AND (
    @AGR IS NULL
    OR (@AGR = -1 AND e.ABYS_AGREEMENT_ID IS NULL AND e.ABYS_ACCOUNT_ID IS NOT NULL)
    OR (@AGR > 0 AND (e.OWNERREF = @AGR OR e.ABYS_AGREEMENT_ID = @AGR OR t.ABYS_AGREEMENT_ID = @AGR))
  )
OPTION (MAXDOP 8);';
    EXEC sp_executesql @sql, N'@AGR BIGINT', @AGR = @AGR_ID;
    SET @nTahMap = @nTahMap + @@ROWCOUNT;
END

/* ---- PT tahsilat: LS_PAYMENT.BANKA_ID (AGR→SOZLESME SARG) ---- */
SET @nPtMap = 0;
IF OBJECT_ID(N'izgazMGR.dbo.LS_PAYMENT', N'U') IS NOT NULL
BEGIN
    IF @AGR_ID > 0
        SET @sql = N'
UPDATE e
SET e.BANKREF = b.LREF
FROM dbo.' + QUOTENAME(@Pt) + N' e
INNER JOIN izgazMGR.dbo.LS_PAYMENT p WITH (NOLOCK)
    ON p.PAY_LREF = e.ABYS_ID AND p.SOZLESME = @AGR
INNER JOIN dbo.LS_BANK b ON b.ABYS_ID = p.BANKA_ID
WHERE p.BANKA_ID IS NOT NULL
  AND ISNULL(p.CANCELED, 0) = 0
  AND e.ABYS_ID IS NOT NULL
  AND e.ABYS_AGREEMENT_ID = @AGR
  AND (e.BANKREF IS NULL OR e.BANKREF <> b.LREF)
OPTION (MAXDOP 8);';
    ELSE IF @AGR_ID = -1
        SET @sql = N'
UPDATE e
SET e.BANKREF = b.LREF
FROM dbo.' + QUOTENAME(@Pt) + N' e
INNER JOIN izgazMGR.dbo.LS_PAYMENT p WITH (NOLOCK) ON p.PAY_LREF = e.ABYS_ID
INNER JOIN dbo.LS_BANK b ON b.ABYS_ID = p.BANKA_ID
WHERE p.BANKA_ID IS NOT NULL
  AND ISNULL(p.CANCELED, 0) = 0
  AND e.ABYS_ID IS NOT NULL
  AND e.ABYS_AGREEMENT_ID IS NULL
  AND (e.BANKREF IS NULL OR e.BANKREF <> b.LREF)
OPTION (MAXDOP 8);';
    ELSE
        SET @sql = N'
UPDATE e
SET e.BANKREF = b.LREF
FROM dbo.' + QUOTENAME(@Pt) + N' e
INNER JOIN izgazMGR.dbo.LS_PAYMENT p WITH (NOLOCK) ON p.PAY_LREF = e.ABYS_ID
INNER JOIN dbo.LS_BANK b ON b.ABYS_ID = p.BANKA_ID
WHERE p.BANKA_ID IS NOT NULL
  AND ISNULL(p.CANCELED, 0) = 0
  AND e.ABYS_ID IS NOT NULL
  AND (e.BANKREF IS NULL OR e.BANKREF <> b.LREF)
OPTION (MAXDOP 8);';

    EXEC sp_executesql @sql, N'@AGR BIGINT', @AGR = @AGR_ID;
    SET @nPayMap = @@ROWCOUNT;
    SET @nPtMap = @nPtMap + @nPayMap;

   AND COL_LENGTH(N'dbo.' + @Prefix + N'_INSTALLMENT_PLAN', 'BANKREF') IS NOT NULL
   AND OBJECT_ID(N'izgazMGR.dbo.LS_INSTALLMENT_PLAN', N'U') IS NOT NULL

    OR (@AGR = -1 AND e.ABYS_AGREEMENT_ID IS NULL AND e.ABYS_ACCOUNT_ID IS NOT NULL)
    OR (@AGR > 0 AND (e.OWNERREF = @AGR OR e.ABYS_AGREEMENT_ID = @AGR OR m.ABYS_AGREEMENT_ID = @AGR))

/* =============================================================================
   prodREADY_ENERGY / 20d_597_LOADED_MAP_HEAL.sql
   R09: MAP dolu / PT var ama STG_PAY.LOADED=0 orphan sync
   Onkosul: MIG_597_STG_PAY + MIG_OV_ID_MAP PAY_PT mevcut (kısmi 597 sonrası)
   @DRY_RUN=1 sayim; 0=apply
   ============================================================================= */
USE energy;
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET IMPLICIT_TRANSACTIONS OFF;

DECLARE @DRY_RUN BIT = 1;
DECLARE @DryRunInt INT = CAST(@DRY_RUN AS INT);
DECLARE @N INT;
DECLARE @Msg NVARCHAR(400);

RAISERROR('20d LOADED↔MAP heal DRY_RUN=%d', 0, 1, @DryRunInt) WITH NOWAIT;

IF OBJECT_ID('dbo.MIG_597_STG_PAY', 'U') IS NULL
   OR OBJECT_ID('dbo.MIG_OV_ID_MAP', 'U') IS NULL
BEGIN
    RAISERROR('MIG_597_STG_PAY / MIG_OV_ID_MAP yok', 16, 1);
    RETURN;
END

/* orphan: STG LOADED=0 ama MAP ENERGY_LREF dolu */
SELECT @N = COUNT(*)
FROM dbo.MIG_597_STG_PAY p WITH (NOLOCK)
INNER JOIN dbo.MIG_OV_ID_MAP m WITH (NOLOCK)
    ON m.OV_KIND = N'PAY_PT' AND m.SRC_KEY = p.SRC_KEY
WHERE p.LOADED = 0
  AND m.ENERGY_LREF IS NOT NULL
OPTION (MAXDOP 8);
SET @Msg = N'STG LOADED=0 + MAP ENERGY_LREF=' + CAST(@N AS VARCHAR(20));
RAISERROR('%s', 0, 1, @Msg) WITH NOWAIT;

/* adopt aday: STG LOADED=0 + PT LREF = hint / map key */
SELECT @N = COUNT(*)
FROM dbo.MIG_597_STG_PAY p WITH (NOLOCK)
INNER JOIN dbo.LS_005_01_PAYTRANS pt WITH (NOLOCK)
    ON pt.LREF = p.LREF_HINT
WHERE p.LOADED = 0
  AND p.USE_HINT = 1
  AND p.LREF_HINT IS NOT NULL
  AND NOT EXISTS (
        SELECT 1 FROM dbo.MIG_OV_ID_MAP m WITH (NOLOCK)
        WHERE m.OV_KIND = N'PAY_PT' AND m.SRC_KEY = p.SRC_KEY AND m.ENERGY_LREF IS NOT NULL
      )
OPTION (MAXDOP 8);
SET @Msg = N'STG hint orphan (PT var, MAP yok)=' + CAST(@N AS VARCHAR(20));
RAISERROR('%s', 0, 1, @Msg) WITH NOWAIT;

IF @DRY_RUN = 1
BEGIN
    RAISERROR('DRY_RUN=1 — APPLY icin @DRY_RUN=0', 0, 1) WITH NOWAIT;
    RETURN;
END

/* LOADED NCIX off — buyuk keyset UPDATE */
IF EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.MIG_597_STG_PAY')
      AND name = N'IX_MIG_597_STG_PAY_LOAD'
      AND is_disabled = 0
)
    ALTER INDEX IX_MIG_597_STG_PAY_LOAD ON dbo.MIG_597_STG_PAY DISABLE;

IF EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.MIG_597_STG_PAY')
      AND name = N'IX_MIG_597_STG_PAY_HINT'
      AND is_disabled = 0
)
    ALTER INDEX IX_MIG_597_STG_PAY_HINT ON dbo.MIG_597_STG_PAY DISABLE;

UPDATE p
SET p.LOADED = 1
FROM dbo.MIG_597_STG_PAY p
INNER JOIN dbo.MIG_OV_ID_MAP m
    ON m.OV_KIND = N'PAY_PT' AND m.SRC_KEY = p.SRC_KEY
WHERE p.LOADED = 0
  AND m.ENERGY_LREF IS NOT NULL
OPTION (MAXDOP 8);
SET @N = @@ROWCOUNT;
SET @Msg = N'LOADED=1 from MAP rows=' + CAST(@N AS VARCHAR(20));
RAISERROR('%s', 0, 1, @Msg) WITH NOWAIT;

/* adopt: sadece tahsilat PT (IOCODE<>0) — borç LREF adopt YASAK (R15) */
UPDATE m
SET m.ENERGY_LREF = p.LREF_HINT
FROM dbo.MIG_OV_ID_MAP m
INNER JOIN dbo.MIG_597_STG_PAY p ON p.SRC_KEY = m.SRC_KEY
INNER JOIN dbo.LS_005_01_PAYTRANS pt ON pt.LREF = p.LREF_HINT
WHERE m.OV_KIND = N'PAY_PT'
  AND m.ENERGY_LREF IS NULL
  AND p.LOADED = 0
  AND p.USE_HINT = 1
  AND p.LREF_HINT IS NOT NULL
  AND pt.IOCODE <> 0
OPTION (MAXDOP 8);

INSERT INTO dbo.MIG_OV_ID_MAP (
    OV_KIND, SRC_KEY, LREF_HINT, PARENT_SRC_KEY, REF_MAIN_LREF,
    ABYS_AGREEMENT_ID, ABYS_ACCOUNT_ID, ABYS_ID_BUSINESS, ENERGY_LREF
)
SELECT
    N'PAY_PT', p.SRC_KEY, CAST(p.LREF_HINT AS BIGINT), NULL, NULL,
    p.ABYS_AGREEMENT_ID, p.ABYS_ACCOUNT_ID, p.ABYS_ID, p.LREF_HINT
FROM dbo.MIG_597_STG_PAY p
INNER JOIN dbo.LS_005_01_PAYTRANS pt ON pt.LREF = p.LREF_HINT
WHERE p.LOADED = 0
  AND p.USE_HINT = 1
  AND p.LREF_HINT IS NOT NULL
  AND pt.IOCODE <> 0
  AND NOT EXISTS (
        SELECT 1 FROM dbo.MIG_OV_ID_MAP m
        WHERE m.SRC_KEY = p.SRC_KEY
      )
OPTION (MAXDOP 8);

UPDATE p
SET p.LOADED = 1
FROM dbo.MIG_597_STG_PAY p
INNER JOIN dbo.MIG_OV_ID_MAP m
    ON m.OV_KIND = N'PAY_PT' AND m.SRC_KEY = p.SRC_KEY
WHERE p.LOADED = 0
  AND m.ENERGY_LREF IS NOT NULL
OPTION (MAXDOP 8);
SET @N = @@ROWCOUNT;
SET @Msg = N'LOADED=1 after adopt rows=' + CAST(@N AS VARCHAR(20));
RAISERROR('%s', 0, 1, @Msg) WITH NOWAIT;

IF EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.MIG_597_STG_PAY')
      AND name = N'IX_MIG_597_STG_PAY_LOAD'
      AND is_disabled = 1
)
    ALTER INDEX IX_MIG_597_STG_PAY_LOAD ON dbo.MIG_597_STG_PAY REBUILD WITH (MAXDOP = 8, SORT_IN_TEMPDB = ON);

IF EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.MIG_597_STG_PAY')
      AND name = N'IX_MIG_597_STG_PAY_HINT'
      AND is_disabled = 1
)
    ALTER INDEX IX_MIG_597_STG_PAY_HINT ON dbo.MIG_597_STG_PAY REBUILD WITH (MAXDOP = 8, SORT_IN_TEMPDB = ON);

RAISERROR('20d DONE — sonra SP_MIG_597_GATE', 0, 1) WITH NOWAIT;
GO

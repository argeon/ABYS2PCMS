-- ------------------------------------------------------------
-- ABYS banka ID → PCMS LS_BANK.LREF (AGR_CLOSE / BNK_TALIMAT)
-- ------------------------------------------------------------
CREATE OR ALTER FUNCTION dbo.FN_MIG_RESOLVE_BANK_LREF (@AbysBankId INT)
RETURNS INT
AS
BEGIN
    IF @AbysBankId IS NULL
        RETURN NULL;

    RETURN (
        SELECT TOP (1) b.LREF
        FROM energy.dbo.LS_BANK b
        WHERE b.ABYS_ID = @AbysBankId
        ORDER BY b.LREF
    );
END

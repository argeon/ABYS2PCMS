IF OBJECT_ID('dbo.LS_INSTALLMENT_PLAN', 'U') IS NOT NULL
AND COL_LENGTH('dbo.LS_INSTALLMENT_PLAN', 'INSTALLMENT_ID') IS NOT NULL
AND NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.LS_INSTALLMENT_PLAN') AND name = 'IX_MIG_LS_IPP_INSTALLMENT_ID'
)
BEGIN
    PRINT 'CREATE IX_MIG_LS_IPP_INSTALLMENT_ID ...';

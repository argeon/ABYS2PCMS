    PRINT 'CREATE IX_MIG_OV_MAHSUP_CLOSED_MAIN ...';
    CREATE NONCLUSTERED INDEX IX_MIG_OV_MAHSUP_CLOSED_MAIN
        ON dbo.LS_OV_MAHSUP_CLOSED (MAIN_LREF)
        INCLUDE (ABYS_AGREEMENT_ID, EXPLAIN_MARK)
        WITH (MAXDOP = 8, ONLINE = ON, SORT_IN_TEMPDB = ON);
    PRINT 'OK IX_MIG_OV_MAHSUP_CLOSED_MAIN';
END
ELSE
    PRINT 'SKIP IX_MIG_OV_MAHSUP_CLOSED_MAIN (exists)';
GO

IF OBJECT_ID('dbo.LS_OV_IADE_PAYTRANS', 'U') IS NOT NULL
AND COL_LENGTH('dbo.LS_OV_IADE_PAYTRANS', 'ABYS_ID') IS NOT NULL
AND NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.LS_OV_IADE_PAYTRANS') AND name = 'IX_MIG_OV_IADE_PT_ABYS'
)
BEGIN
    PRINT 'CREATE IX_MIG_OV_IADE_PT_ABYS ...';
    CREATE NONCLUSTERED INDEX IX_MIG_OV_IADE_PT_ABYS
        ON dbo.LS_OV_IADE_PAYTRANS (ABYS_ID)
        INCLUDE (SRC_KEY, ABYS_AGREEMENT_ID, LREF_HINT)
        WHERE ABYS_ID IS NOT NULL
        WITH (MAXDOP = 8, ONLINE = ON, SORT_IN_TEMPDB = ON);
    PRINT 'OK IX_MIG_OV_IADE_PT_ABYS';
END
ELSE
    PRINT 'SKIP IX_MIG_OV_IADE_PT_ABYS (exists)';
GO

IF OBJECT_ID('dbo.LS_OV_IADE_INVLINES', 'U') IS NOT NULL
AND COL_LENGTH('dbo.LS_OV_IADE_INVLINES', 'SRC_KEY') IS NOT NULL
AND NOT EXISTS (
    SELECT 1 FROM sys.indexes

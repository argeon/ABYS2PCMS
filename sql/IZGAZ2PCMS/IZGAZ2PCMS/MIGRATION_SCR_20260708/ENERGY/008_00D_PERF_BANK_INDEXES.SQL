        ON dbo.LS_OV_IADE_INVLINES (SRC_KEY)
        INCLUDE (INVOICE_SRC_KEY, ABYS_AGREEMENT_ID)
        WITH (MAXDOP = 8, ONLINE = ON, SORT_IN_TEMPDB = ON);

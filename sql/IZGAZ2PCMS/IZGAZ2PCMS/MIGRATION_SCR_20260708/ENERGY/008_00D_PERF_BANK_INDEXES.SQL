/* =============================================================================
   prodREADY_ENERGY3007 / 00d_perf_bank_indexes.sql
   597/35 bank resolve hiz — kritik MGR + ENERGY indexleri.

   Neden:
     - LS_PAYMENT (64M) join PAY_LREF → index yoktu (scan)
     - LS_OV_TAH_INVOICE (66M) ABYS_ID index yoktu; OR join felaket
     - MIG_OV_ID_MAP AGR filtre cover yoktu

   Calistir: sqlcmd -S ... -d izgazMGR -I -i 00d_perf_bank_indexes.sql
   (ENERGY MAP index icin energy context asagida)
   ============================================================================= */
SET NOCOUNT ON;
SET QUOTED_IDENTIFIER ON;

USE izgazMGR;
GO

PRINT CONVERT(VARCHAR(30), SYSDATETIME(), 121) + ' | 00d PERF IX START (izgazMGR)';

/* PAY_LREF: WIRE/35 tahsilat bank join anahtari — UNIQUE (1:1) */
IF OBJECT_ID('dbo.LS_PAYMENT', 'U') IS NOT NULL
AND NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.LS_PAYMENT') AND name = 'UX_MIG_LS_PAYMENT_PAY_LREF'
)
BEGIN
    PRINT 'CREATE UX_MIG_LS_PAYMENT_PAY_LREF ...';
    CREATE UNIQUE NONCLUSTERED INDEX UX_MIG_LS_PAYMENT_PAY_LREF
        ON dbo.LS_PAYMENT (PAY_LREF)
        INCLUDE (BANKA_ID, SOZLESME, CANCELED)
        WITH (MAXDOP = 8, ONLINE = ON, SORT_IN_TEMPDB = ON);
    PRINT 'OK UX_MIG_LS_PAYMENT_PAY_LREF';
END
ELSE
    PRINT 'SKIP UX_MIG_LS_PAYMENT_PAY_LREF (exists)';
GO

/* TAH ABYS_ID: LREF join yedegi — OR join YASAK, ayri seek */
IF OBJECT_ID('dbo.LS_OV_TAH_INVOICE', 'U') IS NOT NULL
AND NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.LS_OV_TAH_INVOICE') AND name = 'IX_MIG_LS_OV_TAH_INVOICE_ABYS'
)
BEGIN
    PRINT 'CREATE IX_MIG_LS_OV_TAH_INVOICE_ABYS ...';
    CREATE NONCLUSTERED INDEX IX_MIG_LS_OV_TAH_INVOICE_ABYS
        ON dbo.LS_OV_TAH_INVOICE (ABYS_ID)
        INCLUDE (LREF, BANKREF, ABYS_AGREEMENT_ID)
        WHERE ABYS_ID IS NOT NULL
        WITH (MAXDOP = 8, ONLINE = ON, SORT_IN_TEMPDB = ON);
    PRINT 'OK IX_MIG_LS_OV_TAH_INVOICE_ABYS';
END
ELSE
    PRINT 'SKIP IX_MIG_LS_OV_TAH_INVOICE_ABYS (exists)';
GO

/* ---- Overlay FULL: MAHSUP / IADE / IPP ---- */
IF OBJECT_ID('dbo.LS_OV_MAHSUP_CLOSED', 'U') IS NOT NULL
AND NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.LS_OV_MAHSUP_CLOSED') AND name = 'IX_MIG_OV_MAHSUP_CLOSED_MAIN'
)

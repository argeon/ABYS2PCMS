FROM sys.tables t
JOIN sys.columns c ON c.object_id = t.object_id
JOIN sys.types ty ON c.user_type_id = ty.user_type_id
WHERE t.name IN (
    'LS_OV_ID_MAP','LS_OV_PAY_PT','LS_OV_TAH_INVOICE','LS_OV_CANCEL_PAY','LS_OV_CANCEL_REV',

   Grain: ACCOUNT_ID = INVOICE.ABYS_ACCOUNT_ID (= CS_ACCOUNT.ID = AFL.FATURAID)
   Onkosul: LS_005_01_INVOICE + INVLINES + PAYTRANS yuklu
            izgazMGR.LS_AFL_OPEN_DEBT (opsiyonel; yoksa AFL_* NULL)
   Kolonlar: Oracle O59 + AFL LEFT JOIN check kolonlari
   Esleme:
     M3/KWH/CONSUMPTION ← INV.ABYS_*
     GAZ/SKB/KDV/TOPLAM ← INVLINES ABYS_AMOUNT_RAW * ABYS_STATUS
                          (939 / 7658 / 169)
     ODENEN             ← -SUM(borc PT.PAID)
     KALAN              ← TOPLAM + ODENEN
     AFL_*              ← LS_AFL_OPEN_DEBT LEFT ON FATURAID = ACCOUNT_ID
   Sonraki: 94_tuketim_tutar_frk.sql (izgazMGR dump vs bu tablo)
   ============================================================ */

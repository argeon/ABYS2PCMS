SET NOCOUNT ON;
PRINT '==== INVOICE ====';
SELECT LREF, ABYS_AGREEMENT_ID, INSTALLMENT_PLAN_REF, ABYS_INSTALLMENT_ID,
       CONVERT(DECIMAL(18,2),PAYABLETOTAL) PAYABLE, CLOSED, CANCELED
FROM energy.dbo.LS_005_01_INVOICE WITH (NOLOCK) WHERE LREF=150404069;

PRINT '==== PAYTRANS inv/pay ====';
SELECT LREF, INVOICEREF, IOCODE, INST_NR, PAYTYPE,
       CONVERT(DECIMAL(18,2),PAYABLETOTAL) PAYABLE,
       CONVERT(DECIMAL(18,2),PAID) PAID, CANCELED, CROSSREF, EXPLAIN
FROM energy.dbo.LS_005_01_PAYTRANS WITH (NOLOCK)
WHERE INVOICEREF IN (150404069,150690265) OR LREF IN (150404069,150690265)
ORDER BY CASE WHEN LREF IN (150404069,150690265) THEN 0 ELSE 1 END, IOCODE, INST_NR, LREF;

PRINT '==== 1653 AGR 5727 ====';
SELECT LREF, INVOICEREF, IOCODE, INST_NR,
       CONVERT(DECIMAL(18,2),PAYABLETOTAL) P, CONVERT(DECIMAL(18,2),PAID) PAID,
       CANCELED, CROSSREF, EXPLAIN
FROM energy.dbo.LS_005_01_PAYTRANS WITH (NOLOCK)
WHERE ABYS_AGREEMENT_ID=5727
  AND ABS(CONVERT(DECIMAL(18,2),ISNULL(PAYABLETOTAL,0))-1653)<0.05
ORDER BY IOCODE, LREF;

PRINT '==== OV PAY ====';
SELECT LREF, CROSSREF_MAIN_LREF, OV_KIND, CONVERT(DECIMAL(18,2),PAYABLETOTAL) P, CANCELED
FROM izgazMGR.dbo.LS_OV_PAY_PT WITH (NOLOCK)
WHERE TRY_CAST(LREF AS BIGINT) IN (150690265,150404069)
   OR TRY_CAST(CROSSREF_MAIN_LREF AS BIGINT)=150404069;

PRINT '==== OV DEBT cols ====';
SELECT TOP 5 * FROM izgazMGR.dbo.LS_OV_DEBT_PAID_UPD WITH (NOLOCK)
WHERE TRY_CAST(MAIN_LREF AS BIGINT)=150404069 OR TRY_CAST(LREF AS BIGINT)=150404069;
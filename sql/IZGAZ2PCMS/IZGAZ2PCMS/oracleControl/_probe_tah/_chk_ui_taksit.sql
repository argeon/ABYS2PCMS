SET NOCOUNT ON;
PRINT '==== search 413.25 taksit PT ====';
SELECT TOP 30 pt.LREF, pt.INVOICEREF, pt.ABYS_AGREEMENT_ID, pt.INST_NR, pt.PAYTYPE,
       CONVERT(DECIMAL(18,2),pt.PAYABLETOTAL) PAYABLE, CONVERT(DECIMAL(18,2),pt.PAID) PAID,
       pt.CANCELED, pt.EXPLAIN
FROM energy.dbo.LS_005_01_PAYTRANS pt WITH (NOLOCK)
WHERE ISNULL(pt.IOCODE,0)=0 AND ISNULL(pt.INST_NR,0)>0
  AND ABS(CONVERT(DECIMAL(18,2),pt.PAYABLETOTAL)-413.25)<0.02
ORDER BY pt.INVOICEREF, pt.INST_NR;


-- 09. STG_PAYTRANS_INCOME [R20] — tahsilat income'un TAMAMI (filtre yok) +SRC_ACCRUE_TYPE
CREATE TABLE STG_PAYTRANS_INCOME NOLOGGING AS
SELECT I.ID LREF, P.LREF PAYTRANSREF,
       ROW_NUMBER() OVER (PARTITION BY P.LREF ORDER BY I.ID) LINENR,
       NVL((SELECT V.LREF FROM STG_INVOICE V WHERE V.SOURCE_ORACLE_ACTION_ID=P.CROSSREF AND ROWNUM=1),P.CROSSREF) DEBT_INVOICEREF,
       P.CROSSREF DEBT_PAYTRANSREF, ABS(I.AMOUNT) INCOME_AMOUNT,
       I.INCOME_ID SRC_INCOME_ID, P.SRC_ACCRUE_TYPE, I.ID SOURCE_ORACLE_INCOME_ID,
       P.SOURCE_ORACLE_ACCOUNT_ID, P.SOURCE_ORACLE_ACTION_ID
  FROM STG_PAYTRANS P JOIN SMS.CS_ACCOUNT_INCOME I ON I.ACCOUNT_ACTION_ID=P.SOURCE_ORACLE_ACTION_ID
 WHERE P.PT_KIND='PAYMENT';
CREATE INDEX IX_STG_PI ON STG_PAYTRANS_INCOME (PAYTRANSREF);
CREATE INDEX IX_STG_PI_SRC ON STG_PAYTRANS_INCOME (SOURCE_ORACLE_INCOME_ID);

UPDATE STG_PAYTRANS D SET D.PAID=NVL((SELECT SUM(C.PAYABLETOTAL) FROM STG_PAYTRANS C
    WHERE C.PT_KIND='PAYMENT' AND C.IOCODE=1 AND C.CROSSREF=D.LREF),0) WHERE D.PT_KIND='ACCRUE'; COMMIT;
UPDATE STG_INVOICE V SET V.CLOSED=1 WHERE V.INV_KIND IN ('MAIN','GECIKME','ARTTIRAN')
   AND EXISTS (SELECT 1 FROM STG_PAYTRANS P WHERE P.INVOICEREF=V.LREF AND P.PT_KIND='ACCRUE'
                AND P.PAID>=P.PAYABLETOTAL-0.01 AND P.PAYABLETOTAL>0); COMMIT;

INSERT INTO MIG_SKIPPED SELECT 'CANCEL_SINIFI',X.ACCOUNT_ID,X.ID,X.ACTION_TYPE_ID,'CANCEL_*'
  FROM STG_PILOT_ACC A JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID
  JOIN STG_ACTION_MAP M ON M.ACTION_TYPE_ID=X.ACTION_TYPE_ID
 WHERE M.ACTION_CLASS IN (4,8) AND A.ACCRUE_TYPE_ID<>14;
COMMIT;

-- 10. STG_ADVANCE_LEDGER (accrue=14 hesap -> TÜM income LEDGER) [R16][R20]
CREATE TABLE STG_ADVANCE_LEDGER NOLOGGING AS
SELECT X.ID LREF, A.REGISTER_ID SRC_REGISTER_ID, A.AGREEMENT_ID SRC_AGREEMENT_ID, A.ACCRUE_TYPE_ID SRC_ACCRUE_TYPE,
       CASE WHEN X.ACTION_TYPE_ID IN (20,48,36,39,44) THEN 1 ELSE 2 END DIRECTION,
       SUM(ABS(I.AMOUNT)) AMOUNT, SUM(I.AMOUNT*M.STATUS) STATUS_NET,

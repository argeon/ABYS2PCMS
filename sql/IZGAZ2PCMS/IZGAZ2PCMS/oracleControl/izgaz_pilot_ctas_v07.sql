-- 02. STG_PILOT_ACC — AGREEMENT-CLOSURE [R13]
CREATE TABLE STG_PILOT_ACC NOLOGGING AS
SELECT A.ID, A.REGISTER_ID, A.AGREEMENT_ID, A.ACCRUE_TYPE_ID, A.PERIOD,
       A.TOTAL_DEBT, A.TOTAL_CREDIT,
       CASE WHEN EXISTS (SELECT 1 FROM SMS.CS_ACCOUNT_ACTION X
                          WHERE X.ACCOUNT_ID=A.ID AND X.ACTION_TYPE_ID=1) THEN 'A' ELSE 'B' END SINIF
  FROM SMS.CS_ACCOUNT A
 WHERE A.AGREEMENT_ID IN (
        SELECT DISTINCT A2.AGREEMENT_ID FROM SMS.CS_ACCOUNT A2
         WHERE NOT EXISTS (SELECT 1 FROM MIG_PARAM)
            OR A2.REGISTER_ID IN (SELECT REG_ID FROM MIG_PARAM));
CREATE UNIQUE INDEX IX_STG_PACC ON STG_PILOT_ACC (ID);
CREATE INDEX IX_STG_PACC_AGR ON STG_PILOT_ACC (AGREEMENT_ID);

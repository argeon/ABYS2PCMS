-- 11. STG_MAHSUP_POOL [R14] — sözleşme-içi FIFO (kümülatif aralık kesişimi)
CREATE TABLE STG_MAHSUP_POOL NOLOGGING AS
SELECT M.AGREEMENT_ID, M.MAH_ACC SOURCE_ORACLE_ACCOUNT_ID, M.MAH_ACTION SOURCE_ORACLE_ACTION_ID,
       M.ACCRUE_TYPE_ID MAH_ACCRUE_TYPE, M.TUT MAHSUP_TUTAR,
       B.DEBT_ACC TARGET_ACCOUNT_ID, B.DEBT_ACTION TARGET_DEBT_ACTION_ID, B.DEBT_PT TARGET_DEBT_PT,
       (LEAST(B.KUM,M.KUM)-GREATEST(B.KUM_PREV,M.KUM_PREV)) PAY_APPLIED, 'ESLESTI' DURUM
  FROM (SELECT A.AGREEMENT_ID, X.ACCOUNT_ID MAH_ACC, X.ID MAH_ACTION, A.ACCRUE_TYPE_ID, MI.TUT,
               SUM(MI.TUT) OVER (PARTITION BY A.AGREEMENT_ID ORDER BY X.ACTION_DATE,X.ID) KUM,
               SUM(MI.TUT) OVER (PARTITION BY A.AGREEMENT_ID ORDER BY X.ACTION_DATE,X.ID)-MI.TUT KUM_PREV
          FROM STG_PILOT_ACC A JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID AND X.ACTION_TYPE_ID=12
          JOIN (SELECT ACCOUNT_ACTION_ID,SUM(ABS(AMOUNT)) TUT FROM SMS.CS_ACCOUNT_INCOME GROUP BY ACCOUNT_ACTION_ID) MI
            ON MI.ACCOUNT_ACTION_ID=X.ID) M
  JOIN (SELECT A.AGREEMENT_ID, P.SOURCE_ORACLE_ACCOUNT_ID DEBT_ACC, P.SOURCE_ORACLE_ACTION_ID DEBT_ACTION,
               P.LREF DEBT_PT,
               SUM(P.PAYABLETOTAL) OVER (PARTITION BY A.AGREEMENT_ID ORDER BY P.DATE_,P.LREF) KUM,
               SUM(P.PAYABLETOTAL) OVER (PARTITION BY A.AGREEMENT_ID ORDER BY P.DATE_,P.LREF)-P.PAYABLETOTAL KUM_PREV
          FROM STG_PAYTRANS P JOIN STG_PILOT_ACC A ON A.ID=P.SOURCE_ORACLE_ACCOUNT_ID
         WHERE P.PT_KIND='ACCRUE' AND P.PAYABLETOTAL>0) B ON B.AGREEMENT_ID=M.AGREEMENT_ID
 WHERE (LEAST(B.KUM,M.KUM)-GREATEST(B.KUM_PREV,M.KUM_PREV)) > 0.01;
INSERT INTO STG_MAHSUP_POOL
SELECT A.AGREEMENT_ID, X.ACCOUNT_ID, X.ID, A.ACCRUE_TYPE_ID,
       (SELECT SUM(ABS(AMOUNT)) FROM SMS.CS_ACCOUNT_INCOME WHERE ACCOUNT_ACTION_ID=X.ID),
       NULL,NULL,NULL,
       (SELECT SUM(ABS(AMOUNT)) FROM SMS.CS_ACCOUNT_INCOME WHERE ACCOUNT_ACTION_ID=X.ID)
        - NVL((SELECT SUM(PAY_APPLIED) FROM STG_MAHSUP_POOL P WHERE P.SOURCE_ORACLE_ACTION_ID=X.ID),0),
       CASE WHEN NVL((SELECT SUM(PAY_APPLIED) FROM STG_MAHSUP_POOL P WHERE P.SOURCE_ORACLE_ACTION_ID=X.ID),0)=0
            THEN 'HEDEF_YOK' ELSE 'ARTAN_IADE' END
  FROM STG_PILOT_ACC A JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID AND X.ACTION_TYPE_ID=12
 WHERE (SELECT SUM(ABS(AMOUNT)) FROM SMS.CS_ACCOUNT_INCOME WHERE ACCOUNT_ACTION_ID=X.ID)
       - NVL((SELECT SUM(PAY_APPLIED) FROM STG_MAHSUP_POOL P WHERE P.SOURCE_ORACLE_ACTION_ID=X.ID),0) > 0.01;
COMMIT;
CREATE INDEX IX_MAHPOOL_SRC ON STG_MAHSUP_POOL (SOURCE_ORACLE_ACTION_ID);


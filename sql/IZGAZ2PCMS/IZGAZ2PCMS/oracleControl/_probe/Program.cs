static async Task RunDiagnostics(string connStr)
{
    await using var conn = new OracleConnection(connStr);
    await conn.OpenAsync();

    var queries = new (string Label, string Sql)[]
    {
        ("R0 RECON SUMMARY", @"
            SELECT SEVERITY, KATEGORI, COUNT(*) SATIR,
                   SUM(NVL(FARK, NVL(KAYNAK_NET, STAGING_NET))) TUTAR
              FROM SMS_AUDIT.STG_RECON_DIFF
             WHERE IGNORED = 0
             GROUP BY SEVERITY, KATEGORI
             ORDER BY DECODE(SEVERITY,'CRITICAL',1,'WARN',2,'INFO',3), SATIR DESC"),
        ("R1 CRITICAL DETAIL", @"
            SELECT AGREEMENT_ID, KATEGORI, KAYNAK_NET, STAGING_NET, FARK, SEBEP
              FROM SMS_AUDIT.STG_RECON_DIFF
             WHERE SEVERITY = 'CRITICAL' AND IGNORED = 0
             ORDER BY AGREEMENT_ID, KATEGORI"),
        ("PAID_OVERFLOW DETAIL", @"
            SELECT R.AGREEMENT_ID, R.SOURCE_ORACLE_ACCOUNT_ID, R.SUSPECT_ACTION_IDS BORC_PT,
                   R.KAYNAK_NET PAYABLE, R.STAGING_NET PAID, R.FARK
              FROM SMS_AUDIT.STG_RECON_DIFF R
             WHERE R.KATEGORI = 'PAID_OVERFLOW' AND R.IGNORED = 0"),
        ("R2 YAPISAL BUTUNLUK", @"
            SELECT DESTINATION, COUNT(*) SATIR, SUM(SRC_AMOUNT) TUTAR
              FROM SMS_AUDIT.STG_INCOME_COVERAGE
             GROUP BY DESTINATION"),
        ("DEBT ODEME_ADET>1", @"
            SELECT A.AGREEMENT_ID, P.SOURCE_ORACLE_ACCOUNT_ID, P.LREF BORC_PT,
                   P.PAYABLETOTAL, P.PAID, P.PAYABLETOTAL - P.PAID FARK,
                   (SELECT COUNT(*) FROM SMS_AUDIT.STG_PAYTRANS C
                     WHERE C.CROSSREF = P.LREF AND C.PT_KIND = 'PAYMENT') ODEME_ADET
              FROM SMS_AUDIT.STG_PAYTRANS P
              JOIN SMS_AUDIT.STG_PILOT_ACC A ON A.ID = P.SOURCE_ORACLE_ACCOUNT_ID
             WHERE P.PT_KIND = 'ACCRUE' AND ABS(P.PAYABLETOTAL - P.PAID) > 0.01

                      JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID = A.ID
                      JOIN SMS.CS_ACCOUNT_INCOME I ON I.ACCOUNT_ACTION_ID = X.ID) V
              FROM DUAL")
    };


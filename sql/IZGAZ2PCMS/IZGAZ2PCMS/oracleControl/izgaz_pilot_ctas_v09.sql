-- 04c. STG_EKSILTEN_CLASS [R1]
CREATE TABLE STG_EKSILTEN_CLASS NOLOGGING AS
SELECT E.ID ACTION_ID, E.ACCOUNT_ID, E.ACTION_DATE, EKS.TUT EKS, NVL(TAH.TUT,0) TAH,
       CASE WHEN EKS.TUT > NVL(TAH.TUT,0)+0.01 THEN 'ASIM'
            WHEN EKS.TUT >= NVL(TAH.TUT,0)*0.995 THEN 'TAM' ELSE 'KISMI' END KIND
  FROM STG_PILOT_ACC A
  JOIN SMS.CS_ACCOUNT_ACTION E ON E.ACCOUNT_ID=A.ID AND E.ACTION_TYPE_ID=2
  JOIN (SELECT ACCOUNT_ACTION_ID,SUM(ABS(AMOUNT)) TUT FROM SMS.CS_ACCOUNT_INCOME GROUP BY ACCOUNT_ACTION_ID) EKS
    ON EKS.ACCOUNT_ACTION_ID=E.ID
  LEFT JOIN (SELECT X.ACCOUNT_ID,SUM(ABS(I.AMOUNT)) TUT FROM SMS.CS_ACCOUNT_ACTION X
               JOIN SMS.CS_ACCOUNT_INCOME I ON I.ACCOUNT_ACTION_ID=X.ID
              WHERE X.ACTION_TYPE_ID=1 GROUP BY X.ACCOUNT_ID) TAH ON TAH.ACCOUNT_ID=E.ACCOUNT_ID
 WHERE A.SINIF='A';
CREATE INDEX IX_EKS_ACC ON STG_EKSILTEN_CLASS (ACCOUNT_ID, KIND);
CREATE INDEX IX_EKS_ACT ON STG_EKSILTEN_CLASS (ACTION_ID);
INSERT INTO MIG_SKIPPED SELECT 'EKS_TAH_ASIMI',ACCOUNT_ID,ACTION_ID,2,
  'EKS>TAH' FROM STG_EKSILTEN_CLASS WHERE KIND='ASIM';
COMMIT;

-- 05. STG_INVLINES [R20][R30][R35][R38] — ABYS Tahakkuk Gelir: AI.STATUS*AI.AMOUNT
CREATE TABLE STG_INVLINES NOLOGGING AS
SELECT I.ID LREF,
       CASE WHEN X.ACTION_TYPE_ID=1 THEN A.ID ELSE 500000000+X.ID END INVOICEREF,
       CASE WHEN NVL(I.IS_DISCOUNT,0)=1 THEN 103 ELSE 119 END LINE_TYPE,
       CASE WHEN NVL(I.IS_DISCOUNT,0)=1 AND I.INCOME_ID=939 THEN 807
            WHEN NVL(I.IS_DISCOUNT,0)=1 AND I.INCOME_ID=7658 THEN 808
            ELSE NVL(R.PCMS_TRANSTYPE, I.INCOME_ID) END TRANSTYPE,
       I.AMOUNT*I.STATUS AMOUNT,
       R.IS_VAT_INCOME, R.IS_DEPOSIT, R.IS_OVERDUE_INCOME, R.IS_LEGAL_FEE, NVL(I.IS_DISCOUNT,0) IS_DISCOUNT,
       A.ACCRUE_TYPE_ID SRC_ACCRUE_TYPE,
       I.INCOME_ID SRC_INCOME_ID, I.ID SOURCE_ORACLE_INCOME_ID,
       A.ID SOURCE_ORACLE_ACCOUNT_ID, X.ID SOURCE_ORACLE_ACTION_ID,
       0 CANCELED,
       CASE WHEN I.INCOME_ID=958 THEN 'SONRAKI AYA DEVIR'
            WHEN I.INCOME_ID=1929 THEN 'ONCEKI AYDAN DEVIR'
            WHEN NVL(I.IS_DISCOUNT,0)=1 AND I.INCOME_ID=939 THEN 'Gaz Bedeli Indirim'
            WHEN NVL(I.IS_DISCOUNT,0)=1 AND I.INCOME_ID=7658 THEN 'SKB Bedeli Indirim'
            ELSE NULL END LINEEXP
  FROM STG_PILOT_ACC A
  JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID AND X.ACTION_TYPE_ID IN (1,3,10,41)
  JOIN SMS.CS_ACCOUNT_INCOME I ON I.ACCOUNT_ACTION_ID=X.ID
  JOIN STG_INCOME_ROUTE R ON R.INCOME_ID=I.INCOME_ID
  JOIN STG_ACTION_MAP M ON M.ACTION_TYPE_ID=X.ACTION_TYPE_ID AND M.ACTION_CLASS IN (1,5)
 WHERE A.ACCRUE_TYPE_ID <> 14
   AND R.ACCRUAL_DEST = 'INVLINES'
UNION ALL
SELECT 1200000000+V.SOURCE_ORACLE_ACTION_ID, V.LREF, 101, 173, V.GRANDTOTAL,
       0,0,0,0,0, V.SRC_ACCRUE_TYPE, -1, 1200000000+V.SOURCE_ORACLE_ACTION_ID,
       V.SOURCE_ORACLE_ACCOUNT_ID, V.SOURCE_ORACLE_ACTION_ID, 0, NULL
  FROM (SELECT 1 LREF, 0 GRANDTOTAL, 0 SRC_ACCRUE_TYPE, 0 SOURCE_ORACLE_ACCOUNT_ID,
               0 SOURCE_ORACLE_ACTION_ID FROM DUAL WHERE 1=0) V;
CREATE INDEX IX_STG_IL ON STG_INVLINES (INVOICEREF);
CREATE INDEX IX_STG_IL_SRC ON STG_INVLINES (SOURCE_ORACLE_INCOME_ID);
ALTER TABLE STG_INVLINES MODIFY (LINEEXP VARCHAR2(100));

-- 06. STG_INVOICE [R22] — iskelet (accrual action'lar) + başlık INVLINES'tan türer + [R24][R25]
CREATE TABLE STG_INVOICE NOLOGGING AS
SELECT KEYS.LREF, KEYS.INV_KIND, KEYS.SOURCE_ORACLE_ACCOUNT_ID, KEYS.SOURCE_ORACLE_ACTION_ID,
       KEYS.SRC_REGISTER_ID, KEYS.SRC_AGREEMENT_ID, KEYS.SRC_ACCRUE_TYPE, KEYS.DATE_,
       KEYS.LEGAL_PROCEEDING_ID LAWDETAILREF,                       -- [R24]
       NVL(AGG.TL,0) TLTOTAL, NVL(AGG.VAT,0) TAX, NVL(AGG.TL,0)+NVL(AGG.VAT,0) GRANDTOTAL,
       NVL(AGG.TL,0)+NVL(AGG.VAT,0) PAYABLETOTAL,
       CASE WHEN AGG.HAS_GAZ=0 AND AGG.HAS_GUV>0 THEN 109
            WHEN KEYS.SRC_ACCRUE_TYPE=443 THEN 121 ELSE 119 END INV_TYPE,
       0 IOCODE, 0 CANCELED, 0 CLOSED,
       CAST(NULL AS NUMBER(12)) RETURN_SOURCE_INVREF, CAST(NULL AS NUMBER(12)) RETURN_TARGET_INVREF,
       CAST(NULL AS NUMBER(12)) INVOICECROSSREF,                    -- [R25]
       CAST(NULL AS NUMBER(12)) LINKED_SOURCE_INVREF
  FROM (
     SELECT A.ID LREF, 'MAIN' INV_KIND, A.ID SOURCE_ORACLE_ACCOUNT_ID, X.ID SOURCE_ORACLE_ACTION_ID,
            A.REGISTER_ID SRC_REGISTER_ID, A.AGREEMENT_ID SRC_AGREEMENT_ID, A.ACCRUE_TYPE_ID SRC_ACCRUE_TYPE,
            CASE WHEN EXTRACT(YEAR FROM X.ACTION_DATE)<1753 THEN ADD_MONTHS(X.ACTION_DATE,24000) ELSE X.ACTION_DATE END DATE_,
            X.LEGAL_PROCEEDING_ID
       FROM STG_PILOT_ACC A JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID AND X.ACTION_TYPE_ID=1
      WHERE A.ACCRUE_TYPE_ID<>14
     UNION ALL
     SELECT 500000000+X.ID, DECODE(X.ACTION_TYPE_ID,3,'ARTTIRAN','GECIKME'), A.ID, X.ID,
            A.REGISTER_ID, A.AGREEMENT_ID, A.ACCRUE_TYPE_ID,
            CASE WHEN EXTRACT(YEAR FROM X.ACTION_DATE)<1753 THEN ADD_MONTHS(X.ACTION_DATE,24000) ELSE X.ACTION_DATE END,
            X.LEGAL_PROCEEDING_ID
       FROM STG_PILOT_ACC A JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID AND X.ACTION_TYPE_ID IN (3,10,41)
      WHERE (A.ACCRUE_TYPE_ID<>14 OR A.ACCRUE_TYPE_ID IN (8,10))
  ) KEYS
  LEFT JOIN (
     SELECT INVOICEREF,
            SUM(CASE WHEN IS_VAT_INCOME=1 THEN 0 ELSE AMOUNT END) TL,
            SUM(CASE WHEN IS_VAT_INCOME=1 THEN AMOUNT ELSE 0 END) VAT,
            SUM(CASE WHEN TRANSTYPE IN (939,7658,807,808) THEN 1 ELSE 0 END) HAS_GAZ,
            SUM(CASE WHEN IS_DEPOSIT=1 THEN 1 ELSE 0 END) HAS_GUV
       FROM STG_INVLINES WHERE SRC_INCOME_ID<>-1 AND NVL(CANCELED,0)=0 GROUP BY INVOICEREF
  ) AGG ON AGG.INVOICEREF = KEYS.LREF;
CREATE UNIQUE INDEX IX_STG_INV ON STG_INVOICE (LREF);
CREATE INDEX IX_STG_INV_SRC ON STG_INVOICE (SOURCE_ORACLE_ACTION_ID);
CREATE INDEX IX_STG_INV_AGR ON STG_INVOICE (SRC_AGREEMENT_ID);
CREATE INDEX IX_STG_INV_KIND ON STG_INVOICE (INV_KIND);
ALTER TABLE STG_INVOICE ADD (
  FITNO NUMBER(12),
  CLIENTREF NUMBER(12),
  OWNERREF NUMBER(12),
  OWNERTYPE NUMBER(6) DEFAULT 91,
  EXPLAIN VARCHAR2(200)
);

-- 07. STG_SPEFEE [R23][R35] — devir 958/1929; INVLINEREF=INVLINES.LREF, INVOICEREF=fatura LREF
CREATE TABLE STG_SPEFEE NOLOGGING AS
SELECT I.ID LREF, 6 STYPE,
       CASE WHEN I.INCOME_ID=958 THEN 'SONRAKI AYA DEVIR' ELSE 'ONCEKI AYDAN DEVIR' END LINEEXP,
       CASE WHEN X.ACTION_TYPE_ID=1 THEN A.ID ELSE 500000000+X.ID END INVOICEREF,
       I.ID INVLINEREF,
       A.AGREEMENT_ID CLIENTREF, A.AGREEMENT_ID OWNERREF, 91 CLIENTTYPE,
       ABS(I.AMOUNT) TLTOTAL, 0 TAX, ABS(I.AMOUNT) GRANDTOTAL,
       0 CANCELLED, 2 STATUS,
       I.INCOME_ID SRC_INCOME_ID, A.ACCRUE_TYPE_ID SRC_ACCRUE_TYPE,
       A.ID SOURCE_ORACLE_ACCOUNT_ID, X.ID SOURCE_ORACLE_ACTION_ID, I.ID SOURCE_ORACLE_INCOME_ID
  FROM STG_PILOT_ACC A
  JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID AND X.ACTION_TYPE_ID IN (1,3,10,41)
  JOIN SMS.CS_ACCOUNT_INCOME I ON I.ACCOUNT_ACTION_ID=X.ID
 WHERE A.ACCRUE_TYPE_ID<>14 AND I.INCOME_ID IN (958,1929);
CREATE INDEX IX_STG_SP_SRC ON STG_SPEFEE (SOURCE_ORACLE_INCOME_ID);
CREATE INDEX IX_STG_SP_IL ON STG_SPEFEE (INVLINEREF);

-- 07b. STG_DEVIR_NET [R29] — tanı/doğrulama (fatura başlığına artık eklenmez; devir INVLINES'ta)
CREATE TABLE STG_DEVIR_NET NOLOGGING AS
SELECT X.ID SOURCE_ORACLE_ACTION_ID, A.ID SOURCE_ORACLE_ACCOUNT_ID,
       SUM(CASE WHEN I.INCOME_ID=958 THEN ABS(I.AMOUNT)
                WHEN I.INCOME_ID=1929 THEN -ABS(I.AMOUNT) ELSE 0 END) DEVIR_NET
  FROM STG_PILOT_ACC A
  JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID AND X.ACTION_TYPE_ID IN (1,3,10,41)
  JOIN SMS.CS_ACCOUNT_INCOME I ON I.ACCOUNT_ACTION_ID=X.ID AND I.INCOME_ID IN (958,1929)
 WHERE A.ACCRUE_TYPE_ID<>14
 GROUP BY X.ID, A.ID;
CREATE INDEX IX_STG_DEVIR_ACT ON STG_DEVIR_NET (SOURCE_ORACLE_ACTION_ID);


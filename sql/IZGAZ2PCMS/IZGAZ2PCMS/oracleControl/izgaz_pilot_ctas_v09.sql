-- 13. STG_INCOME_COVERAGE [R40] — hedef sayımı + beklenen dual-write istisnaları
-- Beklenen çift yazım (DUPLICATE DEĞİL):
--   958/1929 accrual: INVLINES + SPEFEE
--   tahsilat (ACT_CLASS=2): TAHSILAT INVLINES + PAYTRANS_INCOME  [R37]
CREATE TABLE STG_INCOME_COVERAGE NOLOGGING AS
SELECT S.SRC_INCOME_ID, S.SRC_ACTION_ID, S.SRC_ACCOUNT_ID, S.AGREEMENT_ID, S.ACCRUE_TYPE_ID,
       S.ACT_CLASS, S.INCOME_ID, S.SRC_AMOUNT,
       (SELECT COUNT(*) FROM STG_INVLINES IL WHERE IL.SOURCE_ORACLE_INCOME_ID=S.SRC_INCOME_ID AND IL.SRC_INCOME_ID<>-1) CNT_IL,
       (SELECT COUNT(*) FROM STG_PAYTRANS_INCOME PI WHERE PI.SOURCE_ORACLE_INCOME_ID=S.SRC_INCOME_ID) CNT_PI,
       (SELECT COUNT(*) FROM STG_SPEFEE SP WHERE SP.SOURCE_ORACLE_INCOME_ID=S.SRC_INCOME_ID) CNT_SP,
       (SELECT COUNT(*) FROM STG_ADV_LEDGER_INCOME LG WHERE LG.SOURCE_ORACLE_INCOME_ID=S.SRC_INCOME_ID) CNT_LG,
       (CASE WHEN EXISTS (SELECT 1 FROM STG_CANCEL_POOL CP WHERE CP.SOURCE_ORACLE_ACTION_ID=S.SRC_ACTION_ID)
             THEN (SELECT COUNT(*) FROM STG_CANCEL_POOL CP WHERE CP.SOURCE_ORACLE_ACTION_ID=S.SRC_ACTION_ID
                    AND NOT EXISTS (SELECT 1 FROM STG_INVLINES IL2 WHERE IL2.SOURCE_ORACLE_INCOME_ID=S.SRC_INCOME_ID))
             ELSE (SELECT COUNT(*) FROM MIG_SKIPPED SK WHERE SK.ACTION_ID=S.SRC_ACTION_ID) END) CNT_SKIP,
       0 TOTAL_TARGETS
  FROM (SELECT I.ID SRC_INCOME_ID, X.ID SRC_ACTION_ID, A.ID SRC_ACCOUNT_ID, A.AGREEMENT_ID,
               A.ACCRUE_TYPE_ID, M.ACTION_CLASS ACT_CLASS, I.INCOME_ID, ABS(I.AMOUNT) SRC_AMOUNT
          FROM STG_PILOT_ACC A JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID
          JOIN STG_ACTION_MAP M ON M.ACTION_TYPE_ID=X.ACTION_TYPE_ID
          JOIN SMS.CS_ACCOUNT_INCOME I ON I.ACCOUNT_ACTION_ID=X.ID) S;
UPDATE STG_INCOME_COVERAGE SET TOTAL_TARGETS = CNT_IL+CNT_PI+CNT_SP+CNT_LG+CNT_SKIP;
ALTER TABLE STG_INCOME_COVERAGE ADD (DESTINATION VARCHAR2(20));
UPDATE STG_INCOME_COVERAGE SET DESTINATION=
  CASE
       -- Devir dual-write: INVLINES + SPEFEE
       WHEN INCOME_ID IN (958,1929) AND CNT_IL=1 AND CNT_SP=1 AND CNT_PI=0 AND TOTAL_TARGETS=2 THEN 'OK'
       -- Tahsilat dual-write [R37]: TAHSILAT INVLINES + PAYTRANS_INCOME
       WHEN ACT_CLASS=2 AND CNT_IL=1 AND CNT_PI=1 AND CNT_SP=0 AND TOTAL_TARGETS=2 THEN 'OK'
       WHEN TOTAL_TARGETS=0 THEN 'LOST'
       WHEN TOTAL_TARGETS>1 THEN 'DUPLICATE'
       ELSE 'OK' END;
COMMIT;
CREATE INDEX IX_STG_COV ON STG_INCOME_COVERAGE (DESTINATION);


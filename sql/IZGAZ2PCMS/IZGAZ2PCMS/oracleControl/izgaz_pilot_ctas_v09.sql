-- ABYS: EMANET ÇIKIŞI.REF_DEPOSIT_ACCOUNT_ID = referans tahakkuk hesabı (ekranda "Referans Tahakkuk")
CREATE TABLE STG_MAHSUP_POOL NOLOGGING AS
SELECT A.AGREEMENT_ID, X.ACCOUNT_ID SOURCE_ORACLE_ACCOUNT_ID, X.ID SOURCE_ORACLE_ACTION_ID,
       A.ACCRUE_TYPE_ID MAH_ACCRUE_TYPE,
       NVL((SELECT SUM(ABS(AMOUNT)) FROM SMS.CS_ACCOUNT_INCOME WHERE ACCOUNT_ACTION_ID=X.ID),0) MAHSUP_TUTAR,
       D.SOURCE_ORACLE_ACCOUNT_ID TARGET_ACCOUNT_ID,
       D.SOURCE_ORACLE_ACTION_ID TARGET_DEBT_ACTION_ID,
       D.LREF TARGET_DEBT_PT,
       NVL((SELECT SUM(ABS(AMOUNT)) FROM SMS.CS_ACCOUNT_INCOME WHERE ACCOUNT_ACTION_ID=X.ID),0) PAY_APPLIED,
       CAST('ESLESTI' AS VARCHAR2(20)) DURUM
  FROM STG_PILOT_ACC A
  JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID AND X.ACTION_TYPE_ID=12
  JOIN STG_PAYTRANS D ON D.PT_KIND='ACCRUE' AND NVL(D.CANCELED,0)=0
   AND (
         (X.REF_DEPOSIT_ACCOUNT_ACTION_ID IS NOT NULL
          AND D.SOURCE_ORACLE_ACTION_ID=X.REF_DEPOSIT_ACCOUNT_ACTION_ID)
      OR (X.REF_DEPOSIT_ACCOUNT_ACTION_ID IS NULL
          AND X.REF_DEPOSIT_ACCOUNT_ID IS NOT NULL
          AND D.SOURCE_ORACLE_ACCOUNT_ID=X.REF_DEPOSIT_ACCOUNT_ID
          AND D.LREF = (
                SELECT MIN(P2.LREF) KEEP (DENSE_RANK FIRST ORDER BY P2.DATE_, P2.LREF)
                  FROM STG_PAYTRANS P2
                 WHERE P2.PT_KIND='ACCRUE' AND NVL(P2.CANCELED,0)=0
                   AND P2.SOURCE_ORACLE_ACCOUNT_ID=X.REF_DEPOSIT_ACCOUNT_ID))
       )
 WHERE A.ACCRUE_TYPE_ID<>14;


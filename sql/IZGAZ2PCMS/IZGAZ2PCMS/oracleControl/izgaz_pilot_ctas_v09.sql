                 JOIN STG_PAYTRANS P ON P.LREF=PI.PAYTRANSREF
                 JOIN STG_ACTION_MAP M ON M.ACTION_TYPE_ID=P.SRC_ACTION_TYPE
                 WHERE PI.SOURCE_ORACLE_ACCOUNT_ID=A.ID
                   AND (M.ACTION_CLASS=2 OR (P.SRC_ACTION_TYPE=4 AND EXISTS (
                         SELECT 1 FROM SMS.CS_ACCOUNT_INCOME I2
                          WHERE I2.ID=PI.SOURCE_ORACLE_INCOME_ID AND I2.STATUS=1)))),0) BALANCE
      FROM STG_PILOT_ACC A
     WHERE A.AGREEMENT_ID=(SELECT AGR_ID FROM MIG_PARAM WHERE ROWNUM=1)
  ) S ON S.ACCOUNT_ID=K.ACCOUNT_ID
 WHERE ABS(NVL(S.ACRUAL,0)-K.KAYNAK_ACRUAL)>0.01
    OR ABS(NVL(S.PAYED,0)-K.KAYNAK_PAYED)>0.01
    OR ABS(NVL(S.BALANCE,0)-K.KAYNAK_BALANCE)>0.01
 ORDER BY K.ACCOUNT_ID;

-- 08. STG_PAYTRANS  (a)borç PT (b)tahsilat class=2 (c)type-12 mahsup
-- [R41] CROSSREF/PAID: ödeme action'ı tahakkuk action ile ortak INCOME_ID paylaşıyorsa borca bağlanır
--        (tüm gelirler CS_INCOME_PRM'den; ortak gelir yoksa CROSSREF NULL, PAID sayılmaz)
CREATE TABLE STG_PAYTRANS NOLOGGING AS
SELECT V.SOURCE_ORACLE_ACTION_ID LREF, V.LREF INVOICEREF, V.INV_TYPE PT_TYPE, V.IOCODE,
       CAST(NULL AS NUMBER(12)) CROSSREF, CAST(NULL AS NUMBER(6)) PAYTYPE,
       CAST(NULL AS NUMBER(12)) INVLINEREF, 0 INST_NR, V.DATE_, V.PAYABLETOTAL, 0 PAID,
       0 CANCELED, 'ACCRUE' PT_KIND, CAST(NULL AS NUMBER(6)) SRC_ACTION_TYPE,
       V.SRC_ACCRUE_TYPE, V.SOURCE_ORACLE_ACCOUNT_ID, V.SOURCE_ORACLE_ACTION_ID,
       0 CANCELLATIONPAYMENT, CAST(NULL AS NUMBER(12)) INSTALLMENT_ID
  FROM STG_INVOICE V
 WHERE V.INV_KIND IN ('MAIN','GECIKME','ARTTIRAN')
UNION ALL
SELECT X.ID, 1000000000+X.ID, 101, M.IOCODE,
       (SELECT MIN(G.ID) KEEP (DENSE_RANK FIRST ORDER BY
                 CASE WHEN G.ACTION_DATE<=X.ACTION_DATE THEN 0 ELSE 1 END, G.ACTION_DATE DESC, G.ID DESC)
          FROM SMS.CS_ACCOUNT_ACTION G
         WHERE G.ACCOUNT_ID=A.ID AND G.ACTION_TYPE_ID IN (1,3,10,41)
           AND EXISTS (SELECT 1
                         FROM SMS.CS_ACCOUNT_INCOME PI
                         JOIN SMS.CS_ACCOUNT_INCOME AI ON AI.INCOME_ID=PI.INCOME_ID
                        WHERE PI.ACCOUNT_ACTION_ID=X.ID
                          AND AI.ACCOUNT_ACTION_ID=G.ID)) CROSSREF,
       CASE X.ACTION_TYPE_ID WHEN 4 THEN 32 WHEN 5 THEN 33 WHEN 6 THEN 10 ELSE 174 END,
       1200000000+X.ID, NVL(X.INSTALLMENT_ORDER_NUMBER,0),
       CASE WHEN EXTRACT(YEAR FROM X.ACTION_DATE)<1753 THEN ADD_MONTHS(X.ACTION_DATE,24000) ELSE X.ACTION_DATE END,
       (SELECT ABS(SUM(I.AMOUNT*I.STATUS))
          FROM SMS.CS_ACCOUNT_INCOME I
         WHERE I.ACCOUNT_ACTION_ID=X.ID),
       0,0,'PAYMENT', X.ACTION_TYPE_ID, A.ACCRUE_TYPE_ID, A.ID, X.ID,
       0, X.INSTALLMENT_ID
  FROM STG_PILOT_ACC A JOIN SMS.CS_ACCOUNT_ACTION X ON X.ACCOUNT_ID=A.ID
  JOIN STG_ACTION_MAP M ON M.ACTION_TYPE_ID=X.ACTION_TYPE_ID AND M.ACTION_CLASS=2
 WHERE A.ACCRUE_TYPE_ID<>14
UNION ALL
-- Type-12 seed CROSSREF: REF tahakkuk action (PT LREF=action id) [R39]
SELECT X.ID, 1000000000+X.ID, 101, 1,
       NVL(X.REF_DEPOSIT_ACCOUNT_ACTION_ID,

       AND X.REF_DEPOSIT_ACCOUNT_ACTION_ID IS NULL
       AND NOT EXISTS (SELECT 1 FROM STG_MAHSUP_POOL MP WHERE MP.SOURCE_ORACLE_ACTION_ID=X.ID AND MP.DURUM='ESLESTI')
  ) M
  JOIN (
    SELECT A.AGREEMENT_ID, P.SOURCE_ORACLE_ACCOUNT_ID DEBT_ACC, P.SOURCE_ORACLE_ACTION_ID DEBT_ACTION,
           P.LREF DEBT_PT,
           SUM(P.PAYABLETOTAL) OVER (PARTITION BY A.AGREEMENT_ID ORDER BY P.DATE_,P.LREF) KUM,

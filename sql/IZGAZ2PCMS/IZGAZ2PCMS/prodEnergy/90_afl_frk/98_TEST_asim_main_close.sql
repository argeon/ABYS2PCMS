     DELTA_TAH_NET (INV tutari) kalir; sadece PT kalan / CLOSED hizalanir.

   Mahsup / guvence (ayri bacak — bu script DEGIL):
     Ornek 412056: 778.90 emanet mahsup = 162+1936 (EMANET_MAHSUP_RULE.md);
     kalan iade TYPE110 = O60/E610 (GUVENCE_IADE_110_RULE.md).

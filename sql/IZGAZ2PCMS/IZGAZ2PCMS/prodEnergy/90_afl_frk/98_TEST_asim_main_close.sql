     + AFL.BALANCE ≈ 0
     + ABYS TTK TOPLAM_TAHAKKUK ≈ 0 (veya satir yok)
     + Energy hesabinda acik borc PT (kalan > eps)
     → tum uygun PT: PAID=PAYABLE; INV CLOSED=1

   Kapsamaz:

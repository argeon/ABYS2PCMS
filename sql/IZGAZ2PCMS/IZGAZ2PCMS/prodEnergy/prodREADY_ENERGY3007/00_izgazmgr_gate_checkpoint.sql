-- CTAS3007 dump sonrasi — ENERGY yukleme ONCESI hard gate (izgazMGR)
-- GATE_FAIL → DUR (ENERGY'ye gecme)
-- =============================================================================
USE izgazMGR;
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @Fail INT = 0;
DECLARE @Msg NVARCHAR(MAX) = N'';
DECLARE @N BIGINT;

PRINT '========== E3007-00 izgazMGR GATE START ==========';

/* ---- Checkpoint tablo ---- */
IF OBJECT_ID('dbo.CTAS_VALIDATION_CHECKPOINT', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.CTAS_VALIDATION_CHECKPOINT (
        CHECKPOINT_ID INT IDENTITY(1,1) PRIMARY KEY,
        TABLE_NAME VARCHAR(100) NOT NULL,
        CHECKPOINT_TIME DATETIME NOT NULL DEFAULT GETDATE(),
        PHASE VARCHAR(40) NOT NULL DEFAULT 'PRE_ENERGY',
        ROW_COUNT BIGINT NULL,
        MIN_LREF BIGINT NULL,
        MAX_LREF BIGINT NULL,
        SUM_AMT DECIMAL(22,2) NULL,
        NOTE NVARCHAR(400) NULL
    );
END
GO

DECLARE @Fail INT = 0;
DECLARE @Msg NVARCHAR(MAX) = N'';
DECLARE @N BIGINT;
DECLARE @MaxLref BIGINT;
DECLARE @HasCol INT;
DECLARE @sql NVARCHAR(MAX);
DECLARE @Warn NVARCHAR(MAX) = N'';

/* ---- Manifest tablolar ---- */
DECLARE @Need TABLE (T SYSNAME PRIMARY KEY);
INSERT INTO @Need(T) VALUES
 (N'LS_INVOICE'),(N'LS_INVLINES'),(N'LS_DEBT_PAYTRANS'),
 (N'LS_OV_PAY_ALLOC'),(N'LS_OV_PAY_PT'),(N'LS_OV_TAH_INVOICE'),
 (N'LS_OV_DEBT_PAID_UPD'),(N'LS_OV_ID_MAP'),
 (N'LS_AFL_OPEN_DEBT'),(N'LS_STG_INV_PAY_CLOSE'),
 (N'LS_PAYMENT'),(N'LS_TAKSIT'),(N'LS_INSTALLMENT_PLAN_PAY'),
 (N'LS_EKSILTEN'),(N'LS_PARTIAL_EKSILTEN'),(N'LS_MAHSUP');

DECLARE @t SYSNAME;
DECLARE c CURSOR LOCAL FAST_FORWARD FOR SELECT T FROM @Need;
OPEN c; FETCH NEXT FROM c INTO @t;
WHILE @@FETCH_STATUS = 0
BEGIN
    IF OBJECT_ID(N'dbo.' + @t, N'U') IS NULL
    BEGIN
        SET @Fail += 1;
        SET @Msg += N' MISSING:' + @t;
    END
    ELSE
    BEGIN
        SET @sql = N'SELECT @n = COUNT_BIG(*) FROM dbo.' + QUOTENAME(@t) + N' WITH (NOLOCK)';
        EXEC sp_executesql @sql, N'@n BIGINT OUTPUT', @n = @N OUTPUT;
        INSERT INTO dbo.CTAS_VALIDATION_CHECKPOINT (TABLE_NAME, PHASE, ROW_COUNT, NOTE)
        VALUES (@t, 'PRE_ENERGY', @N, N'manifest');
        IF @N = 0 AND @t IN (N'LS_INVOICE', N'LS_OV_PAY_PT', N'LS_AFL_OPEN_DEBT')
        BEGIN
            SET @Fail += 1;
            SET @Msg += N' EMPTY:' + @t;
        END
    END
    FETCH NEXT FROM c INTO @t;
END
CLOSE c; DEALLOCATE c;

/* ---- Soft: CS_INSTALLMENT(+PLAN) for 611/taksit ---- */
IF OBJECT_ID(N'dbo.CS_INSTALLMENT', N'U') IS NULL
    SET @Warn += N' WARN_MISSING:CS_INSTALLMENT';
IF OBJECT_ID(N'dbo.CS_INSTALLMENT_PLAN', N'U') IS NULL
    SET @Warn += N' WARN_MISSING:CS_INSTALLMENT_PLAN';

/* ---- Kolon kritikleri ---- */
DECLARE @Cols TABLE (T SYSNAME, C SYSNAME);
INSERT INTO @Cols(T,C) VALUES
 (N'LS_INVOICE',N'CLOSED'),(N'LS_INVOICE',N'LASTPAIDDATE'),
 (N'LS_INVOICE',N'BANKREF'),(N'LS_INVOICE',N'BANK_RECORD_REF'),
 (N'LS_INVOICE',N'ABYS_INSTALLMENT_ID'),(N'LS_INVOICE',N'INSTALLMENT_PLAN_REF'),
 (N'LS_INVOICE',N'XTYPE'),
 (N'LS_OV_PAY_PT',N'PAID'),(N'LS_OV_PAY_PT',N'BANKREF'),
 (N'LS_OV_PAY_PT',N'BANK_RECORD_REF'),(N'LS_OV_PAY_PT',N'LASTPAIDDATE'),
 (N'LS_OV_PAY_PT',N'XTYPE'),(N'LS_OV_PAY_PT',N'CROSSREF_MAIN_LREF'),
 (N'LS_DEBT_PAYTRANS',N'PAID'),(N'LS_DEBT_PAYTRANS',N'BANKREF'),
 (N'LS_DEBT_PAYTRANS',N'BANK_RECORD_REF'),(N'LS_DEBT_PAYTRANS',N'LASTPAIDDATE'),
 (N'LS_INSTALLMENT_PLAN_PAY',N'PAYMENT_DATE'),
 (N'LS_INSTALLMENT_PLAN_PAY',N'ORDER_NUMBER'),
 (N'LS_INSTALLMENT_PLAN_PAY',N'IS_PAID'),
 (N'LS_INSTALLMENT_PLAN_PAY',N'BANKREF'),
 (N'LS_INSTALLMENT_PLAN_PAY',N'BANK_RECORD_REF');

DECLARE @ct SYSNAME, @cc SYSNAME;
DECLARE c2 CURSOR LOCAL FAST_FORWARD FOR SELECT T,C FROM @Cols;
OPEN c2; FETCH NEXT FROM c2 INTO @ct, @cc;
WHILE @@FETCH_STATUS = 0
BEGIN
    SELECT @HasCol = COUNT(*)
      FROM sys.columns c
      JOIN sys.tables t ON t.object_id = c.object_id
      JOIN sys.schemas s ON s.schema_id = t.schema_id
     WHERE s.name = N'dbo' AND t.name = @ct AND c.name = @cc;
    IF @HasCol = 0 AND OBJECT_ID(N'dbo.' + @ct, N'U') IS NOT NULL
    BEGIN
        SET @Fail += 1;
        SET @Msg += N' COL:' + @ct + N'.' + @cc;
    END
    FETCH NEXT FROM c2 INTO @ct, @cc;
END
CLOSE c2; DEALLOCATE c2;

/* ---- LREF INT ---- */
IF OBJECT_ID('dbo.LS_INVOICE','U') IS NOT NULL
BEGIN
    SELECT @MaxLref = MAX(CAST(LREF AS BIGINT)), @N = COUNT_BIG(*)
      FROM dbo.LS_INVOICE WITH (NOLOCK);
    INSERT INTO dbo.CTAS_VALIDATION_CHECKPOINT (TABLE_NAME, PHASE, ROW_COUNT, MAX_LREF, NOTE)
    VALUES (N'LS_INVOICE', N'LREF_CHECK', @N, @MaxLref,
            CASE WHEN @MaxLref > 2147483647 THEN N'INT_OVERFLOW'
                 WHEN @MaxLref > 1500000000 THEN N'NEAR_LIMIT' ELSE N'OK' END);
    IF @MaxLref > 2147483647
    BEGIN
        SET @Fail += 1;
        SET @Msg += N' LREF_OVERFLOW=' + CAST(@MaxLref AS NVARCHAR(30));
    END
END

/* ---- PAY PAID gap (O34) ---- */
IF OBJECT_ID('dbo.LS_OV_PAY_PT','U') IS NOT NULL
   AND COL_LENGTH('dbo.LS_OV_PAY_PT','PAID') IS NOT NULL
BEGIN
    SELECT @N = COUNT_BIG(*)
      FROM dbo.LS_OV_PAY_PT WITH (NOLOCK)
     WHERE ISNULL(OV_KIND,'PAY') = 'PAY' AND ISNULL(CANCELED,0)=0
       AND ISNULL(PAID,0)+0.01 < ISNULL(PAYABLETOTAL,0)
       AND ISNULL(PAYABLETOTAL,0) > 0.01;
    INSERT INTO dbo.CTAS_VALIDATION_CHECKPOINT (TABLE_NAME, PHASE, ROW_COUNT, NOTE)
    VALUES (N'LS_OV_PAY_PT', N'PAY_PAID_GAP', @N, N'expect 0');
    IF @N > 0
    BEGIN
        SET @Fail += 1;
        SET @Msg += N' PAY_PAID_GAP=' + CAST(@N AS NVARCHAR(20));
    END

    SELECT @N = COUNT_BIG(*)
      FROM dbo.LS_OV_PAY_PT WITH (NOLOCK)
     WHERE ISNULL(OV_KIND,'PAY') = 'PAY' AND ISNULL(CANCELED,0)=0
       AND CROSSREF_MAIN_LREF IS NULL;
    IF @N > 0
    BEGIN
        SET @Fail += 1;
        SET @Msg += N' PAY_NO_XREF=' + CAST(@N AS NVARCHAR(20));
    END
END

/* ---- Invoice amount checkpoint ---- */
IF OBJECT_ID('dbo.LS_INVOICE','U') IS NOT NULL
BEGIN
    DECLARE @SumPay DECIMAL(22,2);
    SELECT @N = COUNT_BIG(*),
           @SumPay = SUM(CONVERT(DECIMAL(18,2), ISNULL(PAYABLETOTAL,0)))
      FROM dbo.LS_INVOICE WITH (NOLOCK)
     WHERE ISNULL(IOCODE,0)=0 AND ISNULL(CANCELED,0)=0;
    INSERT INTO dbo.CTAS_VALIDATION_CHECKPOINT (TABLE_NAME, PHASE, ROW_COUNT, SUM_AMT, NOTE)
    VALUES (N'LS_INVOICE', N'SUM_PAYABLE_IO0', @N, @SumPay, N'pre-energy PAYABLE');
END

IF OBJECT_ID('dbo.LS_DEBT_PAYTRANS','U') IS NOT NULL
   AND COL_LENGTH('dbo.LS_DEBT_PAYTRANS','PAID') IS NOT NULL
BEGIN
    DECLARE @SumDebtPaid DECIMAL(22,2);
    SELECT @N = COUNT_BIG(*),
           @SumDebtPaid = SUM(CONVERT(DECIMAL(18,2), ISNULL(PAID,0)))
      FROM dbo.LS_DEBT_PAYTRANS WITH (NOLOCK)
     WHERE ISNULL(IOCODE,0)=0 AND ISNULL(CANCELED,0)=0;
    INSERT INTO dbo.CTAS_VALIDATION_CHECKPOINT (TABLE_NAME, PHASE, ROW_COUNT, SUM_AMT, NOTE)
    VALUES (N'LS_DEBT_PAYTRANS', N'SUM_PAID', @N, @SumDebtPaid, N'pre-energy');
END

IF OBJECT_ID('dbo.LS_OV_PAY_PT','U') IS NOT NULL
   AND COL_LENGTH('dbo.LS_OV_PAY_PT','PAID') IS NOT NULL
BEGIN
    DECLARE @SumPayPt DECIMAL(22,2);
    SELECT @N = COUNT_BIG(*),
           @SumPayPt = SUM(CONVERT(DECIMAL(18,2), ISNULL(PAID,0)))
      FROM dbo.LS_OV_PAY_PT WITH (NOLOCK)
     WHERE ISNULL(OV_KIND,'PAY')='PAY' AND ISNULL(CANCELED,0)=0;
    INSERT INTO dbo.CTAS_VALIDATION_CHECKPOINT (TABLE_NAME, PHASE, ROW_COUNT, SUM_AMT, NOTE)
    VALUES (N'LS_OV_PAY_PT', N'SUM_PAID_PAY', @N, @SumPayPt, N'pre-energy');
END

IF @Fail > 0
BEGIN
    PRINT '========== E3007-00 GATE_FAIL ==========' + @Msg;
    RAISERROR('E3007-00 GATE_FAIL:%s', 16, 1, @Msg);
    RETURN;
END

IF LEN(@Warn) > 0
    PRINT '========== E3007-00 GATE_PASS (soft warns)' + @Warn + ' ==========';
ELSE
    PRINT '========== E3007-00 GATE_PASS — ENERGY setup serbest ==========';

SELECT TOP 50 * FROM dbo.CTAS_VALIDATION_CHECKPOINT
 ORDER BY CHECKPOINT_ID DESC;
GO
